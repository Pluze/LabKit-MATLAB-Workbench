function html = renderLabKitPage(model, title, outputPath, kind, body)
%RENDERLABKITPAGE Wrap rendered content in contextual site navigation.

    rootPrefix = siteRootPrefix(outputPath);
    styleUrl = rootPrefix + "assets/style.css";
    scriptUrl = rootPrefix + "assets/app.js";
    searchScriptUrl = rootPrefix + "assets/search-index.js";
    homeUrl = relativeWebPath(outputPath, "index.html");
    topNavigation = renderTopNavigation(model, outputPath);
    localNavigation = renderLocalNavigation(model, outputPath, title);
    pageOutline = renderPageOutline(body);
    mobileOutline = renderMobileOutline(body);
    breadcrumbs = renderBreadcrumbs(model, outputPath, title);
    shellClass = "shell";
    if strlength(localNavigation) == 0
        shellClass = shellClass + " shell-without-sidebar";
    end
    if strlength(pageOutline) == 0
        shellClass = shellClass + " shell-without-outline";
    end
    navigationButton = "";
    if strlength(localNavigation) > 0
        navigationButton = "<button class=""nav-toggle"" type=""button"" " + ...
            "aria-controls=""local-navigation"" aria-expanded=""false"">Contents</button>";
    end
    html = strjoin([ ...
        "<!doctype html>"
        "<!-- Generated by tools/docs/renderLabKitDocs.m. Do not edit. -->"
        "<html lang=""en"">"
        "<head>"
        "<meta charset=""utf-8"">"
        "<meta name=""viewport"" content=""width=device-width,initial-scale=1"">"
        "<meta name=""generator"" content=""LabKit MATLAB documentation compiler"">"
        "<title>" + htmlEscape(title) + " - " + htmlEscape(model.title) + "</title>"
        "<link rel=""stylesheet"" href=""" + styleUrl + """>"
        "</head>"
        "<body data-site-root=""" + rootPrefix + """>"
        "<header class=""topbar"">"
        "<div class=""topbar-inner"">"
        navigationButton
        "<a class=""brand"" href=""" + homeUrl + """>" + ...
            htmlEscape(model.title) + "</a>"
        "<div class=""search""><label class=""sr-only"" for=""doc-search-section"">Search section</label>" + ...
            "<select id=""doc-search-section""><option value=""all"">All documentation</option>" + ...
            "<option value=""use"">Use</option><option value=""develop"">Develop</option>" + ...
            "<option value=""reference"">Reference</option><option value=""changes"">Changes</option>" + ...
            "</select>" + ...
            "<label class=""sr-only"" for=""doc-search"">Search documentation</label>" + ...
            "<input id=""doc-search"" type=""search"" placeholder=""Search documentation"" autocomplete=""off"">" + ...
            "<div id=""search-results"" class=""search-results"" hidden></div></div>"
        "</div>"
        "</header>"
        "<nav class=""product-nav"" aria-label=""Documentation areas""><div class=""product-nav-inner"">" + ...
            topNavigation + "</div></nav>"
        "<div class=""" + shellClass + """>"
        conditionalAside(localNavigation, "local-navigation", "sidebar")
        "<main class=""content"" data-page-type=""" + htmlEscape(kind) + """>"
        breadcrumbs
        mobileOutline
        body
        renderFooter(model, outputPath)
        "</main>"
        conditionalAside(pageOutline, "page-outline", "page-outline")
        "</div>"
        "<script src=""" + searchScriptUrl + """></script>"
        "<script src=""" + scriptUrl + """></script>"
        "</body>"
        "</html>"], newline);
end

function html = renderTopNavigation(model, outputPath)
    primaryLabels = ["Use", "Develop", "Reference"];
    primaryTargets = ["use/index.html", "develop/index.html", ...
        "reference/index.html"];
    primarySections = ["use", "develop", "reference"];
    utilityLabels = "Changes";
    utilityTargets = "changes/index.html";
    utilitySections = "changes";
    current = navigationSection(model, outputPath);
    primary = navigationLinks(outputPath, primaryLabels, primaryTargets, ...
        primarySections, current);
    utility = navigationLinks(outputPath, utilityLabels, utilityTargets, ...
        utilitySections, current);
    html = "<div class=""primary-navigation"">" + primary + ...
        "</div><div class=""utility-navigation"">" + utility + "</div>";
end

function html = navigationLinks(outputPath, labels, targets, sections, current)
    links = strings(numel(labels), 1);
    for k = 1:numel(labels)
        className = "product-nav-link";
        if sections(k) == current
            className = className + " active";
        end
        links(k) = "<a class=""" + className + """ href=""" + ...
            relativeWebPath(outputPath, targets(k)) + """>" + ...
            htmlEscape(labels(k)) + "</a>";
    end
    html = strjoin(links, "");
end

function html = conditionalAside(content, id, className)
    if strlength(content) == 0
        html = "";
    else
        html = "<aside id=""" + id + """ class=""" + ...
            className + """>" + content + "</aside>";
    end
end

function html = renderLocalNavigation(model, outputPath, title)
    section = navigationSection(model, outputPath);
    if section == "home"
        html = "";
        return;
    end
    chunks = "<nav aria-label=""Current documentation"">" + ...
        "<p class=""sidebar-title"">" + htmlEscape(sectionTitle(section)) + "</p>";

    [landingTitle, landingTarget] = sectionLanding(section);
    if strlength(landingTarget) > 0 && outputPath ~= landingTarget
        chunks = chunks + "<a class=""context-parent"" href=""" + ...
            relativeWebPath(outputPath, landingTarget) + """>" + ...
            htmlEscape(landingTitle) + "</a>";
    end

    [ownerTitle, ownerTarget, apiItem] = apiOwner(model, outputPath);
    if isempty(apiItem)
        ancestors = renderContextAncestors( ...
            model.pages, outputPath, landingTarget);
        if strlength(ancestors) > 0
            chunks = chunks + "<div class=""context-path"" aria-label=""Page hierarchy"">" + ...
                ancestors + "</div>";
        end
    end
    if strlength(ownerTarget) > 0 && ownerTarget ~= outputPath
        chunks = chunks + "<a class=""context-parent"" href=""" + ...
            relativeWebPath(outputPath, ownerTarget) + """>" + ...
            htmlEscape(ownerTitle) + "</a>";
    end
    chunks = chunks + "<p class=""current-page"">" + ...
        htmlEscape(title) + "</p>";

    related = renderSectionLinks(model, outputPath, section, apiItem);
    if strlength(related) > 0
        chunks = chunks + "<section class=""local-group""><h2>In this section</h2>" + ...
            related + "</section>";
    end

    html = chunks + "</nav>";
end

function html = renderContextAncestors(pages, outputPath, landingTarget)
    folder = replace(string(fileparts(char(outputPath))), "\\", "/");
    parts = split(folder, "/");
    links = strings(numel(parts), 1);
    linkCount = 0;
    for k = 1:numel(parts)
        target = strjoin(parts(1:k), "/") + "/index.html";
        if target == outputPath || target == landingTarget
            continue;
        end
        index = find(string({pages.output}) == target, 1);
        if isempty(index)
            continue;
        end
        linkCount = linkCount + 1;
        links(linkCount, 1) = "<a class=""context-parent"" href=""" + ...
            relativeWebPath(outputPath, target) + """>" + ...
            htmlEscape(pages(index).title) + "</a>";
    end
    html = strjoin(links(1:linkCount), "");
end

function html = renderSectionLinks(model, outputPath, section, apiItem)
    if ~isempty(apiItem)
        html = renderSiblingApis(model.api, apiItem, outputPath);
        return;
    end

    pages = model.pages;
    currentIndex = find(string({pages.output}) == outputPath, 1);
    switch section
        case "use"
            html = renderUseNavigation(pages, currentIndex, outputPath);
        case "reference"
            matches = arrayfun(@(p) ~isempty(p.nav) && ...
                p.nav(1) == "Reference", pages);
            html = renderPageGroups(pages(matches), outputPath, ...
                "Reference", false);
        case "develop"
            matches = arrayfun(@(p) ~isempty(p.nav) && ...
                p.nav(1) == "Develop", pages);
            html = renderPageGroups(pages(matches), outputPath, ...
                "Develop", true);
        case "changes"
            html = renderChangeNavigation(outputPath);
        otherwise
            html = "";
    end
end

function html = renderUseNavigation(pages, currentIndex, outputPath)
    if startsWith(string(outputPath), "use/apps/")
        html = renderAppNavigation(pages, currentIndex, outputPath);
        return;
    end
    matches = arrayfun(@(page) startsWith(string(page.output), "use/") && ...
        (~startsWith(string(page.output), "use/apps/") || ...
        string(page.output) == "use/apps/index.html"), pages);
    html = renderPageGroups(pages(matches), outputPath, "Use", false);
end

function html = renderSiblingApis(api, item, outputPath)
    symbol = string(item.symbol);
    parts = split(symbol, ".");
    prefix = strjoin(parts(1:end - 1), ".") + ".";
    members = api(startsWith(string({api.symbol}), prefix));
    members(string({members.symbol}) == symbol) = [];
    links = strings(numel(members), 1);
    for k = 1:numel(members)
        target = apiOutputPath(members(k));
        nameParts = split(string(members(k).symbol), ".");
        links(k, 1) = localLink(outputPath, target, nameParts(end));
    end
    groupTitle = "Package Functions";
    if ~isempty(parts) && numel(parts) > 1
        groupTitle = parts(end - 1) + " Functions";
    end
    packagePrefix = strjoin(parts(1:end - 1), ".");
    if packagePrefix == "labkit.contract"
        groupTitle = "Framework Compatibility";
    elseif packagePrefix == "labkit.app"
        groupTitle = "App SDK Core API";
    elseif startsWith(packagePrefix, "labkit.app.")
        groupTitle = "App SDK " + titleCasePackage(parts(end - 1)) + " API";
    end
    html = localSubgroup(groupTitle, strjoin(links, ""));
end

function value = titleCasePackage(value)
    value = string(value);
    value = upper(extractBefore(value, 2)) + extractAfter(value, 1);
end

function html = renderAppNavigation(pages, currentIndex, outputPath)
    appMembers = pages(string({pages.kind}) == "app family" | ...
        string({pages.kind}) == "app");
    if string(outputPath) == "use/apps/index.html"
        families = appMembers(string({appMembers.kind}) == "app family");
        html = localSubgroup("App families", ...
            renderPageGroupLinks(families, outputPath, false));
        return;
    end
    families = unique(arrayfun(@appFamilyNavPart, appMembers), "stable");
    families(families == "") = [];
    if ~isempty(currentIndex) && numel(pages(currentIndex).nav) > 2
        families = pages(currentIndex).nav(3);
    end
    chunks = strings(numel(families), 1);
    chunkCount = 0;
    for k = 1:numel(families)
        family = families(k);
        members = appMembers(arrayfun( ...
            @(page) appFamilyNavPart(page) == family, appMembers));
        familyPage = members(string({members.kind}) == "app family");
        appPages = members(string({members.kind}) == "app");
        content = renderPageGroupLinks(appPages, outputPath, false);
        if strlength(content) > 0
            target = "";
            if ~isempty(familyPage) && familyPage(1).output ~= outputPath
                target = string(familyPage(1).output);
            end
            chunkCount = chunkCount + 1;
            chunks(chunkCount, 1) = ...
                localSubgroup(family, content, outputPath, target);
        end
    end
    html = strjoin(chunks(1:chunkCount), "");
end

function value = appFamilyNavPart(page)
    value = "";
    if numel(page.nav) > 2
        value = string(page.nav(3));
    end
end

function html = renderPageGroups(members, outputPath, defaultGroup, useNavGroup)
    if isempty(members)
        html = "";
        return;
    end
    if useNavGroup
        groupNames = arrayfun(@secondNavPart, members);
        groupNames(groupNames == "") = string(defaultGroup);
        groups = unique(groupNames, "stable");
        groupOrders = inf(size(groups));
        memberOrders = [members.order];
        for k = 1:numel(groups)
            groupOrders(k) = min(memberOrders(groupNames == groups(k)));
        end
        [~, groupOrder] = sort(groupOrders);
        groups = groups(groupOrder);
    else
        groupNames = repmat(string(defaultGroup), numel(members), 1);
        groups = string(defaultGroup);
    end
    chunks = strings(numel(groups), 1);
    chunkCount = 0;
    for k = 1:numel(groups)
        content = renderPageGroupLinks( ...
            members(groupNames == groups(k)), outputPath, true);
        if strlength(content) > 0
            chunkCount = chunkCount + 1;
            chunks(chunkCount, 1) = localSubgroup(groups(k), content);
        end
    end
    html = strjoin(chunks(1:chunkCount), "");
end

function html = renderPageGroupLinks(members, outputPath, indentChildren)
    members(string({members.output}) == string(outputPath)) = [];
    if isempty(members)
        html = "";
        return;
    end
    [~, memberOrder] = sort([members.order]);
    members = members(memberOrder);
    parentKinds = ["overview", "app family"];
    hasParent = any(ismember(string({members.kind}), parentKinds));
    links = strings(numel(members), 1);
    for k = 1:numel(members)
        className = "local-link";
        isParent = any(string(members(k).kind) == parentKinds);
        if indentChildren && hasParent && ~isParent
            className = className + " local-child-link";
        elseif isParent
            className = className + " local-parent-link";
        end
        links(k, 1) = localLinkWithClass( ...
            outputPath, members(k).output, members(k).title, className);
    end
    html = strjoin(links, "");
end

function value = secondNavPart(page)
    value = "";
    if numel(page.nav) > 1
        value = string(page.nav(2));
    end
end

function html = localSubgroup(title, content, currentPath, titleTarget)
    if strlength(content) == 0
        html = "";
        return;
    end
    heading = htmlEscape(title);
    if nargin >= 4 && strlength(titleTarget) > 0
        heading = "<a href=""" + ...
            relativeWebPath(currentPath, titleTarget) + """>" + ...
            heading + "</a>";
    end
    html = "<div class=""local-subgroup""><h3>" + ...
        heading + "</h3><div class=""local-branch"">" + ...
        content + "</div></div>";
end

function html = renderOnThisPage(body)
    tokens = regexp(char(body), '<h2 id="([^"]+)">(.+?)</h2>', ...
        'tokens');
    linkCount = min(numel(tokens), 24);
    links = strings(linkCount, 1);
    for k = 1:linkCount
        anchor = string(tokens{k}{1});
        label = regexprep(string(tokens{k}{2}), '<[^>]+>', '');
        label = decodeBasicEntities(label);
        links(k, 1) = "<a class=""toc-link"" href=""#" + ...
            htmlEscape(anchor) + """>" + htmlEscape(label) + "</a>";
    end
    html = strjoin(links, "");
end

function html = renderChangeNavigation(outputPath)
    targets = ["changes/components/index.html", "changes/years/index.html"];
    labels = ["By component", "By year"];
    links = strings(numel(targets), 1);
    for k = 1:numel(targets)
        if string(outputPath) == targets(k)
            continue;
        end
        links(k) = localLink(outputPath, targets(k), labels(k));
    end
    html = localSubgroup("Browse changes", ...
        strjoin(links(strlength(links) > 0), ""));
end

function html = renderPageOutline(body)
    links = renderOnThisPage(body);
    if strlength(links) == 0
        html = "";
    else
        html = "<nav aria-label=""On this page""><h2>On this page</h2>" + ...
            links + "</nav>";
    end
end

function html = renderMobileOutline(body)
    links = renderOnThisPage(body);
    if strlength(links) == 0
        html = "";
    else
        html = "<details class=""mobile-outline""><summary>On this page</summary>" + ...
            "<nav aria-label=""On this page"">" + links + "</nav></details>";
    end
end

function [title, target, item] = apiOwner(model, outputPath)
    title = "";
    target = "";
    item = [];
    paths = strings(numel(model.api), 1);
    for k = 1:numel(model.api)
        paths(k) = apiOutputPath(model.api(k));
    end
    apiIndex = find(paths == outputPath, 1);
    if isempty(apiIndex)
        return;
    end
    item = model.api(apiIndex);
    pages = model.pages;
    if string(item.origin) == "app"
        pageId = "app-" + replace(string(item.owner), "_", "-");
        pageIndex = find(string({pages.id}) == pageId, 1);
    else
        symbol = string(item.symbol);
        if startsWith(symbol, "labkit.app")
            pageIndex = find(string({pages.output}) == ...
                "develop/framework/app-sdk-api.html", 1);
            if ~isempty(pageIndex)
                title = string(pages(pageIndex).title);
                target = string(pages(pageIndex).output);
                return;
            end
        end
        pageIndex = [];
        best = -1;
        for k = 1:numel(pages)
            components = string(pages(k).components);
            for iComponent = 1:numel(components)
                component = components(iComponent);
                if startsWith(component, "labkit.") && ...
                        (symbol == component || startsWith(symbol, component + ".")) && ...
                        strlength(component) > best
                    pageIndex = k;
                    best = strlength(component);
                end
            end
        end
    end
    if ~isempty(pageIndex)
        title = string(pages(pageIndex).title);
        target = string(pages(pageIndex).output);
    end
end

function path = apiOutputPath(item)
    path = "reference/api/" + replace(string(item.symbol), ".", "/") + ...
        ".html";
end

function html = localLink(current, target, label)
    html = localLinkWithClass(current, target, label, "local-link");
end

function html = localLinkWithClass(current, target, label, className)
    currentAttribute = "";
    if string(current) == string(target)
        className = string(className) + " active";
        currentAttribute = " aria-current=""page""";
    end
    html = "<a class=""" + className + """ href=""" + ...
        relativeWebPath(current, target) + """" + currentAttribute + ">" + ...
        htmlEscape(label) + "</a>";
end

function [title, target] = sectionLanding(section)
    switch section
        case "use"
            title = "Use";
            target = "use/index.html";
        case "reference"
            title = "Reference";
            target = "reference/index.html";
        case "develop"
            title = "Develop";
            target = "develop/index.html";
        case "changes"
            title = "Changes";
            target = "changes/index.html";
        otherwise
            title = "";
            target = "";
    end
end

function section = navigationSection(~, outputPath)
    section = documentationSection(outputPath);
end

function section = documentationSection(outputPath)
    outputPath = string(outputPath);
    if startsWith(outputPath, "use/")
        section = "use";
    elseif startsWith(outputPath, "develop/")
        section = "develop";
    elseif startsWith(outputPath, "reference/")
        section = "reference";
    elseif startsWith(outputPath, "changes/")
        section = "changes";
    else
        section = "home";
    end
end

function title = sectionTitle(section)
    [title, ~] = sectionLanding(section);
    if strlength(title) == 0
        title = "Documentation";
    end
end

function html = renderBreadcrumbs(model, outputPath, title)
    if string(outputPath) == "index.html"
        html = "";
        return;
    end
    links = "<li><a href=""" + relativeWebPath(outputPath, "index.html") + ...
        """>Home</a></li>";
    seen = "index.html";
    section = navigationSection(model, outputPath);
    [sectionLabel, sectionTarget] = sectionLanding(section);
    if strlength(sectionTarget) > 0 && sectionTarget ~= outputPath
        links = links + breadcrumbLink(outputPath, sectionTarget, sectionLabel);
        seen(end + 1, 1) = sectionTarget;
    end

    [ownerTitle, ownerTarget, apiItem] = apiOwner(model, outputPath);
    if isempty(apiItem)
        ancestors = breadcrumbAncestors(model.pages, outputPath, seen);
        links = links + ancestors;
    elseif startsWith(ownerTarget, section + "/") && ...
            ~any(seen == ownerTarget) && ownerTarget ~= outputPath
        links = links + breadcrumbLink(outputPath, ownerTarget, ownerTitle);
    end
    links = links + "<li aria-current=""page"">" + htmlEscape(title) + "</li>";
    html = "<nav class=""breadcrumbs"" aria-label=""Breadcrumb""><ol>" + ...
        links + "</ol></nav>";
end

function html = breadcrumbAncestors(pages, outputPath, seen)
    folder = replace(string(fileparts(char(outputPath))), "\", "/");
    parts = split(folder, "/");
    html = "";
    for k = 1:numel(parts)
        target = strjoin(parts(1:k), "/") + "/index.html";
        if target == outputPath || any(seen == target)
            continue;
        end
        index = find(string({pages.output}) == target, 1);
        if ~isempty(index)
            html = html + breadcrumbLink(outputPath, target, pages(index).title);
        end
    end
end

function html = breadcrumbLink(outputPath, target, label)
    html = "<li><a href=""" + relativeWebPath(outputPath, target) + ...
        """>" + htmlEscape(label) + "</a></li>";
end

function html = renderFooter(model, outputPath)
    html = "<footer><nav aria-label=""Documentation utilities"">" + ...
        "<a href=""" + relativeWebPath(outputPath, "map/index.html") + ...
        """>All documentation</a><a href=""" + ...
        relativeWebPath(outputPath, "changes/index.html") + ...
        """>Changes</a><a href=""" + htmlEscape(model.repositoryUrl) + ...
        """>GitHub</a><a href=""" + htmlEscape(model.repositoryUrl) + ...
        "/blob/main/.github/SUPPORT.md"">Support</a></nav>" + ...
        "<p>Current guides are generated from tracked Markdown; API reference is generated from public MATLAB help.</p></footer>";
end

function value = decodeBasicEntities(value)
    value = replace(value, "&amp;", "&");
    value = replace(value, "&quot;", """");
    value = replace(value, "&lt;", "<");
    value = replace(value, "&gt;", ">");
end

function prefix = siteRootPrefix(outputPath)
    folder = replace(string(fileparts(char(outputPath))), "\", "/");
    if strlength(folder) == 0 || folder == "."
        prefix = "";
        return;
    end
    prefix = repmat("../", 1, numel(split(folder, "/")));
    prefix = strjoin(prefix, "");
end

function text = htmlEscape(text)
    text = replace(string(text), "&", "&amp;");
    text = replace(text, "<", "&lt;");
    text = replace(text, ">", "&gt;");
    text = replace(text, """", "&quot;");
end
