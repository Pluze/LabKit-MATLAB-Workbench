function html = renderLabKitPage(model, title, outputPath, kind, body)
%RENDERLABKITPAGE Wrap rendered content in contextual site navigation.

    rootPrefix = siteRootPrefix(outputPath);
    styleUrl = rootPrefix + "assets/style.css";
    scriptUrl = rootPrefix + "assets/app.js";
    searchScriptUrl = rootPrefix + "assets/search-index.js";
    homeUrl = relativeWebPath(outputPath, "index.html");
    topNavigation = renderTopNavigation(outputPath);
    localNavigation = renderLocalNavigation(model, outputPath, title, body);
    html = strjoin([ ...
        "<!doctype html>"
        "<!-- Generated by tools/docs/renderLabKitDocs.m. Do not edit. -->"
        "<html lang=""en"">"
        "<head>"
        "<meta charset=""utf-8"">"
        "<meta name=""viewport"" content=""width=device-width,initial-scale=1"">"
        "<meta name=""generator"" content=""LabKit MATLAB documentation compiler"">"
        "<title>" + htmlEscape(title) + " - " + htmlEscape(model.title) + "</title>"
        "<link rel=""stylesheet"" href=""" + styleUrl + """>"
        "</head>"
        "<body data-site-root=""" + rootPrefix + """>"
        "<header class=""topbar"">"
        "<div class=""topbar-inner"">"
        "<button class=""nav-toggle"" type=""button"" aria-controls=""local-navigation"" aria-expanded=""false"">Contents</button>"
        "<a class=""brand"" href=""" + homeUrl + """>" + ...
            htmlEscape(model.title) + "</a>"
        "<div class=""search""><label class=""sr-only"" for=""doc-search"">Search documentation</label>" + ...
            "<input id=""doc-search"" type=""search"" placeholder=""Search documentation"" autocomplete=""off"">" + ...
            "<div id=""search-results"" class=""search-results"" hidden></div></div>"
        "</div>"
        "</header>"
        "<nav class=""product-nav"" aria-label=""Documentation areas""><div class=""product-nav-inner"">" + ...
            topNavigation + "</div></nav>"
        "<div class=""shell"">"
        "<aside id=""local-navigation"" class=""sidebar"">" + ...
            localNavigation + "</aside>"
        "<main class=""content"">"
        "<p class=""page-kind"">" + htmlEscape(kind) + "</p>"
        body
        "<footer>Generated from tracked Markdown and MATLAB source contracts.</footer>"
        "</main>"
        "</div>"
        "<script src=""" + searchScriptUrl + """></script>"
        "<script src=""" + scriptUrl + """></script>"
        "</body>"
        "</html>"], newline);
end

function html = renderTopNavigation(outputPath)
    labels = ["Get Started", "Apps", "Functions", "Framework", ...
        "Development", "History"];
    targets = ["getting-started/index.html", "apps/index.html", ...
        "reference/index.html", "framework/index.html", ...
        "development/index.html", "history/index.html"];
    sections = ["getting-started", "apps", "functions", "framework", ...
        "development", "history"];
    current = documentationSection(outputPath);
    links = strings(numel(labels), 1);
    for k = 1:numel(labels)
        className = "product-nav-link";
        if sections(k) == current
            className = className + " active";
        end
        links(k) = "<a class=""" + className + """ href=""" + ...
            relativeWebPath(outputPath, targets(k)) + """>" + ...
            htmlEscape(labels(k)) + "</a>";
    end
    html = strjoin(links, "");
end

function html = renderLocalNavigation(model, outputPath, title, body)
    section = documentationSection(outputPath);
    chunks = "<nav aria-label=""Current documentation"">" + ...
        "<a class=""context-home"" href=""" + ...
        relativeWebPath(outputPath, "index.html") + """>Documentation Home</a>";

    [landingTitle, landingTarget] = sectionLanding(section);
    if strlength(landingTarget) > 0 && outputPath ~= landingTarget
        chunks = chunks + "<a class=""context-parent"" href=""" + ...
            relativeWebPath(outputPath, landingTarget) + """>" + ...
            htmlEscape(landingTitle) + "</a>";
    end

    [ownerTitle, ownerTarget, apiItem] = apiOwner(model, outputPath);
    if strlength(ownerTarget) > 0 && ownerTarget ~= outputPath
        chunks = chunks + "<a class=""context-parent"" href=""" + ...
            relativeWebPath(outputPath, ownerTarget) + """>" + ...
            htmlEscape(ownerTitle) + "</a>";
    end
    chunks = chunks + "<p class=""current-page"">" + ...
        htmlEscape(title) + "</p>";

    related = renderSectionLinks(model, outputPath, section, apiItem);
    if strlength(related) > 0
        chunks = chunks + "<section class=""local-group""><h2>In this section</h2>" + ...
            related + "</section>";
    end

    onPage = renderOnThisPage(body);
    if strlength(onPage) > 0
        chunks = chunks + "<section class=""local-group on-this-page""><h2>On this page</h2>" + ...
            onPage + "</section>";
    end
    html = chunks + "</nav>";
end

function html = renderSectionLinks(model, outputPath, section, apiItem)
    if ~isempty(apiItem)
        html = renderSiblingApis(model.api, apiItem, outputPath);
        return;
    end

    pages = model.pages;
    currentIndex = find(string({pages.output}) == outputPath, 1);
    matches = false(numel(pages), 1);
    switch section
        case "apps"
            if ~isempty(currentIndex) && numel(pages(currentIndex).nav) > 1
                family = pages(currentIndex).nav(2);
                matches = arrayfun(@(p) numel(p.nav) > 1 && ...
                    p.nav(1) == "Apps" && p.nav(2) == family, pages);
            else
                matches = string({pages.kind}) == "app family";
            end
        case "functions"
            matches = arrayfun(@(p) ~isempty(p.nav) && ...
                p.nav(1) == "Libraries", pages);
        case "framework"
            matches = arrayfun(@(p) ~isempty(p.nav) && ...
                p.nav(1) == "App Framework", pages);
        case "development"
            matches = arrayfun(@(p) ~isempty(p.nav) && ...
                p.nav(1) == "Development", pages);
        otherwise
            html = "";
            return;
    end
    members = pages(matches);
    links = strings(0, 1);
    for k = 1:numel(members)
        if members(k).output == outputPath
            continue;
        end
        links(end + 1, 1) = localLink(outputPath, members(k).output, ...
            members(k).title);
    end
    html = strjoin(links, "");
end

function html = renderSiblingApis(api, item, outputPath)
    symbol = string(item.symbol);
    parts = split(symbol, ".");
    prefix = strjoin(parts(1:end - 1), ".") + ".";
    members = api(startsWith(string({api.symbol}), prefix));
    links = strings(0, 1);
    for k = 1:numel(members)
        target = apiOutputPath(members(k));
        if target == outputPath
            continue;
        end
        nameParts = split(string(members(k).symbol), ".");
        links(end + 1, 1) = localLink(outputPath, target, nameParts(end));
    end
    html = strjoin(links, "");
end

function html = renderOnThisPage(body)
    tokens = regexp(char(body), '<h2 id="([^"]+)">(.+?)</h2>', ...
        'tokens');
    links = strings(0, 1);
    for k = 1:min(numel(tokens), 24)
        anchor = string(tokens{k}{1});
        label = regexprep(string(tokens{k}{2}), '<[^>]+>', '');
        label = decodeBasicEntities(label);
        links(end + 1, 1) = "<a class=""toc-link"" href=""#" + ...
            htmlEscape(anchor) + """>" + htmlEscape(label) + "</a>";
    end
    html = strjoin(links, "");
end

function [title, target, item] = apiOwner(model, outputPath)
    title = "";
    target = "";
    item = [];
    paths = strings(numel(model.api), 1);
    for k = 1:numel(model.api)
        paths(k) = apiOutputPath(model.api(k));
    end
    apiIndex = find(paths == outputPath, 1);
    if isempty(apiIndex)
        return;
    end
    item = model.api(apiIndex);
    pages = model.pages;
    if string(item.origin) == "app"
        pageId = "app-" + replace(string(item.owner), "_", "-");
        pageIndex = find(string({pages.id}) == pageId, 1);
    else
        symbol = string(item.symbol);
        pageIndex = [];
        best = -1;
        for k = 1:numel(pages)
            if string(pages(k).kind) == "history"
                continue;
            end
            components = string(pages(k).components);
            for iComponent = 1:numel(components)
                component = components(iComponent);
                if startsWith(component, "labkit.") && ...
                        (symbol == component || startsWith(symbol, component + ".")) && ...
                        strlength(component) > best
                    pageIndex = k;
                    best = strlength(component);
                end
            end
        end
    end
    if ~isempty(pageIndex)
        title = string(pages(pageIndex).title);
        target = string(pages(pageIndex).output);
    end
end

function path = apiOutputPath(item)
    path = "reference/api/" + replace(string(item.symbol), ".", "/") + ...
        ".html";
end

function html = localLink(current, target, label)
    html = "<a class=""local-link"" href=""" + ...
        relativeWebPath(current, target) + """>" + htmlEscape(label) + "</a>";
end

function [title, target] = sectionLanding(section)
    switch section
        case "getting-started"
            title = "Get Started";
            target = "getting-started/index.html";
        case "apps"
            title = "Apps";
            target = "apps/index.html";
        case "functions"
            title = "Functions";
            target = "reference/index.html";
        case "framework"
            title = "Framework";
            target = "framework/index.html";
        case "development"
            title = "Development";
            target = "development/index.html";
        case "history"
            title = "History";
            target = "history/index.html";
        otherwise
            title = "";
            target = "";
    end
end

function section = documentationSection(outputPath)
    outputPath = string(outputPath);
    if startsWith(outputPath, "getting-started/")
        section = "getting-started";
    elseif startsWith(outputPath, "apps/")
        section = "apps";
    elseif any(startsWith(outputPath, ["reference/", "libraries/"]))
        section = "functions";
    elseif startsWith(outputPath, "framework/")
        section = "framework";
    elseif startsWith(outputPath, "development/")
        section = "development";
    elseif startsWith(outputPath, "history/")
        section = "history";
    else
        section = "home";
    end
end

function value = decodeBasicEntities(value)
    value = replace(value, "&amp;", "&");
    value = replace(value, "&quot;", """");
    value = replace(value, "&lt;", "<");
    value = replace(value, "&gt;", ">");
end

function prefix = siteRootPrefix(outputPath)
    folder = replace(string(fileparts(char(outputPath))), "\", "/");
    if strlength(folder) == 0 || folder == "."
        prefix = "";
        return;
    end
    prefix = repmat("../", 1, numel(split(folder, "/")));
    prefix = strjoin(prefix, "");
end

function text = htmlEscape(text)
    text = replace(string(text), "&", "&amp;");
    text = replace(text, "<", "&lt;");
    text = replace(text, ">", "&gt;");
    text = replace(text, """", "&quot;");
end
