function count = countPublicFiles(folder)
    entries = dir(fullfile(folder, "*.m"));
    count = nnz(~startsWith(string({entries.name}), "."));
end

function scenario = emptyScenario()
    scenario = struct("name", "", "targetCount", 0, ...
        "operationCount", 0, "deterministic", false, ...
        "compileMedianSeconds", 0);
end

function root = defaultRepositoryRoot()
    root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
end

function root = validateRoot(root)
    [ok, attributes] = fileattrib(root);
    if ~ok || ~attributes.directory || ...
            ~isfile(fullfile(attributes.Name, "labkit_launcher.m"))
        error("LabKit:Migration:InvalidRoot", ...
            "Not a LabKit repository root: %s", root);
    end
    root = string(attributes.Name);
end

function writeEvidence(outputRoot, report)
    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    jsonPath = fullfile(outputRoot, "phase-1-prototype-evidence.json");
    writeText(jsonPath, string(jsonencode(report, PrettyPrint=true)) + newline);
    lines = [ ...
        "# Phase 1 representation prototype evidence"
        ""
        "| Representation | Public files | Deterministic Apps | Strict failures |"
        "| --- | ---: | ---: | ---: |"
        "| Sealed value classes | " + ...
            string(report.valueClass.publicPrototypeFileCount) + " | " + ...
            string(nnz([report.valueClass.scenarios.deterministic])) + ...
            "/3 | 5/5 |"
        "| Opaque function values | " + ...
            string(report.opaqueFunction.publicPrototypeFileCount) + " | " + ...
            string(nnz([report.opaqueFunction.scenarios.deterministic])) + ...
            "/3 | 5/5 |"
        ""
        "Decision: `" + report.decision + "`."
        ""
        report.decisionRationale
        ""
        "GUI-free compile medians (value/opaque, milliseconds): " + ...
            compileTimingText(report) + "."
        ""
        "Prototype-covered seam lines (current/value/opaque): " + ...
            string(report.seamComparison.currentDistinctSeamLines) + ...
            "/" + string(report.seamComparison. ...
                valuePrototypeCoveredSeamLines) + ...
            "/" + string(report.seamComparison. ...
                opaquePrototypeCoveredSeamLines) + "."
        ""
        "Opaque closure backing state visible through MATLAB `functions`: " + ...
            string(report.opaqueFunction. ...
                backingRepresentationVisibleThroughFunctions) + "."
        ""];
    writeText(fullfile(outputRoot, ...
        "phase-1-prototype-evidence.md"), strjoin(lines, newline));
end

function text = compileTimingText(report)
    valueTimes = 1000 * [report.valueClass.scenarios.compileMedianSeconds];
    opaqueTimes = 1000 * ...
        [report.opaqueFunction.scenarios.compileMedianSeconds];
    names = string({report.valueClass.scenarios.name});
    parts = strings(numel(names), 1);
    for k = 1:numel(names)
        parts(k) = names(k) + " " + compose("%.3f", valueTimes(k)) + ...
            "/" + compose("%.3f", opaqueTimes(k));
    end
    text = strjoin(parts, "; ");
end

function writeText(filepath, text)
    fid = fopen(filepath, "w", "n", "UTF-8");
    if fid < 0
        error("LabKit:Migration:WriteFailed", ...
            "Could not write migration evidence: %s", filepath);
    end
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, char(text), "char");
    clear cleanup
end
