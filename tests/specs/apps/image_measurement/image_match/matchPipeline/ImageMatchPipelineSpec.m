classdef ImageMatchPipelineSpec < matlab.unittest.TestCase
    %IMAGEMATCHPIPELINESPEC Guard match-history transitions.

    methods (Test, TestTags = {'Contract:presentation', 'Env:headless'})
        function undoRemovesOnlyTheNewestMatchStep(testCase)
            project = image_match.initialData();
            project.annotations.steps = [ ...
                image_match.analysisRun.makeStep( ...
                "White balance", 100, 100, 100); ...
                image_match.analysisRun.makeStep( ...
                "Tone only", 80, 90, 0)];
            context = labkittest.createCallbackContext( ...
                struct("log", @(varargin) []));
            state = struct("project", project, ...
                "session", image_match.createSession(project, context));

            state = image_match.matchPipeline.undo(state, context);

            testCase.verifyNumElements( ...
                state.project.annotations.steps, 1);
            testCase.verifyEqual( ...
                state.project.annotations.steps.matchMethod, "White balance");
        end
    end
end
