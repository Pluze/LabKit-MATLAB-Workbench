classdef SessionLoggingPrivacyContractSpec < matlab.unittest.TestCase
    %SESSIONLOGGINGPRIVACYCONTRACTSPEC Specify the bounded logging boundary.

    methods (Test, TestTags = {'Contract:source', 'Env:headless'})
        function passesOnlyBoundedSemanticDetailsToTheLoggingBackend(testCase)
            captured = cell(1, 7);
            context = labkit.app.internal.runtime.CallbackContextFactory.create( ...
                struct("log", @captureLog));
            context.log("info", "source.loaded", ...
                "Loaded selected sources.", Category="sourceFiles", ...
                Audience="developer", ...
                Attributes=struct("acceptedCount", 3, ...
                    "sourceAlias", "source-1"));

            testCase.verifyEqual(captured{3}, "Loaded selected sources.");
            testCase.verifyEqual(captured{6}.acceptedCount, 3);
            testCase.verifyEqual(captured{6}.sourceAlias, "source-1");

            testCase.verifyError(@() context.log("info", "source.loaded", ...
                "Loaded /synthetic/input.csv.", Category="sourceFiles"), ...
                "labkit:app:contract:UnsafeLogData");
            testCase.verifyError(@() context.log("info", "source.loaded", ...
                "Loaded selected sources.", Category="sourceFiles", ...
                Attributes=struct("values", [1 2 3])), ...
                "labkit:app:contract:UnsafeLogData");

            function captureLog(varargin)
                captured = varargin;
            end
        end
    end
end
