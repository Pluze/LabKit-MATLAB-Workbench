        function exactNiDmmPrivateAdapterIsTheOnlyProductionException(testCase)
            repositoryRoot = labkittest.setup();
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repositoryRoot, "tools", "codecheck")));
            root = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture).Folder;
            adapterFolder = fullfile(root, "+labkit", "+nidmm", "private");
            mkdir(adapterFolder);
            marker = "% Secondary-runtime facade boundary: user-installed NI .NET runtime.";
            availabilityCalls = repmat( ...
                "National" + "Instruments.Driver.Value;", 1, 3);
            writeText(fullfile(adapterFolder, "niDmmAvailability.m"), [ ...
                "function value = niDmmAvailability()", marker, ...
                "NET" + ".addAssembly('fixed');", availabilityCalls, ...
                "value = 1;", "end"]);
            backendCalls = repmat( ...
                "National" + "Instruments.Driver.Value;", 1, 12);
            writeText(fullfile(adapterFolder, "openNiDmmBackend.m"), [ ...
                "function value = openNiDmmBackend()", marker, ...
                backendCalls, "National" + "Instruments.Driver.Value;", ...
                "National" + "Instruments.Driver.Value;", ...
                "value = 1;", "end"]);
            discoveryCalls = repmat( ...
                "National" + "Instruments.Driver.Value;", 1, 3);
            writeText(fullfile(adapterFolder, "niDmmDiscovery.m"), [ ...
                "function value = niDmmDiscovery()", marker, ...
                "NET" + ".addAssembly('fixed');", discoveryCalls, ...
                "value = 1;", "end"]);
            report = runCodecheckReport(root, "OpenReport", false, ...
                "WriteArtifacts", false);
            testCase.verifyEqual(report.runtimeViolationCount, 0, ...
                strjoin(report.runtimeViolations, newline));

            writeText(fullfile(root, "appDirectCall.m"), [ ...
                "function appDirectCall()", ...
                "National" + "Instruments.Driver.Value;", "end"]);
            report = runCodecheckReport(root, "OpenReport", false, ...
                "WriteArtifacts", false);
            testCase.verifyEqual(report.runtimeViolationCount, 1);
            testCase.verifySubstring(report.runtimeViolations, "[ni-dotnet]");
        end

        function scanScopeIgnoresAmbientPrivateAppRoots(testCase)
            repositoryRoot = labkittest.setup();
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repositoryRoot, "tools", "codecheck")));
            fixtureRoot = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture).Folder;
            scanRoot = fullfile(fixtureRoot, "public");
            privateRoot = fullfile(fixtureRoot, "external-private");
            mkdir(scanRoot);
            mkdir(fullfile(privateRoot, "apps"));
            writeText(fullfile(scanRoot, "publicProbe.m"), ...
                ["function value = publicProbe()", "value = 1;", "end"]);
            writeText(fullfile(privateRoot, "apps", "privateProbe.m"), ...
                ["function value = privateProbe()", "value = 2;", "end"]);
            previousRoots = getenv("LABKIT_PRIVATE_APP_ROOTS");
            cleanup = onCleanup(@() setenv( ...
                "LABKIT_PRIVATE_APP_ROOTS", previousRoots));
            setenv("LABKIT_PRIVATE_APP_ROOTS", privateRoot);

            report = runCodecheckReport(scanRoot, ...
                "OpenReport", false, "WriteArtifacts", false);

            testCase.verifyEqual(report.fileCount, 1);
            clear cleanup
        end
