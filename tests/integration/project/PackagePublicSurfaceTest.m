classdef PackagePublicSurfaceTest < matlab.unittest.TestCase
    %PACKAGEPUBLICSURFACETEST Verify LabKit behavior through official MATLAB tests.

    methods (Test, TestTags = {'Integration', 'Style'})
        function test_package_public_surface(testCase)
            setupLabKitTestPath();
            verify_package_public_surface();
        end
    end
end

function verify_package_public_surface()
%TEST_PACKAGE_PUBLIC_SURFACE Verify public and private package file surfaces.

    root = testRepoRoot();
    h = architectureTestHelpers();

    assert(exist(fullfile(root, '+labkit', '+app'), 'dir') ~= 7, ...
        'Reusable +labkit should not keep the transitional +app package.');
    assert(exist(fullfile(root, '+labkit', '+plot'), 'dir') ~= 7, ...
        'Reusable +labkit should not keep a plot package for app-specific plotting.');
    h.assertNoPackageMFiles(fullfile(root, '+labkit', '+analysis'), ...
        'Public reusable +labkit analysis');
    h.assertNoPackageMFiles(fullfile(root, '+labkit', '+data'), ...
        'Public reusable +labkit data');
    h.assertNoPackageMFiles(fullfile(root, '+labkit', '+io'), ...
        'Public reusable +labkit IO');
    h.assertNoPackageMFiles(fullfile(root, '+labkit', '+util'), ...
        'Reusable +labkit utility');

    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+ui'), {}, ...
        'Layered +labkit UI root');
    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+ui', '+app'), ...
        {'create.m', 'dispatchRequest.m', 'runBusy.m'}, ...
        'UI app facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+ui', '+app', 'private'), ...
        {'addRowResizeHandle.m', 'attachColumnResize.m', ...
        'buildControl.m', 'buildControlTabs.m', 'buildSection.m', ...
        'buildShellFromSpec.m', 'buildWorkspace.m', ...
        'createTabbedWorkbenchShell.m', 'enableAxesPopout.m', ...
        'popoutAxes.m', 'semanticEvent.m', 'validateAppSpec.m'}, ...
        'UI app private implementation');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+ui', '+diag'), ...
        {'createContext.m'}, ...
        'UI diagnostics facade');
    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+ui', '+view'), ...
        {'appendLog.m', 'clearAxes.m', 'drawImage.m', 'getValue.m', ...
        'resetAxes.m', 'setEnabled.m', 'setListItems.m', ...
        'setListSelection.m', 'setValue.m'}, ...
        'UI view facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+ui', '+view', 'private'), ...
        {'appendLog.m', 'clearAxes.m', 'controlAxes.m', ...
        'controlHandles.m', 'controlValueHandle.m', 'enablePopout.m', ...
        'popoutAxes.m', 'resolveControl.m', 'refreshListboxItems.m', ...
        'refreshListboxSelection.m', 'resetAxes.m', 'showImage.m'}, ...
        'UI view private implementation');
    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+ui', '+spec'), ...
        {'action.m', 'actionGroup.m', 'app.m', 'custom.m', 'field.m', ...
        'logPanel.m', 'pathPanel.m', 'previewArea.m', 'rangeField.m', ...
        'resultTable.m', 'section.m', 'statusPanel.m', 'tab.m', ...
        'workspace.m'}, ...
        'UI 2.0 spec facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+ui', '+spec', 'private'), ...
        {'makeSpec.m', 'optionStruct.m', 'specChildren.m'}, ...
        'UI 2.0 spec private implementation');
    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+ui', '+tool'), ...
        {'anchorEditor.m', 'createRuntime.m', 'scaleBar.m', ...
        'scaleBarCalibration.m'}, ...
        'UI tool facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+ui', '+tool', 'private'), ...
        {'addOrInsertAnchor.m', 'anchorCurvePoints.m', ...
        'createLabeledDropdown.m', 'createLabeledEditField.m', ...
        'createLabeledSpinner.m', 'createReadOnlyInfoRow.m', ...
        'createReadOnlyTextField.m', 'defaultScaleBarUnits.m', ...
        'drawScaleBarOverlay.m', 'enableAxesPopout.m', ...
        'normalizeScaleBarUnit.m', 'popoutAxes.m', 'scaleBarPanel.m'}, ...
        'UI tool private implementation');
    assertNoPublicPackage(fullfile(root, '+labkit', '+ui', '+control'), ...
        'UI control helpers should stay private instead of becoming a public helper-dump package.');

    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+dta'), ...
        {'addFilesToSession.m', 'detectPulses.m', 'detectType.m', 'findFiles.m', ...
        'getColumn.m', 'getCurveXY.m', 'getMainCurve.m', 'getZCurve.m', ...
        'loadFile.m', 'loadFiles.m', 'loadFolder.m', 'loadSession.m', ...
        'makeSession.m', 'removeSelectedItemsFromSession.m', ...
        'saveSession.m', 'selectSessionItems.m'}, ...
        'Public reusable +labkit DTA facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+dta', 'private'), ...
        {'addItemsToSession.m', 'defaultPulseOptions.m', 'detectPulseCore.m', ...
        'emptyPulse.m', 'findDTAFilesRecursive.m', 'isDataLike.m', 'makeChronoItem.m', ...
        'makeEISItem.m', 'makeSessionStruct.m', 'nextNonEmpty.m', ...
        'normalizeExpectedKind.m', ...
        'parseChronoDTA.m', 'parseCVCTDTA.m', 'parseEISDTA.m', ...
        'pulsesFromCurrent.m', 'pulsesFromMetadata.m', 'removeFilesFromSession.m', ...
        'removeSelectedSessionItems.m', 'selectItemsByNames.m', 'splitTabs.m'}, ...
        'DTA private implementation');

    h.assertTopLevelMFiles(fullfile(root, '+labkit', '+biosignal'), ...
        {'buildTemplate.m', 'compareGroups.m', 'cropSignal.m', ...
        'defaultEcgPeakOptions.m', 'detectEcgPeaks.m', 'filterSignal.m', ...
        'getChannel.m', 'listChannels.m', 'measureSegments.m', ...
        'readRecording.m', 'segmentByEvents.m'}, ...
        'Public reusable +labkit biosignal facade');
    h.assertPackageMFiles(fullfile(root, '+labkit', '+biosignal', 'private'), ...
        {'detectEcgPeaksImpl.m', 'fillVectorMissing.m', 'inferSampleRate.m', ...
        'inferTableTime.m', 'isTimeLikeName.m', 'makeRecording.m', ...
        'makeSignalStruct.m', 'numericColumn.m', 'optionValue.m', ...
        'readCsvRecording.m', 'readDelimitedTable.m', ...
        'readMatRecording.m', 'resolveSignalColumns.m', ...
        'timeColumnName.m', 'timeToSeconds.m'}, ...
        'Biosignal private implementation');

    assert(exist(fullfile(root, '+labkit', '+util', 'splitTabs.m'), 'file') ~= 2, ...
        'Parser-only tab splitting should be private to +labkit/+dta.');
    assert(exist(fullfile(root, '+labkit', '+util', 'nextNonEmpty.m'), 'file') ~= 2, ...
        'Parser-only line scanning should be private to +labkit/+dta.');
    assert(exist(fullfile(root, '+labkit', '+util', 'isDataLike.m'), 'file') ~= 2, ...
        'Parser-only data-row detection should be private to +labkit/+dta.');
    assert(exist(fullfile(root, '+labkit', '+dta', 'private', 'splitTabs.m'), 'file') == 2, ...
        'Shared parser tab splitting should live under +labkit/+dta/private.');
    assert(exist(fullfile(root, '+labkit', '+dta', 'private', 'nextNonEmpty.m'), 'file') == 2, ...
        'Shared parser line scanning should live under +labkit/+dta/private.');
    assert(exist(fullfile(root, '+labkit', '+dta', 'private', 'isDataLike.m'), 'file') == 2, ...
        'Shared parser data-row detection should live under +labkit/+dta/private.');
end

function assertNoPublicPackage(packageDir, message)
    assert(exist(packageDir, 'dir') ~= 7, message);
end
