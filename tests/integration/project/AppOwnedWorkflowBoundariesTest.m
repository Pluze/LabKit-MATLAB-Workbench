classdef AppOwnedWorkflowBoundariesTest < matlab.unittest.TestCase
    %APPOWNEDWORKFLOWBOUNDARIESTEST Verify LabKit behavior through official MATLAB tests.

    methods (Test, TestTags = {'Integration', 'Style'})
        function test_app_owned_workflow_boundaries(testCase)
            setupLabKitTestPath();
            verify_app_owned_workflow_boundaries();
        end
    end
end

