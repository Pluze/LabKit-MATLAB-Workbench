function assertDeclarativeImageApp(source, appName, removedBuilderCall)
    assert(contains(source, 'labkit.ui.app.create('), ...
        [appName ' should launch through labkit.ui.app.create after UI 2.0 migration.']);
    forbidden = { ...
        'labkit.ui.app.createShell' ...
        'labkit.ui.app.tab(' ...
        removedBuilderCall ...
        'labkit.ui.view.section' ...
        'labkit.ui.view.form' ...
        'labkit.ui.view.panel' ...
        'labkit.ui.view.draw(' ...
        'labkit.ui.view.update(' ...
        'labkit.ui.view.place' ...
        'uigetfile(' ...
        'Layout.Row' ...
        'Layout.Column'};
    for k = 1:numel(forbidden)
        assert(~contains(source, forbidden{k}), ...
            [appName ' UI 2.0 path should not retain old UI debt: ' forbidden{k}]);
    end
end
