classdef GuiLayoutUiBasicControlsTest < matlab.uitest.TestCase
    %GUILAYOUTUIBASICCONTROLSTEST Verify UI 2.0 view helper contracts.

    methods (Test, TestTags = {'GUI', 'Structural'})
        function test_gui_layout_ui_basic_controls(testCase)
            setupLabKitTestPath();
            verify_gui_layout_ui_basic_controls();
        end
    end
end

function verify_gui_layout_ui_basic_controls()
%TEST_GUI_LAYOUT_UI_BASIC_CONTROLS Verify final reusable UI view helpers.

    h = guiTestHelpers();
    h.assertUifigureAvailable();
    cleanup = onCleanup(@() h.closeAllFigures());

    spec = labkit.ui.spec.app('basicControlsProbe', 'Basic Controls Probe', ...
        'position', [120 100 980 680], ...
        'controlTabs', { ...
            labkit.ui.spec.tab('setup', 'Setup', { ...
                labkit.ui.spec.section('filesSection', 'Files', { ...
                    labkit.ui.spec.pathPanel('files', 'Files', ...
                        'mode', 'multiFile', ...
                        'selectionMode', 'multiple', ...
                        'status', 'No files loaded'), ...
                    labkit.ui.spec.field('gain', 'Gain', ...
                        'kind', 'spinner', ...
                        'value', 1, ...
                        'limits', [0 10]), ...
                    labkit.ui.spec.action('run', 'Run', @noop)})}), ...
            labkit.ui.spec.tab('results', 'Results', { ...
                labkit.ui.spec.section('resultsSection', 'Results', { ...
                    labkit.ui.spec.resultTable('table', 'Table', ...
                        'columns', {'Name', 'Value'}), ...
                    labkit.ui.spec.statusPanel('details', 'Details', ...
                        'value', {'Ready.'})})}), ...
            labkit.ui.spec.tab('log', 'Log', { ...
                labkit.ui.spec.section('logSection', 'Log', { ...
                    labkit.ui.spec.logPanel('logPanel', 'Log', ...
                        'value', {'Started.'})})})}, ...
        'workspace', labkit.ui.spec.workspace('workspace', 'Preview', { ...
            labkit.ui.spec.previewArea('preview', 'Preview', ...
                'layout', 'single', ...
                'axisIds', {'main'}, ...
                'axisTitles', {'Preview'})}));
    ui = labkit.ui.app.create(spec);

    labkit.ui.view.setListItems(ui, 'files', {'a.dat', 'b.dat'});
    assert(h.sameStringCell(ui.controls.files.listbox.Items, {'a.dat', 'b.dat'}), ...
        'setListItems should populate semantic list-bearing controls.');
    [selection, idx] = labkit.ui.view.setListSelection( ...
        ui, 'files', {'a.dat', 'b.dat'}, {'b.dat'}, struct());
    assert(h.sameStringCell(selection, {'b.dat'}) && isequal(idx, 2), ...
        'setListSelection should apply valid semantic multi-selection.');

    labkit.ui.view.setValue(ui, 'gain', 4);
    assert(labkit.ui.view.getValue(ui, 'gain') == 4, ...
        'setValue/getValue should round-trip field values by id.');
    labkit.ui.view.setEnabled(ui, 'run', false);
    assert(strcmp(ui.controls.run.button.Enable, 'off'), ...
        'setEnabled should target action buttons by id.');

    labkit.ui.view.appendLog(ui, 'logPanel', 'Completed.');
    assert(any(contains(string(ui.controls.logPanel.textArea.Value), 'Completed.')), ...
        'appendLog should append to a semantic log panel.');
    labkit.ui.view.drawImage(ui, 'preview', zeros(8, 9, 3, 'uint8'), ...
        'axis', 'main', 'title', 'Preview');
    ax = ui.controls.preview.primaryAxes;
    assert(~isempty(ax.Children), 'drawImage should draw into a semantic preview axes.');
    labkit.ui.view.clearAxes(ui, 'preview', 'main');
    assert(isempty(ax.Children), 'clearAxes should remove preview axes children.');
    labkit.ui.view.resetAxes(ui, 'preview', 'Preview Reset', true, 'main');
    assert(strcmp(char(ax.Title.String), 'Preview Reset'), ...
        'resetAxes should retitle a semantic preview axes.');

    function noop(varargin)
    end
end
