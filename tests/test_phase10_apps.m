        'GUI-free session loading should live in +gamrywb/+data, not +ui.');
    assert(exist(fullfile(root, '+gamrywb', '+ui', 'removeSelectedItemsFromSession.m'), 'file') ~= 2, ...
        'GUI-free selected-item removal should live in +gamrywb/+data, not +ui.');
    assert(exist(fullfile(root, '+gamrywb', '+ui', 'selectItemsByNames.m'), 'file') ~= 2, ...
        'GUI-free selected-item lookup should live in +gamrywb/+data, not +ui.');
    assert(exist(fullfile(root, '+gamrywb', '+io', 'exportTableCSV.m'), 'file') ~= 2, ...
        'One-line CSV writer wrappers should not live in reusable +gamrywb/+io.');

    assert(exist(fullfile(root, 'apps', 'private'), 'dir') ~= 7, ...
        'The transitional apps/private launcher directory should be removed after all app bodies move public.');

    chronoSource = assertSingleFileApp(root, ...
        'gamrywb_ChronoOverlay_app', ...
        'launchChronoOverlayApp', ...
        'gamry_multiDTA_plot_export_gui(');
    assert(contains(chronoSource, 'gamrywb.dta.loadFile(filepath, "chrono")'), ...
        'gamrywb_ChronoOverlay_app should load DTA files through the GUI-free DTA facade.');
    assert(~contains(chronoSource, 'gamrywb.data.makeChronoItem(filepath)'), ...
        'gamrywb_ChronoOverlay_app should not construct chrono items directly in the app layer.');
    assert(~contains(chronoSource, 'gamrywb_apps.chrono'), ...
        'Chrono overlay should not depend on the transitional gamrywb_apps.chrono namespace.');
    assert(contains(chronoSource, 'function [item, msg] = alignByPulseGap'), ...
        'Chrono overlay alignment should be local to the public app file.');
    assert(contains(chronoSource, 'function plotVTIT'), ...
        'Chrono overlay plotting should be local to the public app file.');
    assert(contains(chronoSource, 'function T = buildOverlayExportTable'), ...
        'Chrono overlay export table construction should be local to the public app file.');
    assert(~contains(chronoSource, 'gamrywb.analysis.alignChronoByPulseGap'), ...
        'Chrono overlay alignment should not live in reusable +gamrywb analysis.');
    assert(~contains(chronoSource, 'gamrywb.plot.plotChronoVTIT'), ...
        'Chrono overlay plotting should not live in reusable +gamrywb plot.');
    assert(~contains(chronoSource, 'gamrywb.io.buildChronoOverlayExportTable'), ...
        'Chrono overlay export table construction should not live in reusable +gamrywb io.');
    assert(exist(fullfile(root, 'apps', '+gamrywb_apps', '+chrono'), 'dir') ~= 7, ...
        'The transitional gamrywb_apps.chrono package should be removed.');
    assert(exist(fullfile(root, '+gamrywb', '+analysis', 'alignChronoByPulseGap.m'), 'file') ~= 2, ...
        'Chrono overlay alignment should not live in reusable +gamrywb analysis.');

    eisSource = assertSingleFileApp(root, ...
        'gamrywb_EIS_app', ...
        'launchEISApp', ...
        'gamry_EIS_multiDTA_plot_gui(');
    assert(contains(eisSource, 'gamrywb.dta.loadFile(filepath, "eis")'), ...
        'gamrywb_EIS_app should load DTA files through the GUI-free DTA facade.');
    assert(~contains(eisSource, 'gamrywb.data.makeEISItem(filepath)'), ...
        'gamrywb_EIS_app should not construct EIS items directly in the app layer.');
    assert(~contains(eisSource, 'gamrywb_apps.eis'), ...
        'EIS app should not depend on the transitional gamrywb_apps.eis namespace.');
    assert(contains(eisSource, 'function values = valuesForAxis'), ...
        'EIS axis selection should be local to the public app file.');
    assert(contains(eisSource, 'function labels = plotOverlay'), ...
        'EIS overlay plotting should be local to the public app file.');
    assert(contains(eisSource, 'function T = buildExportTable'), ...
        'EIS export table construction should be local to the public app file.');
    assert(~contains(eisSource, 'gamrywb.plot.plotEISOverlay'), ...
        'EIS overlay plotting should not live in reusable +gamrywb plot.');
    assert(~contains(eisSource, 'gamrywb.io.buildEISExportTable'), ...
        'EIS export table construction should not live in reusable +gamrywb io.');
    assert(exist(fullfile(root, 'apps', '+gamrywb_apps', '+eis'), 'dir') ~= 7, ...
