    assert(~contains(cicSource, 'gamrywb.analysis.computeCIC'), ...
        'gamrywb_CIC_app should not call CIC analysis through reusable +gamrywb.');
    cicComputeSource = fileread(fullfile(root, 'apps', '+gamrywb_apps', '+cic', 'computeCIC.m'));
