classdef StarterAppViewTest < matlab.unittest.TestCase
    %STARTERAPPVIEWTEST Verify template app GUI-free display helpers.

    methods (Test, TestTags = {'Unit'})
        function summaryRowsReflectTemplateState(testCase)
            S = struct( ...
                'inputNames', ["a.csv"; "b.csv"], ...
                'primaryValue', 7.25, ...
                'mode', "Review", ...
                'enabled', false, ...
                'lastAction', "Updated settings");

            data = starter_app.view.summaryTableData(S);

            testCase.verifyEqual(data(:, 1), { ...
                'Inputs selected'; ...
                'Primary value'; ...
                'Mode'; ...
                'Run enabled'; ...
                'Last action'});
            testCase.verifyEqual(data{1, 2}, '2');
            testCase.verifyEqual(data{2, 2}, '7.25');
            testCase.verifyEqual(data{3, 2}, 'Review');
            testCase.verifyEqual(data{4, 2}, 'off');
            testCase.verifyEqual(data{5, 2}, 'Updated settings');
        end

        function detailLinesProvideStarterGuidance(testCase)
            lines = starter_app.view.detailLines(struct());

            testCase.verifyTrue(iscell(lines));
            testCase.verifyTrue(any(contains(string(lines), ...
                'starter canvas')));
            testCase.verifyTrue(any(contains(string(lines), ...
                'Mode: Preview')));
        end
    end
end
