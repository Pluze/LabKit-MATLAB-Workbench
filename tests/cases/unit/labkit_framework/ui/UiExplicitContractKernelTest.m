classdef UiExplicitContractKernelTest < matlab.unittest.TestCase
    methods (Test)
        function compilesAndValidatesCompleteTablePlotContract(testCase)
            setupLabKitTestPath();
            [app, view] = representativeContract();

            testCase.verifyEqual(app.TargetIds, ...
                ["group", "run", "dataTable", "result"]);
            testCase.verifyTrue(app.validatePresentation(view));
            testCase.verifyTrue(app.validatePresentation(view));
            testCase.verifyTrue(meta.class.fromName( ...
                "labkit.ui.Application").Sealed);
            testCase.verifyTrue(meta.class.fromName( ...
                "labkit.ui.Command").Sealed);
            testCase.verifyTrue(meta.class.fromName( ...
                "labkit.ui.Layout").Sealed);
            testCase.verifyTrue(meta.class.fromName( ...
                "labkit.ui.Presentation").Sealed);
        end

        function rejectsUnknownArgumentsAndCallbackShapes(testCase)
            setupLabKitTestPath();
            testCase.verifyError(@() labkit.ui.Command( ...
                "run", @invoke, Typo=true), ...
                "labkit:ui:contract:UnknownArgument");
            testCase.verifyError(@() labkit.ui.Command( ...
                "run", @variableInput), ...
                "labkit:ui:contract:CallbackRoleMismatch");
            testCase.verifyError(@() labkit.ui.Command( ...
                "run", @noOutput), ...
                "labkit:ui:contract:CallbackRoleMismatch");
            testCase.verifyError(@() labkit.ui.Command( ...
                "changed", @invoke, Role="value"), ...
                "labkit:ui:contract:CallbackRoleMismatch");
        end

        function rejectsInvalidOwnershipAndReferences(testCase)
            setupLabKitTestPath();
            field = labkit.ui.Layout.field("group");
            testCase.verifyError(@() labkit.ui.Layout.group( ...
                "bad", {labkit.ui.Layout.previewArea("plot")}), ...
                "labkit:ui:contract:UnsupportedOperation");
            testCase.verifyError(@() applicationFor( ...
                labkit.ui.Layout.workbench({field, field})), ...
                "labkit:ui:contract:DuplicateId");

            run = labkit.ui.Command("run", @invoke);
            layout = labkit.ui.Layout.workbench({ ...
                labkit.ui.Layout.action("run", "Run", run)});
            testCase.verifyError(@() applicationFor(layout), ...
                "labkit:ui:contract:UnknownReference");
            testCase.verifyError(@() labkit.ui.Application( ...
                Command="labkit_Probe_app", Id="probe.app", ...
                Title="Probe", Family="Tests", AppVersion="1.0.0", ...
                Updated="2026-07-19", Requirements=[], Layout=layout, ...
                Commands={run}, Capabilities="unknown"), ...
                "labkit:ui:contract:InvalidValue");
        end

        function rejectsInvalidOrIncompletePresentation(testCase)
            setupLabKitTestPath();
            [app, view] = representativeContract();
            testCase.verifyError(@() app.validatePresentation( ...
                labkit.ui.Presentation().value("missing", 1)), ...
                "labkit:ui:contract:UnknownReference");
            testCase.verifyError(@() app.validatePresentation( ...
                labkit.ui.Presentation().table("group", [1 2])), ...
                "labkit:ui:contract:UnsupportedOperation");
            testCase.verifyError(@() app.validatePresentation( ...
                labkit.ui.Presentation().value("group", "A")), ...
                "labkit:ui:contract:UnknownReference");
            testCase.verifyError(@() view.value("group", "B"), ...
                "labkit:ui:contract:DuplicateId");

            [appWithRenderer, incompleteRendererView] = ...
                contractWithWrongRenderer();
            testCase.verifyError(@() appWithRenderer.validatePresentation( ...
                incompleteRendererView), ...
                "labkit:ui:contract:UnknownReference");
        end

        function compilesAuditedLayoutVocabularyAndWorkspacePages(testCase)
            setupLabKitTestPath();
            run = labkit.ui.Command("run", @invoke);
            changed = labkit.ui.Command( ...
                "changed", @valueChanged, Role="value");
            selected = labkit.ui.Command( ...
                "selected", @selectionChanged, Role="selection");
            edited = labkit.ui.Command( ...
                "edited", @tableEdited, Role="tableEdit");

            controls = {
                labkit.ui.Layout.section("inputs", "Inputs", { ...
                    labkit.ui.Layout.group("basic", { ...
                        labkit.ui.Layout.field("name", Changed=changed), ...
                        labkit.ui.Layout.rangeField( ...
                            "window", Changed=changed), ...
                        labkit.ui.Layout.panner("frame", Changed=changed), ...
                        labkit.ui.Layout.filePanel("files", ...
                            SelectionChanged=selected), ...
                        labkit.ui.Layout.action("run", "Run", run)})}), ...
                labkit.ui.Layout.tab("details", "Details", { ...
                    labkit.ui.Layout.logPanel("log"), ...
                    labkit.ui.Layout.statusPanel("status")}), ...
                };
            workspace = labkit.ui.Layout.workspace(PageChanged=changed);
            workspace = workspace.page("tablePage", "Table", ...
                labkit.ui.Layout.resultTable("table", ...
                    Edited=edited, SelectionChanged=selected));
            workspace = workspace.page("plotPage", "Plot", ...
                labkit.ui.Layout.previewArea("plot", ...
                    AxisIds=["image", "trace"], Renderers="draw"));
            workspace = workspace.initialPage("tablePage");
            layout = labkit.ui.Layout.workbench( ...
                controls, Workspace=workspace);
            app = labkit.ui.Application( ...
                Command="labkit_Probe_app", Id="probe.layout", ...
                Title="Probe", Family="Tests", AppVersion="1.0.0", ...
                Updated="2026-07-19", Requirements=[], Layout=layout, ...
                Commands={run, changed, selected, edited}, ...
                Renderers=struct("draw", @renderComparison));

            testCase.verifyEqual(workspace.PageIds, ...
                ["tablePage", "plotPage"]);
            testCase.verifyEqual(workspace.InitialPage, "tablePage");
            testCase.verifyTrue(all(ismember( ...
                ["name", "window", "frame", "files", "run", "log", ...
                 "status", "tablePage", "table", "plotPage", "plot"], ...
                app.TargetIds)));
            testCase.verifyError(@() workspace.initialPage("missing"), ...
                "labkit:ui:contract:UnknownReference");
            testCase.verifyError(@() labkit.ui.Layout.workspace( ...
                labkit.ui.Layout.statusPanel("single")).page( ...
                "other", "Other", labkit.ui.Layout.statusPanel("other")), ...
                "labkit:ui:contract:UnsupportedOperation");
        end
    end
end

function [app, view] = representativeContract()
    changed = labkit.ui.Command( ...
        "groupChanged", @valueChanged, Role="value");
    edited = labkit.ui.Command( ...
        "tableEdited", @tableEdited, Role="tableEdit");
    run = labkit.ui.Command("run", @invoke);
    layout = labkit.ui.Layout.workbench({ ...
        labkit.ui.Layout.group("inputs", { ...
            labkit.ui.Layout.field("group", Changed=changed), ...
            labkit.ui.Layout.action("run", "Run", run)}), ...
        labkit.ui.Layout.resultTable("dataTable", Edited=edited), ...
        labkit.ui.Layout.previewArea("result", Renderers="comparison")});
    app = labkit.ui.Application( ...
        Command="labkit_Probe_app", ...
        Id="probe.app", ...
        Title="Probe", ...
        Family="Tests", ...
        AppVersion="1.0.0", ...
        Updated="2026-07-19", ...
        Requirements=[], ...
        Layout=layout, ...
        Commands={changed, edited, run}, ...
        Renderers=struct("comparison", @renderComparison), ...
        Capabilities=["workflow", "render"]);
    view = labkit.ui.Presentation();
    view = view.choices("group", ["A", "B"]);
    view = view.value("group", "A");
    view = view.table("dataTable", [1 2; 3 4]);
    view = view.enabled("run", true);
    view = view.plot("result", "comparison", ...
        struct("X", [1 2], "Y", [2 3]));
end

