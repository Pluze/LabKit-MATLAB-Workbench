classdef UiSpecTest < matlab.unittest.TestCase
    %UISPECTEST Verify LabKit UI 3.0 declarative spec contracts.

    methods (Test, TestTags = {'Unit'})
        function test_uiSpec(testCase)
            setupLabKitTestPath();
            verify_uiSpec();
        end
    end
end

function verify_uiSpec()
%TEST_UISPEC Verify UI 3.0 spec grammar and GUI-free validation.

    checkCommonSpecShape();
    checkChildrenMustBeCellRows();
    checkFieldKindWhitelist();
    checkPannerSpec();
    checkFilePanelSpec();
    checkFileLabels();
    checkPreviewAreaValidation();
    checkRetiredLayoutOptionsAreRejected();
    checkDuplicateIdsFailBeforeGuiConstruction();
end

function checkRetiredLayoutOptionsAreRejected()
    baseSection = labkit.ui.spec.section('section', 'Section', { ...
        labkit.ui.spec.action('run', 'Run', @uiSpecModeProbe)});
    baseTab = labkit.ui.spec.tab('setup', 'Setup', {baseSection});
    workspace = labkit.ui.spec.workspace('workspace', 'Workspace', {});

    withPosition = labkit.ui.spec.app('positionProbe', 'Position Probe', ...
        'position', [1 2 3 4], ...
        'controlTabs', {baseTab}, ...
        'workspace', workspace);
    assertThrows(@() labkit.ui.app.create(withPosition), ...
        'labkit:ui:app:RetiredLayoutProperty', ...
        'App position should be a shared framework default.');

    withLeftWidth = labkit.ui.spec.app('leftWidthProbe', 'Left Width Probe', ...
        'leftWidth', 360, ...
        'controlTabs', {baseTab}, ...
        'workspace', workspace);
    assertThrows(@() labkit.ui.app.create(withLeftWidth), ...
        'labkit:ui:app:RetiredLayoutProperty', ...
        'App left pane width should be a shared framework default.');

    layoutProps = { ...
        'height', 80; ...
        'height', 'fit'; ...
        'height', 'flex'; ...
        'minRows', 3; ...
        'minHeight', 160; ...
        'maxColumns', 3; ...
        'rowSpacing', 12; ...
        'columnSpacing', 12; ...
        'padding', [4 4 4 4]; ...
        'chrome', 'none'; ...
        'columnWidth', {{80, '1x'}}; ...
        'rowHeight', {{'fit'}}};
    for k = 1:size(layoutProps, 1)
        section = labkit.ui.spec.section('layoutSection', 'Layout Section', { ...
            labkit.ui.spec.action('layoutRun', 'Run', @uiSpecModeProbe)}, ...
            layoutProps{k, 1}, layoutProps{k, 2});
        app = labkit.ui.spec.app(['layoutProbe' num2str(k)], ...
            'Layout Probe', ...
            'controlTabs', {labkit.ui.spec.tab('layoutTab', 'Layout', {section})}, ...
            'workspace', workspace);
        assertThrows(@() labkit.ui.app.create(app), ...
            'labkit:ui:app:RetiredLayoutProperty', ...
            'App specs should not own concrete layout properties.');
    end
end

function checkCommonSpecShape()
    field = labkit.ui.spec.field('gain', 'Gain', ...
        'kind', 'spinner', 'value', 2);
    section = labkit.ui.spec.section('settings', 'Settings', {field});
    tab = labkit.ui.spec.tab('setup', 'Setup', {section});
    workspace = labkit.ui.spec.workspace('workspace', 'Preview', { ...
        labkit.ui.spec.previewArea('preview', 'Preview')});
    app = labkit.ui.spec.app('probeApp', 'Probe App', ...
        'controlTabs', {tab}, 'workspace', workspace);

    assert(strcmp(app.kind, 'app'), 'App spec should preserve kind.');
    assert(strcmp(app.id, 'probeApp'), 'App spec should preserve id.');
    assert(isstruct(app.props) && iscell(app.children) && isstruct(app.slots), ...
        'Spec should use the common kind/id/props/children/slots shape.');
    assert(iscell(app.props.controlTabs) && isrow(app.props.controlTabs), ...
        'controlTabs should stay a cell row vector for heterogeneous children.');
    assert(strcmp(section.children{1}.id, 'gain'), ...
        'Section children should preserve child specs.');
    usageApp = labkit.ui.spec.app('usageProbe', 'Usage Probe', ...
        'controlTabs', {tab}, ...
        'workspace', workspace, ...
        'usage', {'Open files.', 'Run analysis.'});
    firstTabChildren = usageApp.props.controlTabs{1}.children;
    assert(strcmp(firstTabChildren{end}.children{1}.kind, 'usagePanel'), ...
        'App-level usage should be injected into the first tab.');
    usage = labkit.ui.spec.usagePanel('usage', 'How to use', ...
        'value', {'Open files.', 'Run analysis.'});
    assert(strcmp(usage.kind, 'usagePanel') && ...
        strcmp(usage.props.title, 'How to use') && ...
        numel(usage.props.value) == 2, ...
        'usagePanel should preserve static workflow help lines.');
end

function checkChildrenMustBeCellRows()
    child = labkit.ui.spec.field('probe', 'Probe');
    assertThrows(@() labkit.ui.spec.section('bad', 'Bad', [child child]), ...
        'labkit:ui:spec:InvalidChildren', ...
        'Struct-array children should be rejected.');
    assertThrows(@() labkit.ui.spec.tab('badTab', 'Bad', {child; child}), ...
        'labkit:ui:spec:InvalidChildren', ...
        'Column-cell children should be rejected.');
end

function checkFieldKindWhitelist()
    allowed = {'text', 'number', 'spinner', 'dropdown', 'slider', ...
        'checkbox', 'readonly'};
    for k = 1:numel(allowed)
        spec = labkit.ui.spec.field(['field' num2str(k)], 'Field', ...
            'kind', allowed{k});
        assert(strcmpi(spec.props.kind, allowed{k}), ...
            'Allowed field kind should be preserved.');
    end
    assertThrows(@() labkit.ui.spec.field('radio', 'Radio', ...
        'kind', 'radioGroup'), 'labkit:ui:spec:InvalidFieldKind', ...
        'Primitive or unproven field kinds should stay out of UI 3.0.');
end

function checkPannerSpec()
    spec = labkit.ui.spec.panner('pan', 'Pan', ...
        'limits', [0 12], ...
        'value', 3, ...
        'stepFraction', 0.01, ...
        'minStep', 0.1, ...
        'maxStep', 0.5);
    assert(strcmp(spec.kind, 'panner') && isequal(spec.props.limits, [0 12]), ...
        'panner should preserve numeric limits and common spec shape.');
    assertThrows(@() labkit.ui.spec.panner('badPan', 'Bad', ...
        'limits', [1 1]), ...
        'labkit:ui:spec:InvalidPannerLimits', ...
        'panner should reject non-increasing limits.');
end

function checkFilePanelSpec()
    spec = labkit.ui.spec.filePanel('tasks', 'Files', ...
        'filters', {'*.jpg;*.png', 'Images'}, ...
        'selectionMode', 'multiple', ...
        'maxFiles', 12, ...
        'folderWarningThreshold', 100);
    assert(strcmp(spec.kind, 'filePanel') && ...
        strcmp(spec.props.selectionMode, 'multiple') && ...
        spec.props.maxFiles == 12, ...
        'filePanel should preserve file input options.');
    singleSpec = labkit.ui.spec.filePanel('singleFile', 'Single file', ...
        'mode', 'single');
    assert(strcmp(singleSpec.props.mode, 'single'), ...
        'filePanel should preserve single-file mode.');
    customChoose = labkit.ui.spec.filePanel('customFileLabels', 'Files', ...
        'chooseLabel', 'Add DTA files', ...
        'removeLabel', 'Remove selected files', ...
        'clearLabel', 'Clear all files');
    assert(strcmp(customChoose.props.chooseLabel, 'Add DTA files') && ...
        strcmp(customChoose.props.removeLabel, 'Remove selected files') && ...
        strcmp(customChoose.props.clearLabel, 'Clear all files'), ...
        'filePanel should preserve app-authored command wording.');
    assertThrows(@() labkit.ui.spec.filePanel('badMode', 'Files', ...
        'mode', 'folder'), ...
        'labkit:ui:spec:InvalidFilePanelMode', ...
        'Unsupported filePanel modes should fail validation.');
    assertThrows(@() labkit.ui.spec.filePanel('badFiles', 'Files', ...
        'selectionMode', 'range'), ...
        'labkit:ui:spec:InvalidFilePanelSelectionMode', ...
        'Unsupported filePanel selection modes should fail validation.');
    assertThrows(@() labkit.ui.spec.filePanel('badMaxFiles', 'Files', ...
        'maxFiles', 0), ...
        'labkit:ui:spec:InvalidFilePanelMaxFiles', ...
        'filePanel maxFiles should reject nonpositive values.');
end

function checkFileLabels()
    paths = [ ...
        string(fullfile(tempdir, 'x', 'y', 'z.jpg')); ...
        string(fullfile(tempdir, 'x', 'yy', 'z.jpg')); ...
        string(fullfile(tempdir, 'a', 'y', 'z.jpg')); ...
        string(fullfile(tempdir, 'plain', 'a.png'))];
    labels = string(labkit.ui.view.fileLabels(paths, ...
        'status', ["ready"; "ready"; "needs review"; ""]));
    assert(contains(labels(1), 'z.jpg') && contains(labels(1), '(x/y)') && ...
        contains(labels(2), '(yy)') && contains(labels(3), '(a/y)'), ...
        'fileLabels should use the nearest unique parent suffix for repeated file names.');
    assert(startsWith(labels(4), '04 a.png') && ~contains(labels(4), '['), ...
        'fileLabels should prefix sequence numbers and omit empty status.');
end

function checkPreviewAreaValidation()
    pair = labkit.ui.spec.previewArea('pairPreview', 'Pair', ...
        'layout', 'pair', ...
        'axisIds', {'input', 'output'}, ...
        'xLabels', {'Time (s)', 'Time (s)'}, ...
        'yLabels', {'Vf (V)', 'Im (A)'});
    assert(strcmp(pair.props.layout, 'pair'), ...
        'Allowed preview layout should be preserved.');
    assert(strcmp(pair.props.xLabels{1}, 'Time (s)') && ...
        strcmp(pair.props.yLabels{2}, 'Im (A)'), ...
        'previewArea should preserve app-authored axis labels.');
    stack = labkit.ui.spec.previewArea('waveforms', 'Waveforms', ...
        'layout', 'stack', 'count', 4);
    assert(stack.props.count == 4, ...
        'Stacked preview areas should support axis count.');
    modes = labkit.ui.spec.previewArea('modePreview', 'Mode Preview', ...
        'viewModes', {'Input', 'Output'}, 'onModeChange', @uiSpecModeProbe);
    assert(isequal(modes.props.viewModes, {'Input', 'Output'}), ...
        'previewArea should preserve declared viewModes.');
    assertThrows(@() labkit.ui.spec.previewArea('badPreview', 'Bad', ...
        'layout', 'grid'), 'labkit:ui:spec:InvalidPreviewLayout', ...
        'Unsupported preview layouts should fail validation.');
end

function checkDuplicateIdsFailBeforeGuiConstruction()
    tab = labkit.ui.spec.tab('setup', 'Setup', { ...
        labkit.ui.spec.section('sectionOne', 'One', { ...
            labkit.ui.spec.field('dup', 'First'), ...
            labkit.ui.spec.field('dup', 'Second')})});
    workspace = labkit.ui.spec.workspace('workspace', 'Workspace', {});
    spec = labkit.ui.spec.app('probeApp', 'Probe App', ...
        'controlTabs', {tab}, 'workspace', workspace);
    assertThrows(@() labkit.ui.app.create(spec), ...
        'labkit:ui:app:DuplicateId', ...
        'Duplicate ids should fail before GUI construction.');
end

function assertThrows(fn, expectedIdentifier, label)
    try
        fn();
    catch ME
        assert(strcmp(ME.identifier, expectedIdentifier), ...
            '%s Expected %s but caught %s.', label, expectedIdentifier, ME.identifier);
        return;
    end
    error('%s Expected an error with identifier %s.', label, expectedIdentifier);
end

