        end

        function inlineRenderingDoesNotCaptureTheFullModelPerFragment(testCase)
            root = setupLabKitTestPath();
            renderer = string(fileread(fullfile(root, "tools", "docs", ...
                "private", "renderLabKitMarkdown.m")));

            testCase.verifyFalse(contains(renderer, ...
                "@(token) renderLink(model, page, token)"), ...
                ['Inline rendering must not allocate a closure that captures ' ...
                'the complete documentation model for every text fragment.']);
            testCase.verifyTrue(contains(renderer, ...
                "replacement = renderLink(model, page, tokens)"), ...
                ['Link tokens should receive shared model and page inputs ' ...
                'without per-fragment closure capture.']);
        end

        function rendererSynchronizesWithoutReplacingSiteRoot(testCase)
            root = setupLabKitTestPath();
            renderer = string(fileread(fullfile(root, "tools", "docs", ...
                "renderLabKitDocs.m")));

            testCase.verifyTrue(contains(renderer, ...
                "syncLabKitDocTree(stagingRoot, outputRoot)"));
            testCase.verifyFalse(contains(renderer, "rmdir(outputRoot"), ...
                ["The renderer must not delete the canonical site root; " ...
                "sync folders can preserve it as a numbered conflict copy."]);
            testCase.verifyFalse(contains(renderer, ...
                "movefile(stagingRoot, outputRoot)"));
            syncHelper = string(fileread(fullfile(root, "tools", "docs", ...
                "private", "syncLabKitDocTree.m")));
            testCase.verifyTrue(contains(syncHelper, ...
                "removeEmptyNumberedSiblings(targetRoot)"));
        end

        function generatedTreeListingSupportsRelativeRoots(testCase)
            root = setupLabKitTestPath();
            tools = fullfile(root, "tools", "docs");
            addpath(tools);
            pathCleanup = onCleanup(@() rmpath(tools));

            originalFolder = pwd;
            sandbox = string(tempname);
            mkdir(sandbox);
            folderCleanup = onCleanup(@() cleanupRelativeTree( ...
                originalFolder, sandbox));
            cd(sandbox);
            result = renderLabKitDocs(fullfile(root, "docs"), "relative-site");
            testCase.verifyTrue(isfile(fullfile("relative-site", "index.html")));
            testCase.verifyEqual(result.outputRoot, ...
                string(fullfile(sandbox, "relative-site")));
            clear folderCleanup pathCleanup
        end

