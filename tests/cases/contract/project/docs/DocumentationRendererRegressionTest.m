                "api", "labkit", "biosignal", "listChannels.html")));

            testCase.verifyTrue(contains(page, ...
                ['<dd>Recording structure returned by <a class="api-inline-link" ' ...
                'href="readRecording.html"><code>labkit.biosignal.' ...
