classdef DocumentationRendererRegressionTest < matlab.unittest.TestCase
    methods (Test, TestTags = {'Integration', 'Style'})
        function orderedListsPreserveItemsAndContinuations(testCase)
            root = setupLabKitTestPath();
            page = string(fileread(fullfile(root, "site", "apps", ...
                "electrochemistry", "cic.html")));
            workflow = extractBetween(page, ...
                '<h2 id="basic-workflow">Basic Workflow</h2>', ...
                '<h2 id="analysis-parameters">Analysis Parameters</h2>');

            testCase.assertNotEmpty(workflow);
            testCase.verifyEqual(count(workflow, "<ol>"), 1, ...
                "One Markdown sequence must render as one ordered list.");
            testCase.verifyEqual(count(workflow, "<li>"), 6);
            testCase.verifyTrue(contains(workflow, ...
                "phase mode, and output unit.</li>"), ...
                ["Indented list-item explanations must stay inside their " ...
                "list items so numbering does not restart at one."]);
            testCase.verifyFalse(contains(workflow, "</ol>" + newline + ...
                "<p>output unit.</p>"));
        end

        function historyUsesOneTimelineForEveryEra(testCase)
            root = setupLabKitTestPath();
            page = string(fileread(fullfile(root, "site", "history", ...
                "index.html")));

            testCase.verifyTrue(contains(page, ...
                '<h2 id="reading-the-timeline">Reading The Timeline</h2>'));
            testCase.verifyTrue(contains(page, ...
                '<h2>Complete timeline</h2>'));
            testCase.verifyEqual(count(page, ...
                '<section class="component-history">'), 1);
            testCase.verifyFalse(contains(page, "Before v1.0"));
            testCase.verifyFalse(contains(page, "The 2.x Line"));
            testCase.verifyFalse(contains(page, "Add A Record"));
            testCase.verifyEqual(count(page, "<ol>"), 0, ...
                ["Early records must use the same generated timeline as " ...
                "later records instead of a separate ordered-list format."]);
        end

        function apiProseLinksKnownPublicSymbols(testCase)
            root = setupLabKitTestPath();
            page = string(fileread(fullfile(root, "site", "reference", ...
                "api", "labkit", "biosignal", "listChannels.html")));

            testCase.verifyTrue(contains(page, ...
                ['<dd>Recording structure returned by <a class="api-inline-link" ' ...
                'href="readRecording.html"><code>labkit.biosignal.' ...
                'readRecording</code></a>.</dd>']));
            testCase.verifyTrue(contains(page, ...
                ['accepted by <a class="api-inline-link" ' ...
                'href="getChannel.html"><code>labkit.biosignal.' ...
                'getChannel</code></a>']));
            testCase.verifyFalse(contains(page, ...
                '<code class="language-matlab"><a'), ...
                "Executable examples must remain literal code, not links.");
        end

        function rendererSynchronizesWithoutReplacingSiteRoot(testCase)
            root = setupLabKitTestPath();
            renderer = string(fileread(fullfile(root, "tools", "docs", ...
                "renderLabKitDocs.m")));

            testCase.verifyTrue(contains(renderer, ...
                "syncLabKitDocTree(stagingRoot, outputRoot)"));
            testCase.verifyFalse(contains(renderer, "rmdir(outputRoot"), ...
                ["The renderer must not delete the canonical site root; " ...
                "sync folders can preserve it as a numbered conflict copy."]);
            testCase.verifyFalse(contains(renderer, ...
                "movefile(stagingRoot, outputRoot)"));
            syncHelper = string(fileread(fullfile(root, "tools", "docs", ...
                "private", "syncLabKitDocTree.m")));
            testCase.verifyTrue(contains(syncHelper, ...
                "removeEmptyNumberedSiblings(targetRoot)"));
        end
    end
end
