function assertPrivatePackageHasMFiles(packageDir, label)
    assert(exist(packageDir, 'dir') == 7, ...
        [label ' package directory should exist.']);
    files = dir(fullfile(packageDir, '*.m'));
    assert(any(~[files.isdir]), ...
        [label ' package should keep private implementation files.']);
end

function assertNativeAdapterClassFolder(root)
    classDir = fullfile(root, '+labkit', '+app', '+internal', ...
        '@MatlabPlatformAdapter');
    assert(exist(fullfile(classDir, 'MatlabPlatformAdapter.m'), 'file') == 2, ...
        'Native adapter class definition should remain in its class folder.');
    files = string({dir(fullfile(classDir, '*.m')).name});
    responsibilityAnchors = [ ...
        "buildTree.m", "createComponent.m", "installWorkbenchLayout.m", ...
        "applyView.m", "renderPlot.m", "installCallbacks.m"];
    assert(all(ismember(responsibilityAnchors, files)), ...
        'Native adapter class folder should own layout and reconciliation methods.');
    lifecycleGlue = [ ...
        "attachRuntime.m", "chooseFiles.m", "reconcile.m", "requestClose.m"];
    assert(~any(ismember(lifecycleGlue, files)), ...
        'Native adapter lifecycle and callback glue should stay in the class definition.');
    assert(numel(files) >= 20 && numel(files) <= 50, ...
        'Native adapter class-folder split should remain cohesive, not monolithic or fragmented.');
end
