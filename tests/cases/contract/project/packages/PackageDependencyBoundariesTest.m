classdef PackageDependencyBoundariesTest < matlab.unittest.TestCase
    %PACKAGEDEPENDENCYBOUNDARIESTEST Verify LabKit behavior through official MATLAB tests.

    methods (Test, TestTags = {'Integration', 'Style'})
        function test_package_dependency_boundaries(testCase)
            setupLabKitTestPath();
            verify_package_dependency_boundaries();
        end
    end
end

function verify_package_dependency_boundaries()
%TEST_PACKAGE_DEPENDENCY_BOUNDARIES Verify reusable package dependency rules.

    root = testRepoRoot();
    h = architectureTestHelpers();
    guiWords = h.guiWords();
    appWords = h.appEntrypointWords(root);
    workflowWords = h.experimentWorkflowWords();

    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+dta', 'private'), ...
        [guiWords {'labkit.ui', 'apps/'} appWords workflowWords], ...
        'DTA private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+dta'), ...
        [guiWords {'apps/', 'labkit.io', 'labkit.data'} appWords], ...
        'Reusable +labkit DTA facade');
    rhsForbidden = [guiWords {'apps/', 'labkit.ui', 'labkit.dta', ...
        'labkit.biosignal', 'protocol', 'stimulus train', 'CAP'} appWords workflowWords];
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+rhs'), ...
        rhsForbidden, ...
        'Reusable +labkit RHS facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+rhs', 'private'), ...
        rhsForbidden, ...
        'RHS private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+biosignal'), ...
        [guiWords {'apps/', 'labkit.ui', 'labkit.dta'} appWords], ...
        'Reusable +labkit biosignal facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+biosignal', 'private'), ...
        [guiWords {'apps/', 'labkit.ui', 'labkit.dta'} appWords], ...
        'Biosignal private implementation');
    uiForbidden = [{'DTA', 'Gamry', 'labkit.dta', 'labkit.io', ...
        'labkit.data', 'labkit.analysis', 'apps/'} appWords];
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui'), ...
        uiForbidden, ...
        'Reusable +labkit UI root');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+app'), ...
        uiForbidden, ...
        'Reusable +labkit UI app facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+app', 'private'), ...
        uiForbidden, ...
        'Reusable +labkit UI app private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+view'), ...
        uiForbidden, ...
        'Reusable +labkit UI view facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+view', 'private'), ...
        uiForbidden, ...
        'Reusable +labkit UI view private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+spec'), ...
        uiForbidden, ...
        'Reusable +labkit UI spec facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+spec', 'private'), ...
        uiForbidden, ...
        'Reusable +labkit UI spec private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+tool'), ...
        uiForbidden, ...
        'Reusable +labkit UI tool facade');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+tool', 'private'), ...
        uiForbidden, ...
        'Reusable +labkit UI tool private implementation');
    h.assertPackageSourcesDoNotContain(fullfile(root, '+labkit', '+ui', '+diag'), ...
        uiForbidden, ...
        'Reusable +labkit UI diagnostics facade');
end
