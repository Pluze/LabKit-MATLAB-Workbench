classdef GuiLayoutCicTest < matlab.uitest.TestCase
    %GUILAYOUTCICTEST Verify CIC GUI layout contracts.

    methods (Test, TestTags = {'GUI', 'Structural'})
        function cic_layout(testCase)
            setupLabKitTestPath();
            h = guiTestHelpers();
            h.assertUifigureAvailable();
            cleanup = onCleanup(@() h.closeAllFigures());

            fig = h.launchFigure('labkit_CIC_app', ...
                'Gamry CIC GUI (Voltage Transient)');
            h.assertFigureMinimumSize(fig, 1600, 900);
            h.assertComponentCounts(fig, struct('Button', 7, 'CheckBox', 6, ...
                'DropDown', 8, 'ListBox', 1, 'Table', 1, 'TextArea', 1, ...
                'Axes', 2));
            h.assertButtonContract(fig, {'Open DTA file(s)', ...
                'Open folder recursively', 'Clear all', 'Export results CSV', ...
                'Refresh plots', 'Swap top / bottom', 'Reset axes'});
            h.assertCheckboxContract(fig, { ...
                'Show debug markers', 'Show window limits', 'Shade pulse windows', ...
                'Use measured Im integration for charge (recommended)'});
            h.assertTabTitles(fig, {'Files + Analysis', 'Summary + Results', 'Log'});
            h.assertDropdownGroups(fig, [ ...
                h.dropdownGroup({'Pt (-0.6 to 0.8 V)', ...
                'PEDOT:PSS (-0.9 to 0.6 V)', 'Custom'}, 1), ...
                h.dropdownGroup({'Metadata first, then auto', 'Metadata only', ...
                'Auto from Im only'}, 1), ...
                h.dropdownGroup({'Cathodic phase', 'Anodic phase', ...
                'Total biphasic'}, 1), ...
                h.dropdownGroup({'mC/cm^2', 'uC/cm^2'}, 1), ...
                h.dropdownGroup({'Time (s)', 'Sample #'}, 2), ...
                h.dropdownGroup({'VT: Vf vs time', 'IT: Im vs time'}, 2)]);
            h.assertTableColumns(fig, {'File','Amp(A)','Emc(V)','Ema(V)', ...
                'Qc(mC/cm^2)','Qa(mC/cm^2)','Qtot(mC/cm^2)','Safe'});
            h.assertAxesContract(fig, { ...
                h.axesSpec('Top Plot', '', ''), ...
                h.axesSpec('Bottom Plot', '', '')});
            h.assertDropdownCallbacksPresent(fig);
            h.invokeButton(fig, 'Refresh plots');
            h.invokeButton(fig, 'Reset axes');
            h.invokeButton(fig, 'Clear all');
        end
    end
end
