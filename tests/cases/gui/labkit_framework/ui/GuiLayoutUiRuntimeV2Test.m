function verifyRuntimeV2()
    h = guiTestHelpers();
    h.assertUifigureAvailable();
    oldMode = getenv('LABKIT_GUI_TEST_MODE');
    setenv('LABKIT_GUI_TEST_MODE', 'hidden');
    cleanupMode = onCleanup(@() setenv('LABKIT_GUI_TEST_MODE', oldMode));
    cleanupFigures = onCleanup(@() h.closeAllFigures());
    cleanupValues = zeros(1, 0);
    renderedModels = zeros(1, 0);
    presentedCounts = zeros(1, 0);

    fig = labkit.ui.runtime.launch(@definition);
    h.waitForUiIdle(fig);
    ui = getappdata(fig, 'labkitUiRegistry');
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(runtime.definition.contractVersion == 2, ...
        'V2 definitions should launch through the v2 runtime path.');
    assert(runtime.state.project.parameters.count == 1, ...
        'Start should run as the first queued semantic event.');
    assert(runtime.metrics.stateCommits == 1 && ...
        runtime.metrics.presentationCommits == 2, ...
        'Initial presentation and Start should each commit exactly once.');
    assert(~isappdata(fig, 'labkitUiStartup') && ...
        ~isappdata(fig, 'labkitUiBusy'), ...
        'V2 startup should release readiness only after initial commits finish.');
    assert(startsWith(string(fig.Name), "Runtime V2 Probe") && ...
        endsWith(string(fig.Name), "v1.0.0 (2026-07-14)"), ...
        'runtime.launch should apply app version metadata.');
    assert(~isempty(findall(fig, 'Tag', 'labkitUiUtilityPlotMenu')) && ...
        ~isempty(findall(fig, 'Tag', 'labkitUiUtilitySaveState')), ...
        'V2 utilities should infer plot support and expose durable persistence.');
    assert(string(ui.controls.files.status.Value) == "2 inputs" && ...
        string(ui.controls.files.currentSelectedFiles().id) == "item2", ...
        'V2 control presentation should separate file inventory, selection, and status.');
    renderedBeforeSelection = numel(renderedModels);
    ui.controls.files.listbox.Value = ui.controls.files.listbox.Items{1};
    ui.controls.files.listbox.ValueChangedFcn( ...
        ui.controls.files.listbox, struct());
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(runtime.state.session.selection.fileIndex == 1, ...
        'V2 event services should decode a selected file item into its index.');
    assert(string(ui.controls.files.currentSelectedFiles().id) == "item1", ...
        'The presenter should preserve the canonical file selection.');
    assert(numel(renderedModels) == renderedBeforeSelection, ...
        'A state-only file selection must not rerun unchanged preview renderers.');

    invoke(ui.controls.increment.button);
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(runtime.state.project.parameters.count == 2, ...
        'Generated action callbacks should commit returned semantic state.');
    assert(runtime.state.session.workflow.logLines(end) == "increment", ...
        'Workflow log service should append canonical session log state.');
    assert(any(contains(string(ui.controls.appLog.textArea.Value), ...
        "increment")), ...
        'Runtime should present workflow log lines in semantic log panels.');
    assert(runtime.metrics.stateCommits == 3 && ...
        runtime.metrics.presentationCommits == 4, ...
        'Each action should produce one state and one presentation commit.');

    gain = ui.controls.gain.valueHandle;
    gain.Value = 4;
    gain.ValueChangedFcn(gain, struct());
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(runtime.state.project.parameters.gain == 4, ...
        'A layout binding should update its canonical semantic path.');
    assert(runtime.state.session.workflow.history(end) == "gainChanged", ...
        'A binding Event should run after the bound value is staged.');

    historyBeforeBinding = runtime.state.session.workflow.history;
    preset = ui.controls.boundOnly.valueHandle;
    preset.Value = "Second";
    preset.ValueChangedFcn(preset, struct());
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(runtime.state.session.selection.boundOnly == "Second", ...
        'A binding without Event should commit its canonical state path.');
    assert(isequal(runtime.state.session.workflow.history, ...
        historyBeforeBinding), ...
        'A binding without Event should not require a no-op App action.');

    beforeNestedPresentation = runtime.metrics.presentationCommits;
    invoke(ui.controls.outer.button);
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(isequal(runtime.state.session.workflow.history(end-2:end), ...
        ["outer", "outerEnd", "inner"]), ...
        'Nested services.dispatch should enqueue until the outer event commits.');
    assert(runtime.metrics.presentationCommits == beforeNestedPresentation + 2, ...
        'Outer and queued inner events should each have one visible commit.');

    invoke(ui.controls.resourceOne.button);
    invoke(ui.controls.resourceTwo.button);
    assert(isequal(cleanupValues, 1), ...
        'Replacing a scoped resource should dispose the prior resource once.');
    invoke(ui.controls.cellResource.button);
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    cellResourceValue = runtime.resources( ...
        [runtime.resources.scope] == "figure" & ...
        [runtime.resources.id] == "cellProbe").value;
    assert(iscell(cellResourceValue) && ...
        isequal(cellResourceValue, {"alpha", "beta"}), ...
        'Resource registry must retain a cell value inside one scalar entry.');
    assertThrows(@() invoke(ui.controls.failAfterResource.button), ...
        'runtimeV2Probe:ExpectedFailure');
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(any(cleanupValues == 99) && ...
        ~containsResource(runtime.resources, "event", "temporary"), ...
        'A failed event should dispose event-scoped resources.');

    beforeFailure = runtime.state;
    beforeFailureMetrics = runtime.metrics;
    assertThrows(@() invoke(ui.controls.failPresentation.button), ...
        'runtimeV2Probe:PresentationFailure');
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(isequaln(runtime.state, beforeFailure), ...
        'A presenter error should roll semantic state back atomically.');
    assert(isequal(runtime.metrics, beforeFailureMetrics), ...
        'Failed events should not count as committed state or presentation.');
    assert(contains(string(ui.controls.status.textArea.Value), ...
        "Count: " + beforeFailure.project.parameters.count), ...
        'Presenter rollback should restore the last committed visible state.');

    assertThrows(@() invoke(ui.controls.invalidState.button), ...
        'labkit:ui:runtime:InvalidState');
    runtime = getappdata(fig, 'labkitUiAppRuntime');
    assert(isequaln(runtime.state, beforeFailure), ...
        'Runtime resources in semantic state should be rejected before commit.');
    assert(~isempty(renderedModels) && renderedModels(end) == ...
        runtime.state.project.parameters.count, ...
        'Registered renderers should receive prepared models for the latest state.');
    assert(~isempty(ui.controls.main.axesById.first.Children) && ...
        ~isempty(ui.controls.main.axesById.second.Children), ...
        'A presenter should reconcile every declared axis in one preview area.');
    assert(numel(presentedCounts) >= runtime.metrics.presentationCommits, ...
        'The presenter should run for every visible commit.');

    delete(fig);
    assert(any(cleanupValues == 2), ...
        'Figure deletion should dispose remaining figure-scoped resources.');
    clear cleanupFigures cleanupMode;

