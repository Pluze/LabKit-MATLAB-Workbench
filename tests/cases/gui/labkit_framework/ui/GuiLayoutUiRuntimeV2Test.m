            h.waitForUiIdle(fig);
            runtime = getappdata(fig, 'labkitUiAppRuntime');

            testCase.verifyEmpty(fieldnames(runtime.definition.actions), ...
                'A static App should not need an action registry.');
            testCase.verifyEmpty(runtime.definition.createSession, ...
