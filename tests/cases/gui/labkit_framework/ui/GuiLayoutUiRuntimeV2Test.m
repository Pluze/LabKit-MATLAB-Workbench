        function minimal_definition_launches_without_optional_components(testCase)
            setupLabKitTestPath();
            h = guiTestHelpers();
            h.assertUifigureAvailable();
            oldMode = getenv('LABKIT_GUI_TEST_MODE');
            setenv('LABKIT_GUI_TEST_MODE', 'hidden');
