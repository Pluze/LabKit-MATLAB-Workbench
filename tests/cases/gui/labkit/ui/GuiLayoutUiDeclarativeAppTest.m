function assertStatusPanelContract(control)
    assert(isvalid(control.textArea) && strcmp(control.kind, 'statusPanel'), ...
        'statusPanel controls should expose a valid read-only text area.');
end

function assertLogPanelContract(control)
    assert(isvalid(control.textArea) && strcmp(control.kind, 'logPanel'), ...
        'logPanel controls should expose a valid read-only text area.');
end

function assertReadonlyTextFit(control)
    assert(isvalid(control.handle) && isprop(control.handle, 'Value'), ...
        'Readonly field values should render through a text-bearing handle.');
    assert(strcmp(char(string(control.handle.Value)), ...
        'Long status text should wrap and shrink inside the control instead of being clipped'), ...
        'Readonly field text should preserve the complete display value.');
    if isprop(control.handle, 'WordWrap')
        assert(strcmp(control.handle.WordWrap, 'on'), ...
            'Readonly field text should wrap by default when MATLAB supports WordWrap.');
    end
    assert(control.handle.FontSize <= 12 && control.handle.FontSize >= 10, ...
        'Readonly field text should shrink within the framework readability range.');
end

function assertLogTabFillsAvailableHeight(ui)
    logicalRowMap = ui.logGrid.UserData.LabKitLogicalRowMap;
    logRowHeight = ui.logGrid.RowHeight{logicalRowMap(1)};
    assert(strcmp(char(string(logRowHeight)), '1x'), ...
        'A single growable log section should fill the log tab height.');
    assert(isequal(ui.sections.logSection.grid.RowHeight, {'1x'}), ...
        'A logPanel section should let the log text area grow vertically.');
end

function assertMultiFilePanelContract(control)
    assert(isvalid(control.listbox) && strcmp(control.kind, 'filePanel') && ...
        isvalid(control.removeButton), ...
        'filePanel controls should expose a selectable list and remove button.');
end

function assertSingleFilePanelContract(control)
    assert(strcmp(control.kind, 'filePanel') && ...
        isvalid(control.displayField) && isvalid(control.chooseButton) && ...
        ~isfield(control, 'listbox') && ~isfield(control, 'removeButton') && ...
        ~isfield(control, 'clearButton'), ...
        'single-mode filePanel controls should expose only choose and display handles.');
    assert(strcmp(control.displayField.Type, 'uieditfield'), ...
        'single-mode filePanel should use a read-only single-line text field.');
    assert(control.chooseButton.Position(4) <= 36 && ...
        control.displayField.Position(4) <= 36, ...
        'single-mode filePanel controls should not stretch vertically with the section.');
    assert(control.displayField.Position(3) > control.chooseButton.Position(3), ...
        'single-mode filePanel should reserve most horizontal space for the filename.');
    rowHeight = control.panel.Parent.RowHeight{control.panel.Layout.Row};
    assert(isnumeric(rowHeight) && rowHeight <= 72, ...
        'single-mode filePanel should use a compact section row height.');
end

