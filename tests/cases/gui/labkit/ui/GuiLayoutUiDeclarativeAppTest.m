        h.axesSpec('Raw', 'Frame', 'Intensity'), ...
        h.axesSpec('Filtered', 'Frame', 'Intensity'), ...
        h.axesSpec('Difference', 'Frame', 'Delta')});
    assert(isfield(ui.controls, 'sourceImages') && isfield(ui.controls, 'preview'), ...
        'UI registry should expose semantic control ids.');
    assert(numel(ui.setupResizeHandles) == 3 && all(isvalid(ui.setupResizeHandles)), ...
        'Multi-section control tabs should expose a height separator after every section.');
    assert(strcmp(ui.controls.defaultOutputFolder.listbox.Items{1}, ...
        'No output folder selected') && ...
        strcmp(ui.controls.defaultOutputFolder.listbox.Value, ...
        'No output folder selected') && ...
        strcmp(ui.controls.defaultOutputFolder.status.Value, ...
        'No output folder selected'), ...
        'pathPanel should show a selected mode-aware empty prompt by default.');
    labkit.ui.view.setListItems(ui, 'defaultOutputFolder', {});
    assert(strcmp(ui.controls.defaultOutputFolder.listbox.Items{1}, ...
        'No output folder selected') && ...
        strcmp(ui.controls.defaultOutputFolder.listbox.Value, ...
