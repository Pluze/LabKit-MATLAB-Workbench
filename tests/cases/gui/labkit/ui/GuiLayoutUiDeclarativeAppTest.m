    dialogPaths = cellstr(reshape(dialogProvider(struct()), 1, []));
    drawnow;
    h.assertFigureMinimumSize(ui.figure, 1100, 760);
    h.assertTabTitles(ui.figure, {'Setup', 'Review', 'Log', 'Preview', ...
        'Inputs', 'Results'});
    h.assertButtonContract(ui.figure, {'Choose files', 'Clear', 'Run', 'Reset'});
