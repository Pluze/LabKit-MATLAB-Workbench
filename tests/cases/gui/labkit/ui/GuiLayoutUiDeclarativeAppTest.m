classdef GuiLayoutUiDeclarativeAppTest < matlab.uitest.TestCase
    %GUILAYOUTUIDECLARATIVEAPPTEST Verify UI 2.0 app builder contracts.

    methods (Test, TestTags = {'GUI', 'Structural'})
        function test_gui_layout_ui_declarative_app(testCase)
            setupLabKitTestPath();
            verify_gui_layout_ui_declarative_app();
        end
    end
end

function verify_gui_layout_ui_declarative_app()
%TEST_GUI_LAYOUT_UI_DECLARATIVE_APP Verify UI 2.0 builder and registry helpers.

    h = guiTestHelpers();
    h.assertUifigureAvailable();
    cleanup = onCleanup(@() h.closeAllFigures());
    checkExplicitSectionHeightCannotClipContent(h);

    events = {};
    spec = labkit.ui.spec.app('probeApp', 'UI 2 Probe', ...
        'position', [120 100 1100 760], ...
        'leftWidth', 390, ...
        'controlTabs', { ...
            labkit.ui.spec.tab('setup', 'Setup', { ...
                labkit.ui.spec.section('inputs', 'Inputs', { ...
                    labkit.ui.spec.pathPanel('sourceImages', 'Source images', ...
                        'mode', 'multiFile', ...
                        'selectionMode', 'single', ...
                        'status', 'No images loaded', ...
                        'emptyText', "No selection", ...
                        'dialogProvider', @dialogProvider, ...
                        'onChoose', @captureEvent, ...
                        'onSelectionChange', @captureEvent), ...
                    labkit.ui.spec.pathPanel('defaultOutputFolder', ...
                        'Output folder', ...
                        'mode', 'outputFolder'), ...
                    labkit.ui.spec.field('gain', 'Gain', ...
                        'kind', 'spinner', ...
                        'limits', [0 10], ...
                        'value', 2, ...
                        'onChange', @captureEvent), ...
                    labkit.ui.spec.panner('pan', 'Pan', ...
                        'limits', [0 10], ...
                        'value', 3, ...
                        'step', 0.5, ...
                        'onChange', @captureEvent), ...
                    labkit.ui.spec.rangeField('displayLimits', ...
                        'Display limits', ...
                        'limits', [0 1], ...
                        'value', [0.1 0.9], ...
                        'onChange', @captureEvent), ...
                    labkit.ui.spec.actionGroup('runActions', { ...
                        labkit.ui.spec.action('run', 'Run', @captureEvent, ...
                            'priority', 'primary'), ...
                        labkit.ui.spec.action('reset', 'Reset', @captureEvent)})}), ...
                labkit.ui.spec.section('notes', 'Notes', { ...
                    labkit.ui.spec.statusPanel('notesText', 'Notes', ...
                        'value', {'Ready'})}), ...
                labkit.ui.spec.section('extra', 'Extra', { ...
                    labkit.ui.spec.statusPanel('extraText', 'Extra', ...
                        'value', {'Ready'})})}), ...
            labkit.ui.spec.tab('review', 'Review', { ...
                labkit.ui.spec.section('resultsSection', 'Results', { ...
                    labkit.ui.spec.resultTable('results', 'Results', ...
                        'columns', {'Name', 'Status'}), ...
                    labkit.ui.spec.statusPanel('status', 'Status', ...
                        'value', {'Idle'})})}), ...
            labkit.ui.spec.tab('log', 'Log', { ...
                labkit.ui.spec.section('logSection', 'Log', { ...
                    labkit.ui.spec.logPanel('logPanel', 'Log')})})}, ...
        'workspace', labkit.ui.spec.workspace('workspace', 'Preview', { ...
            labkit.ui.spec.previewArea('preview', 'Preview', ...
