function settleLayout()
    drawnow;
    pause(0.5);
    drawnow;
end

function assertDefaultResizeHandleDrags(ui)
    grid = ui.setupGrid;
    for k = 1:numel(ui.setupResizeHandles)
        resizeHandle = ui.setupResizeHandles(k);
        assert(resizeHandle.Position(4) >= 5, ...
            'Resize handle should expose a visible, clickable height.');
        resizeHandle.ButtonDownFcn(resizeHandle, struct('CurrentPoint', [0 300]));
        assert(~isempty(ui.figure.WindowButtonMotionFcn) && ...
            ~isempty(ui.figure.WindowButtonUpFcn), ...
            'Resize handle press should install figure drag callbacks.');

        ui.figure.WindowButtonMotionFcn(ui.figure, struct('CurrentPoint', [0 240]));
        rowHeight = grid.RowHeight;
        topRow = resizeHandle.Layout.Row - 1;
        assert(isnumeric(rowHeight{topRow}), ...
            'Resize handle drag should convert the section above to fixed height.');
        assert(rowHeight{topRow} > 80, ...
            'Resize handle drag should resize only the section above while preserving minimum height.');

        ui.figure.WindowButtonUpFcn(ui.figure, struct());
        assert(isempty(ui.figure.WindowButtonMotionFcn) && ...
            isempty(ui.figure.WindowButtonUpFcn), ...
            'Resize handle release should clear temporary figure drag callbacks.');
        assert(strcmp(ui.figure.Pointer, 'arrow'), ...
            'Resize handle release should restore the default pointer.');
    end
end

function assertSectionsDoNotOverlapResizeHandles(ui)
    handleRows = arrayfun(@(h) h.Layout.Row, ui.setupResizeHandles);
    panels = directSectionPanels(ui.setupGrid, ui.setupResizeHandles);
    sectionPanelCount = 0;
    for k = 1:numel(panels)
        row = panels(k).Layout.Row;
        if any(handleRows == row)
            error('Section panels should not overlap physical resize-handle rows.');
        end
        sectionPanelCount = sectionPanelCount + 1;
    end
    assert(sectionPanelCount >= 3, ...
        'Declarative test probe should include at least three section panels.');
end

function panels = directSectionPanels(grid, resizeHandles)
    panels = gobjects(0);
    children = grid.Children;
    for k = 1:numel(children)
        if isa(children(k), 'matlab.ui.container.Panel') && ...
                ~any(children(k) == resizeHandles)
            panels(end + 1) = children(k);
        end
    end
end
