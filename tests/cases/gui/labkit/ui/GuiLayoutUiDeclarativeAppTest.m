    function paths = dialogProvider(~)
        dialogCalls = dialogCalls + 1;
        if dialogCalls == 1
            paths = firstDialogPaths;
        else
            paths = string(recursiveFolder);
        end
    end

    function tf = folderWarningProvider(~, fileCount, threshold)
        folderWarningCalls = folderWarningCalls + 1;
        folderWarningCount = fileCount;
        tf = fileCount > threshold;
    end

    function paths = duplicateDialogProvider(~)
        duplicateDialogCalls = duplicateDialogCalls + 1;
        assert(duplicateDialogCalls == 1, ...
            'Duplicate-file dialog provider should be called only once in this probe.');
        paths = duplicateDialogPaths;
    end

    function paths = singleDialogProvider(~)
        singleDialogCalls = singleDialogCalls + 1;
        paths = singleDialogPaths(min(singleDialogCalls, numel(singleDialogPaths)));
    end
