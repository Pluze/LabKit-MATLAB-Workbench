function checkExplicitSectionHeightCannotClipContent(h)
    spec = labkit.ui.spec.app('heightProbe', 'Height Probe', ...
        'position', [120 100 900 620], ...
        'leftWidth', 360, ...
        'controlTabs', { ...
            labkit.ui.spec.tab('setup', 'Setup', { ...
                labkit.ui.spec.section('shortSection', 'Short Section', { ...
                    labkit.ui.spec.pathPanel('files', 'Files', ...
                        'mode', 'multiFile', ...
                        'selectionMode', 'single'), ...
                    labkit.ui.spec.actionGroup('actions', { ...
                        labkit.ui.spec.action('duplicate', 'Duplicate', @noop)}), ...
                    labkit.ui.spec.field('status', 'Status', ...
                        'kind', 'readonly', ...
                        'value', 'Ready')}, ...
                    'height', 20)})}, ...
        'workspace', labkit.ui.spec.workspace('workspace', 'Preview', { ...
            labkit.ui.spec.previewArea('preview', 'Preview')}));
    ui = labkit.ui.app.create(spec);
    drawnow;
    rowHeight = ui.setupGrid.RowHeight{1};
    assert(isnumeric(rowHeight) && rowHeight > 280, ...
        'Explicit section height should be clamped to the content minimum.');
    h.closeAllFigures();
end

function assertTextPanelsHaveDefaultRoom(ui)
    settleLayout();
    assertStatusPanelContract(ui.controls.notesText);
    ui.logTab.Parent.SelectedTab = ui.logTab;
    settleLayout();
    assertLogPanelContract(ui.controls.logPanel);
    ui.setupTab.Parent.SelectedTab = ui.setupTab;
    settleLayout();
    assertPathPanelContract(ui.controls.sourceImages);
end

