% Expected caller: starter_app.run. Inputs are app callback handles. Output
% is a data-only UI 2.0 workbench spec demonstrating the current app API.
function spec = buildSpec(callbacks)
%BUILDSPEC Build the LabKit Template App UI spec.

    spec = labkit.ui.spec.app('templateApp', 'LabKit Template App', ...
        'position', [120 80 1280 760], ...
        'leftWidth', 430, ...
        'controlTabs', { ...
            labkit.ui.spec.tab('setup', 'Setup', { ...
                labkit.ui.spec.section('inputsSection', 'Inputs', { ...
                    labkit.ui.spec.pathPanel('inputs', 'Inputs', ...
                        'mode', 'multiFile', ...
                        'selectionMode', 'single', ...
                        'filters', { ...
                        {'*.mat;*.csv;*.txt;*.png;*.jpg;*.tif', ...
                        'Common lab inputs'}}, ...
                        'status', 'No inputs selected', ...
                        'emptyText', 'No inputs selected', ...
                        'onChoose', callbackValue(callbacks, 'inputsChosen'), ...
                        'onClear', callbackValue(callbacks, 'inputsCleared'), ...
                        'onSelectionChange', callbackValue(callbacks, ...
                        'inputSelectionChanged'))}, ...
                    'height', 245), ...
                labkit.ui.spec.section('optionsSection', 'Options', { ...
                    labkit.ui.spec.field('primaryValue', 'Primary value', ...
                        'kind', 'slider', ...
                        'limits', [0 10], ...
                        'value', 5, ...
                        'unit', 'a.u.', ...
                        'onChange', callbackValue(callbacks, 'settingChanged')), ...
                    labkit.ui.spec.rangeField('displayRange', ...
                        'Display range', ...
                        'limits', [0 1], ...
                        'value', [0 1], ...
                        'onChange', callbackValue(callbacks, 'settingChanged')), ...
                    labkit.ui.spec.field('mode', 'Mode', ...
                        'kind', 'dropdown', ...
                        'items', {'Preview', 'Review', 'Export'}, ...
                        'value', 'Preview', ...
                        'onChange', callbackValue(callbacks, 'settingChanged')), ...
                    labkit.ui.spec.field('enableOption', 'Enable run', ...
                        'kind', 'checkbox', ...
                        'value', true, ...
                        'onChange', callbackValue(callbacks, 'settingChanged'))}, ...
                    'height', 210), ...
                labkit.ui.spec.section('actionsSection', 'Actions', { ...
                    labkit.ui.spec.actionGroup('templateActions', { ...
                        labkit.ui.spec.action('runTemplate', ...
                            'Run template step', ...
                            callbackValue(callbacks, 'runTemplate'), ...
                            'priority', 'primary'), ...
                        labkit.ui.spec.action('resetTemplate', ...
                            'Reset', ...
                            callbackValue(callbacks, 'resetTemplate'))})}, ...
                    'height', 95)}), ...
            labkit.ui.spec.tab('review', 'Review', { ...
                labkit.ui.spec.section('summarySection', 'Summary', { ...
                    labkit.ui.spec.resultTable('summaryTable', ...
                        'Template Summary', ...
                        'columns', {'Field', 'Value'}, ...
                        'data', starter_app.view.summaryTableData(struct()))}, ...
                    'height', 210), ...
                labkit.ui.spec.section('detailsSection', 'Details', { ...
                    labkit.ui.spec.statusPanel('details', 'Details', ...
                        'value', starter_app.view.detailLines(struct()), ...
                        'height', 'flex')}, ...
                    'height', 220)}), ...
            labkit.ui.spec.tab('log', 'Log', { ...
                labkit.ui.spec.section('logSection', 'Log', { ...
                    labkit.ui.spec.logPanel('logPanel', 'Log', ...
                        'value', {'Ready.'})}, ...
                    'height', 'flex')})}, ...
        'workspace', labkit.ui.spec.workspace('workspace', 'Preview', { ...
            labkit.ui.spec.previewArea('preview', 'Preview', ...
                'layout', 'single', ...
                'axisIds', {'main'}, ...
                'axisTitles', {'Template Preview'}, ...
                'viewModes', {'Preview', 'Review', 'Export'}, ...
                'onModeChange', callbackValue(callbacks, 'previewModeChanged'))}));
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
