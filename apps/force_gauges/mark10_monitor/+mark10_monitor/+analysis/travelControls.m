function section = travelControls(prefix)
%TRAVELCONTROLS Share a single set of draft and applied plot options.
controls = { ...
    labkit.app.layout.field(prefix+"DisplacementMode",Label="Displacement",Kind="choice", ...
        Choices=mark10_monitor.analysis.travelModes(),Bind="session.analysis.travelDraft.mode"), ...
    labkit.app.layout.field(prefix+"TravelSpeed",Label="Speed magnitude (mm/min)",Kind="numeric", ...
        Bind="session.analysis.travelDraft.speed_mm_min"), ...
    labkit.app.layout.button(prefix+"ApplyTravelSettings","Apply Travel Settings", ...
        @mark10_monitor.analysis.applyTravelSettings), ...
    labkit.app.layout.statusPanel(prefix+"TravelStatus",Lines=3)};
if prefix=="monitor"
    controls = [{labkit.app.layout.field("monitorExperimentType",Label="Test type",Kind="choice", ...
        Choices=mark10_monitor.analysis.experimentTypes(),Bind="session.experiment.type", ...
        OnValueChanged=@mark10_monitor.analysis.refreshPlotReference)},controls];
end
if prefix=="analysis"
    controls = [{ ...
        labkit.app.layout.field("analysisSurfaceTime",Label="Contact time (s, -1 = unset)",Kind="numeric", ...
            Bind="session.analysis.travelDraft.contact_s")}, controls, { ...
        labkit.app.layout.button("suggestTravelContact","Suggest Contact Time", ...
            @mark10_monitor.analysis.suggestContact), ...
        labkit.app.layout.statusPanel("travelContactSuggestion",Lines=2)}];
end
section = labkit.app.layout.section(prefix+"Travel","Travel Reconstruction",controls);
end
