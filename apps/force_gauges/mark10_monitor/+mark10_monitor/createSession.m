    "forceZero_N", 0, "travelZero_mm", 0, ...
    "geometryConfirmed", false, "fitMode", "Automatic", ...
    "dataSource", "None", ...
    "manualStart_mm", 0, "manualEnd_mm", 1, ...
    "status", "Load or record data, enter specimen geometry, then analyze.", ...
    "summary", "No modulus analysis has been run.", ...
    "exportStatus", "No modulus results exported.", ...
    "resultRows", {cell(0, 11)}, ...
    "plotStrain_percent", zeros(0, 1), ...
    "plotStress_MPa", zeros(0, 1), ...
    "fitLines", {struct("strain_percent", {}, "stress_MPa", {}, ...
        "accepted", {})}, ...
    "resultRevision", 0);
end

function settings = emptySettings()
settings = struct("unit", "", "mode", "", "currentFilter", NaN, ...
    "displayFilter", NaN, "outputFormat", "", "autoOutput", NaN, ...
    "autoShutoff", NaN, "invertPolarity", false, ...
    "omitPolarity", false, "raw", "");
end
