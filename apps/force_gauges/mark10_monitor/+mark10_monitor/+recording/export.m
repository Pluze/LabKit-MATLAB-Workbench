function state = export(state, context)
%EXPORT Write the App-owned CSV, official-style LOG, and MAT outputs.
buffer = context.getResource("application", "mark10Buffer");
valid = buffer("valid");
if ~any(valid)
    context.alert("No valid monitoring samples are available.", ...
        "Export Monitoring Data");
    return;
end
choice = context.chooseOutputFile( ...
    ["*.csv", "CSV files"], "mark10_recording.csv");
if choice.Cancelled
    return;
end
csvPath = string(choice.Value);
[folder, stem, extension] = fileparts(csvPath);
if lower(string(extension)) ~= ".csv"
    csvPath = string(fullfile(folder, string(stem) + ".csv"));
end
logName = string(stem) + ".log";
logPath = fullfile(folder, logName);
matName = string(stem) + ".mat";
matPath = fullfile(folder, matName);
time = buffer("time_s");
force = buffer("force_N");
travel = buffer("travel_mm");
mode = buffer("mode");
clean = table(time(valid), force(valid), travel(valid), ...
    'VariableNames', {'Time_s', 'Force_N', 'Travel_mm'});
writetable(clean, csvPath);
mark10_monitor.recording.writeMesurGaugeLog(logPath, ...
    time(valid), force(valid), travel(valid), "N", "mm", ...
    buffer("monitoringStartedAt"));
recording = struct( ...
    "Time_s", time, "Force_N", force, "Travel_mm", travel, ...
    "ForceRawValue", buffer("forceRaw"), ...
    "TravelRawValue", buffer("travelRaw"), ...
    "ForceUnit", buffer("forceUnit"), ...
    "TravelUnit", buffer("travelUnit"), ...
    "Valid", valid, "AcquisitionMode", mode, ...
    "ExperimentType", state.session.experiment.type, ...
    "Settings", state.session.settings, ...
    "Connection", state.session.connection, ...
    "RequestedRate", state.session.acquisition.rate);
save(matPath, "recording");
state.session.export.status = "Exported: " + csvPath;
end
