% Expected caller: chrono_overlay.definition. Handlers contain only
% Chrono-owned business behavior; bindings and standard file lifecycle are
% supplied by the LabKit App runtime.
function layout = buildWorkbenchLayout()
    handlers = chrono_overlay.stateHandlers();
    files = labkit.app.layout.fileList("files", ...
        Label="Gamry DTA files", ...
        Filters=["*.DTA;*.dta", "Gamry DTA (*.DTA)", "*.*", "All files"], ...
        ChooseLabel="Add DTA files", ...
        Bind="project.inputs.sources", ...
        SelectionBind="session.selection.files", ...
        SourceRole="chrono", SourceIdPrefix="dta", Required=true);
    controls = { ...
        labkit.app.layout.tab("filesAnalysis", "Files + Analysis", { ...
            labkit.app.layout.section("filesSection", "Files", { ...
                files, ...
                labkit.app.layout.button("exportCurves", ...
                    "Export curves CSV", handlers.exportCSV)}), ...
            labkit.app.layout.section("plotOptions", "Plot Options", { ...
                labkit.app.layout.field("xAxis", Label="X axis:", ...
                    Kind="choice", ...
                    Choices=["Time (s)", "Time (ms)", "Sample #"], ...
                    Bind="project.parameters.xAxis"), ...
                labkit.app.layout.slider("lineWidth", Label="Line width:", ...
                    Limits=[0.1 10], Step=0.1, ...
                    Bind="project.parameters.lineWidth"), ...
                labkit.app.layout.field("showLegend", ...
                    Label="Show file-name legend", Kind="logical", ...
                    Bind="project.parameters.showLegend"), ...
                labkit.app.layout.field("showGrid", Label="Show grid", ...
                    Kind="logical", Bind="project.parameters.showGrid")})}), ...
        labkit.app.layout.tab("log", "Log", { ...
            labkit.app.layout.logPanel("appLog")})};
    workspace = labkit.app.layout.workspace( ...
        labkit.app.layout.plotArea("overlayPlots", ...
            AxisIds=["voltage", "current"], Renderers="overlay"));
    layout = labkit.app.layout.workbench(controls, Workspace=workspace);
end
