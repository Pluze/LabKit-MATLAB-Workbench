% App-owned explicit contract for labkit_ChronoOverlay_app. Construction is
% side-effect free and validates the complete semantic graph before GUI work.
function app = definition()
    commands = chrono_overlay.definitionActions();
    app = labkit.ui.Application( ...
        Command="labkit_ChronoOverlay_app", ...
        Id="chrono_overlay", ...
        Title="Gamry Multi-DTA Plot Export GUI", ...
        DisplayName="Chrono Overlay", ...
        Family="Electrochem", ...
        AppVersion="1.5.0", ...
        Updated="2026-07-19", ...
        Requirements=labkit.contract.requirements( ...
            "ui", ">=8 <9", "dta", ">=2.0 <3"), ...
        Project=chrono_overlay.projectSpec(), ...
        Session=@chrono_overlay.createSession, ...
        Layout=chrono_overlay.userInterface.buildWorkbenchLayout(commands), ...
        Present=@chrono_overlay.userInterface.presentWorkbench, ...
        Renderers=struct( ...
            "overlay", @chrono_overlay.userInterface.renderOverlayAxis), ...
        DebugSample=@chrono_overlay.debug.writeSamplePack);
end
