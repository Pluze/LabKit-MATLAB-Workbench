% Expected caller: chrono_overlay.ui.runApp. Input is a callback struct whose
% fields are app-owned callback handles. Output is a data-only UI 2.0 workbench
% spec for the Chrono Overlay app.
function spec = buildSpec(callbacks)

    spec = labkit.ui.spec.app("chronoOverlay", ...
        "Gamry Multi-DTA Plot Export GUI", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", plotsWorkspace());
end

function tabs = controlTabs(callbacks)
    tabs = {filesAnalysisTab(callbacks), summaryResultsTab(), logTab()};
end

function tab = filesAnalysisTab(callbacks)
    tab = labkit.ui.spec.tab("filesAnalysis", "Files + Analysis", { ...
        filesSection(callbacks), ...
        plotOptionsSection(callbacks)});
end

function tab = summaryResultsTab()
    tab = labkit.ui.spec.tab("summaryResults", "Summary + Results", { ...
        usageSection()});
end

function tab = logTab()
    tab = labkit.ui.spec.tab("log", "Log", { ...
        labkit.ui.spec.section("logSection", "Log", { ...
            labkit.ui.spec.logPanel("appLog", "Log")})});
end

function section = filesSection(callbacks)
    section = labkit.ui.spec.section("filesSection", "Files", { ...
        labkit.ui.spec.pathPanel("files", "Files", ...
            "mode", "multiFile", ...
            "selectionMode", "multiple", ...
            "chooseLabel", "Open DTA file(s)", ...
            "clearLabel", "Clear all", ...
            "filters", {'*.DTA;*.dta', 'Gamry DTA (*.DTA)'; '*.*', 'All files'}, ...
            "status", "No files loaded", ...
            "onChoose", callbackValue(callbacks, "openFilesChosen"), ...
            "onClear", callbackValue(callbacks, "clearAll"), ...
            "onSelectionChange", callbackValue(callbacks, "selectionChanged")), ...
        labkit.ui.spec.actionGroup("fileActions", { ...
            labkit.ui.spec.action("openFolder", ...
                "Open folder recursively", callbackValue(callbacks, "openFolder")), ...
            labkit.ui.spec.action("removeSelected", ...
                "Remove selected", callbackValue(callbacks, "removeSelected")), ...
            labkit.ui.spec.action("exportCurves", ...
                "Export curves CSV", callbackValue(callbacks, "exportCSV"))})});
end

function section = plotOptionsSection(callbacks)
    section = labkit.ui.spec.section("plotOptions", "Plot Options", { ...
        labkit.ui.spec.field("xAxis", "X axis:", ...
            "kind", "dropdown", ...
            "items", {'Time (s)', 'Time (ms)', 'Sample #'}, ...
            "value", "Time (s)", ...
            "onChange", callbackValue(callbacks, "plotOptionsChanged")), ...
        labkit.ui.spec.field("lineWidth", "Line width:", ...
            "kind", "spinner", ...
            "value", 1.3, ...
            "limits", [0.1 10], ...
            "step", 0.1, ...
            "onChange", callbackValue(callbacks, "plotOptionsChanged")), ...
        labkit.ui.spec.field("showLegend", ...
            "Show file-name legend", ...
            "kind", "checkbox", ...
            "value", true, ...
            "onChange", callbackValue(callbacks, "plotOptionsChanged")), ...
        labkit.ui.spec.field("showGrid", "Show grid", ...
            "kind", "checkbox", ...
            "value", true, ...
            "onChange", callbackValue(callbacks, "plotOptionsChanged"))});
end

function section = usageSection()
    section = labkit.ui.spec.section("usageSection", "Usage", { ...
        labkit.ui.spec.statusPanel("usage", "Usage", ...
            "value", { ...
            'Usage:', ...
            '1. Open multiple .DTA files.', ...
            '2. Curves are aligned to the center of the blank time between cathodic and anodic phases.', ...
            '3. Voltage and current curves will be overlaid.', ...
            '4. Export CSV columns as: TimeGapCenterAligned_s, V_*, I_*.', ...
            '5. If files have different time grids, export uses a merged aligned-time axis with interpolation.'})});
end

function workspace = plotsWorkspace()
    workspace = labkit.ui.spec.workspace("plots", "Overlay Plots", { ...
        labkit.ui.spec.previewArea("overlayPlots", "Overlay Plots", ...
            "layout", "stack", ...
            "count", 2, ...
            "axisIds", {'voltage', 'current'}, ...
            "axisTitles", {'Voltage', 'Current'}, ...
            "xLabels", {'Time (s)', 'Time (s)'}, ...
            "yLabels", {'Vf (V)', 'Im (A)'})}, ...
        "rowSpacing", 10);
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
