% App-owned implementation for eis.workbench.present within the eis product workflow.
function view = present(applicationState)
project = applicationState.project;
session = applicationState.session;
model = struct("items", session.cache.items, ...
    "options", project.parameters, ...
    "hasItems", ~isempty(session.cache.items), ...
    "viewAction", session.cache.plotViewAction);
if project.parameters.groupingEnabled
    model.items = eis.analysisRun.groupItems(model.items, project.inputs.sources, project.groups);
    model.hasItems = ~isempty(model.items);
end
summary = "No files loaded.";
if ~isempty(session.cache.items)
    summary = string(numel(session.cache.items)) + " file(s) loaded.";
end
assigned = false(numel(session.cache.items), 1);
groupLabels = repmat("(unassigned)", numel(session.cache.items), 1);
if ~isempty(project.inputs.sources)
    ids = string({project.inputs.sources.id});
    for k = 1:numel(project.groups)
        members = ismember(ids, project.groups(k).sourceIds);
        groupLabels(members) = project.groups(k).name;
        assigned(members) = true;
    end
end
names = strings(0, 1);
if ~isempty(session.cache.items)
    names = string({session.cache.items.name}).';
end
groupStatus = "Disabled: original file curves are shown. Assignments are retained.";
if project.parameters.groupingEnabled
    groupStatus = string(numel(project.groups)) + " group(s); " + ...
        string(sum(~assigned)) + ...
        " unassigned file(s) excluded. Error bars: ±1 sample SD; one scan has no SD.";
end
choices = eis.workbench.groupChoices(project.groups);
hasTarget = any(string({project.groups.name}) == project.parameters.selectedGroup);
counts = arrayfun(@(group) numel(group.sourceIds), project.groups).';
groupRows = [cellstr(string({project.groups.name}).'), num2cell(counts)];
view = labkit.app.view.Snapshot().tableData("groupSummary", groupRows, Columns=["Group" "Scans"]) ...
    .choices("selectedGroup", choices) ...
    .enabled("selectedGroup", project.parameters.groupingEnabled && ~isempty(project.groups)) ...
    .enabled("addGroup", project.parameters.groupingEnabled) ...
    .enabled("deleteGroup", project.parameters.groupingEnabled && hasTarget) ...
    .enabled("autoGroup", project.parameters.groupingEnabled && ~isempty(session.cache.items)) ...
    .tableData("groupTable", ...
    [cellstr(names), cellstr(groupLabels)], Columns=["File" "Group"]) ...
    .text("groupStatus", groupStatus) ...
    .enabled("groupName", project.parameters.groupingEnabled) ...
    .enabled("assignGroup", project.parameters.groupingEnabled && hasTarget && ~isempty(session.selection.files.Indices)) ...
    .enabled("ungroupFiles", project.parameters.groupingEnabled && ~isempty(session.selection.files.Indices)) ...
    .text("summary", summary).renderPlot( ...
    "plot", model, ViewRevision=viewportRevision( ...
        project.inputs.sources, project.parameters, project.groups, ...
        session.cache.plotViewRevision));
overviewRevision = string(jsonencode(struct( ...
    "sourceIds", sourceIds(project.inputs.sources), ...
    "impedanceUnit", string(model.options.impedanceUnit), ...
    "grouping", groupingRevision(project.parameters, project.groups), ...
    "explicitRevision", session.cache.overviewViewRevision)));
view = view.renderPlot("nyquistOverview", model, ViewRevision=overviewRevision);
view = view.renderPlot("bodeOverview", model, ViewRevision=overviewRevision);
end

function revision = viewportRevision(sources, p, groups, explicitRevision)
revision = string(jsonencode(struct( ...
    "sourceIds", sourceIds(sources), ...
    "xName", string(p.xName), "yName", string(p.yName), ...
    "impedanceUnit", string(p.impedanceUnit), ...
    "logX", logical(p.logX), "logY", logical(p.logY), ...
    "grouping", groupingRevision(p, groups), ...
    "explicitRevision", explicitRevision)));
end

function ids = sourceIds(sources)
ids = strings(1, 0);
if ~isempty(sources)
    ids = reshape(string({sources.id}), 1, []);
end
end

function value = groupingRevision(parameters, groups)
value = struct("enabled", parameters.groupingEnabled, "members", {{}});
if parameters.groupingEnabled
    value.members = {groups.sourceIds};
end
end
