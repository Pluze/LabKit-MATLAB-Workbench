function layout = buildLayout()
%BUILDLAYOUT Assemble EIS file-bound overlay controls.
axes = eis.overlayPlot.axisItems();
units = eis.impedanceDisplay.catalog();
files = labkit.app.layout.fileList("files", Label="Files", ...
    Filters=["*.DTA;*.dta", "Gamry DTA (*.DTA)", "*.*", "All files"], ...
    ChooseLabel="Add DTA files", FolderLabel="Add folder", ...
    ChooseTooltip="Add Gamry DTA files containing EIS ZCURVE impedance data.", ...
    RecursiveFolderLabel="Add folder tree", ...
    RemoveLabel="Remove selected", ClearLabel="Clear all", ...
    EmptyText="No files loaded", ...
    PathFilter=@eis.sourceFiles.matchesDtaKind, ...
    PathFilterDescription="EIS DTA", ...
    Bind="project.inputs.sources", SelectionBind="session.selection.files", ...
    SourceRole="eis", SourceIdPrefix="dta");
filesSection = labkit.app.layout.section("filesSection", "Files", { ...
    files, ...
    labkit.app.layout.button("exportPlot", "Export custom plot CSV", ...
        @eis.resultFiles.exportCurrentPlot, ...
        Tooltip="Export selected raw files, or all assigned groups with means, sample SD, and valid counts when grouping is enabled.")});
plotOptions = labkit.app.layout.section("plotOptions", "Custom Plot Options", { ...
    labkit.app.layout.field("xAxis", Label="X axis", Kind="choice", Choices=axes, Bind="project.parameters.xName"), ...
    labkit.app.layout.field("yAxis", Label="Y axis", Kind="choice", Choices=axes, Bind="project.parameters.yName"), ...
    labkit.app.layout.field("impedanceUnit", Label="Impedance unit", ...
        Kind="choice", Choices=units.choices, ...
        Bind="project.parameters.impedanceUnit"), ...
    labkit.app.layout.slider("lineWidth", Label="Line width", Limits=[.1 10], Step=.1, Bind="project.parameters.lineWidth"), ...
    labkit.app.layout.slider("markerSize", Label="Marker size", Limits=[1 20], Step=1, Bind="project.parameters.markerSize"), ...
    labkit.app.layout.field("showMarkers", Label="Show markers", Kind="logical", Bind="project.parameters.showMarkers"), ...
    labkit.app.layout.field("logX", Label="Log X", Kind="logical", Bind="project.parameters.logX"), ...
    labkit.app.layout.field("logY", Label="Log Y", Kind="logical", Bind="project.parameters.logY"), ...
    labkit.app.layout.field("showLegend", Label="Legend", Kind="logical", Bind="project.parameters.showLegend"), ...
    labkit.app.layout.field("showGrid", Label="Grid", Kind="logical", Bind="project.parameters.showGrid"), ...
    labkit.app.layout.button("fitAxes", "Fit X/Y limits", ...
        @eis.overlayPlot.fitLimits, ...
        Tooltip="Re-estimate independent X and Y limits from the plotted data and leave the axes non-equal."), ...
    labkit.app.layout.button("equalAxes", "Use equal X/Y scale", ...
        @eis.overlayPlot.restoreEqualAspect, ...
        Tooltip="Once, restore equal X/Y data units for the current plot without constraining later zooming.")});
groupSection = labkit.app.layout.section("groupSection", "Scan Groups", { ...
    labkit.app.layout.field("groupingEnabled", Label="Enable group mean ± SD", ...
        Kind="logical", Bind="project.parameters.groupingEnabled", ...
        OnValueChanged=@eis.workbench.enableGrouping), ...
    labkit.app.layout.group("newGroupRow", { ...
        labkit.app.layout.field("groupName", Label="New group name", ...
            Kind="text", Bind="project.parameters.groupName"), ...
        labkit.app.layout.button("addGroup", "Add group", @eis.workbench.addGroup, ...
            Tooltip="Create an empty sample group and select it as the assignment target.")}, Layout="horizontal"), ...
    labkit.app.layout.group("targetGroupRow", { ...
        labkit.app.layout.field("selectedGroup", Label="Target group", Kind="choice", ...
            Choices=eis.workbench.groupChoices(struct("name", {})), ...
            Bind="project.parameters.selectedGroup"), ...
        labkit.app.layout.button("deleteGroup", "Delete group", @eis.workbench.deleteGroup, ...
            Tooltip="Delete the target group and leave its scans imported but unassigned.")}, Layout="horizontal"), ...
    labkit.app.layout.group("assignGroupRow", { ...
        labkit.app.layout.button("assignGroup", "Assign selected files", @eis.workbench.assignGroup, ...
            Tooltip="Select scans in the Files list on the left, then move them to the target group."), ...
        labkit.app.layout.button("ungroupFiles", "Unassign selected files", @eis.workbench.ungroupFiles, ...
            Tooltip="Remove selected files from groups while keeping the imported scans."), ...
        labkit.app.layout.button("autoGroup", "Auto-group unassigned", @eis.workbench.autoGroup, ...
            Tooltip="Recognize identical prefixes before a final -number; keep existing assignments.")}, Layout="horizontal"), ...
    labkit.app.layout.statusPanel("groupStatus", Title="Grouping", Lines=2)});
summary = labkit.app.layout.section("summarySection", "Summary", { ...
    labkit.app.layout.statusPanel("summary", Title="Summary")});
custom = labkit.app.layout.plotArea("plot", @eis.overlayPlot.draw, ...
    Title="Custom EIS Overlay", AxisIds="main", AxisTitles="EIS Overlay", ...
    XLabels="Zreal (" + units.choices(3) + ")", ...
    YLabels="-Zimag (" + units.choices(3) + ")");
nyquist = labkit.app.layout.plotArea("nyquistOverview", @eis.overlayPlot.drawOverview, ...
    Title="Nyquist", AxisIds="nyquist", AxisTitles="Nyquist");
bode = labkit.app.layout.plotArea("bodeOverview", @eis.overlayPlot.drawOverview, ...
    Title="Bode", Layout="pair", AxisIds=["magnitude" "phase"], ...
    AxisTitles=["Impedance magnitude" "Phase"]);
workspace = labkit.app.layout.workspace(Title="EIS plots");
workspace = workspace.page("overviewPage", "Nyquist + Bode", { ...
    labkit.app.layout.button("fitOverviewAxes", "Fit all X/Y limits", ...
        @eis.overlayPlot.fitOverviewLimits, ...
        Tooltip="Refit the Nyquist, magnitude, and phase axes to their plotted data."), ...
    nyquist, bode});
workspace = workspace.page("customPage", "Custom plot", {custom});
workspace = workspace.page("groupsPage", "Groups", {groupSection, ...
    labkit.app.layout.dataTable("groupSummary", Title="Groups and scan counts", Columns=["Group" "Scans"]), ...
    labkit.app.layout.dataTable("groupTable", Title="All imported files and assignments", Columns=["File" "Group"])});
workspace = workspace.initialPage("overviewPage");
layout = labkit.app.layout.workbench({ ...
    labkit.app.layout.tab("filesAnalysis", "Files + Analysis", {filesSection, plotOptions}), ...
    labkit.app.layout.tab("summaryResults", "Summary + Results", {summary})}, ...
    Workspace=workspace, Usage=usageLines());
end

function lines = usageLines()
lines = [ ...
    "Usage:"; ...
    "1. Open one or more EIS .DTA files containing ZCURVE."; ...
    "2. Review Nyquist, magnitude, and phase together in Nyquist + Bode."; ...
    "3. Use Custom plot to choose another X/Y combination; impedance units and styling apply to both pages."; ...
    "4. Bode frequency uses a logarithmic X axis; magnitude and phase use linear Y axes."; ...
    "5. Fit all X/Y limits restores all three overview plots after zooming."; ...
    "6. Open Groups and enable group mode; choose filename auto-grouping or manual setup."; ...
    "7. Add/select/delete groups; select files on the left and assign them. Group plots show mean ± SD."; ...
    "8. CSV exports raw X/Y pairs when grouping is off, or all group means, SD, and counts when on."];
end
