function layout = buildLayout()
%BUILDLAYOUT Assemble EIS file-bound overlay controls.
axes = eis.overlayPlot.axisItems();
units = eis.impedanceDisplay.catalog();
files = labkit.app.layout.fileList("files", Label="Source files", ...
    Filters=["*.DTA;*.dta", "Gamry DTA (*.DTA)", "*.*", "All files"], ...
    ChooseLabel="Add DTA files", FolderLabel="Folder", ...
    ChooseTooltip="Add Gamry DTA files containing EIS ZCURVE impedance data.", ...
    RecursiveFolderLabel="Folder tree", ...
    RemoveLabel="Remove", ClearLabel="Clear", ...
    EmptyText="No files loaded", ShowStatus=false, ...
    PathFilter=@eis.sourceFiles.matchesDtaKind, ...
    PathFilterDescription="EIS DTA", ...
    Bind="project.inputs.sources", SelectionBind="session.selection.files", ...
    SourceRole="eis", SourceIdPrefix="dta");
frequencySection = labkit.app.layout.group("frequencySection", { ...
    labkit.app.layout.slider("nyquistMinimum", Label="Min · Hz", ...
        LabelPosition="top", ShowValue=false, LiveUpdate=true, Limits=[0 1], ...
        Bind="session.nyquist.lower", OnValueChanged=@eis.overlayPlot.setMinimumFrequency), ...
    labkit.app.layout.slider("nyquistMaximum", Label="Max · Hz", ...
        LabelPosition="top", ShowValue=false, LiveUpdate=true, Limits=[0 1], ...
        Bind="session.nyquist.upper", OnValueChanged=@eis.overlayPlot.setMaximumFrequency), ...
    labkit.app.layout.button("recommendFrequency", "Recommended", ...
        @eis.overlayPlot.useRecommendedFrequency, ...
        Tooltip="Restore the suggested overview frequency window based on arc descent and a dominant low-frequency tail. Unavailable when no clear transition is found."), ...
    labkit.app.layout.button("resetFrequency", "Full range", ...
        @eis.overlayPlot.resetFrequency, ...
        Tooltip="Restore all Nyquist frequencies. Nyquist and Bode share this range; custom plots retain all frequencies."), ...
    labkit.app.layout.button("fitOverviewAxes", "Reset X/Y", ...
        @eis.overlayPlot.fitOverviewLimits, ...
        Tooltip="Refit the Nyquist, magnitude, and phase axes to their plotted data.")}, ...
    Layout="horizontal", ColumnWidths={'1x', '1x', 100, 90, 100});
display = labkit.app.layout.section("displayOptions", "PLOT APPEARANCE · ALL VIEWS", { ...
    labkit.app.layout.field("impedanceUnit", Label="Impedance unit", ...
        Kind="choice", Choices=units.choices, Bind="project.parameters.impedanceUnit"), ...
    labkit.app.layout.slider("lineWidth", Label="Line width", LabelPosition="top", ShowValue=false, LiveUpdate=true, Limits=[.1 10], Step=.1, Bind="project.parameters.lineWidth"), ...
    labkit.app.layout.slider("markerSize", Label="Marker size", LabelPosition="top", ShowValue=false, LiveUpdate=true, Limits=[1 20], Step=1, Bind="project.parameters.markerSize"), ...
    labkit.app.layout.group("displayToggles", { ...
        labkit.app.layout.field("showMarkers", Label="Markers", Kind="logical", Bind="project.parameters.showMarkers"), ...
        labkit.app.layout.field("showLegend", Label="Legend", Kind="logical", Bind="project.parameters.showLegend"), ...
        labkit.app.layout.field("showGrid", Label="Grid", Kind="logical", Bind="project.parameters.showGrid")}, ...
        Layout="horizontal")});
plotOptions = labkit.app.layout.section("plotOptions", "Coordinates", { ...
    labkit.app.layout.group("xCoordinate", {labkit.app.layout.field("xAxis", ...
        Label="", Kind="choice", Choices=axes, Bind="project.parameters.xName")}, Title="X axis"), ...
    labkit.app.layout.group("yCoordinate", {labkit.app.layout.field("yAxis", ...
        Label="", Kind="choice", Choices=axes, Bind="project.parameters.yName")}, Title="Y axis"), ...
    labkit.app.layout.group("logScales", { ...
        labkit.app.layout.field("logX", Label="Log X", Kind="logical", Bind="project.parameters.logX"), ...
        labkit.app.layout.field("logY", Label="Log Y", Kind="logical", Bind="project.parameters.logY")}, Layout="horizontal"), ...
    labkit.app.layout.button("fitAxes", "Fit X/Y limits", @eis.overlayPlot.fitLimits), ...
    labkit.app.layout.button("equalAxes", "Use equal X/Y scale", @eis.overlayPlot.restoreEqualAspect)});
groupMode = labkit.app.layout.group("groupSection", { ...
    labkit.app.layout.field("groupingEnabled", Label="Enable group mean ± SD", ...
        Kind="logical", Bind="project.parameters.groupingEnabled", OnValueChanged=@eis.workbench.enableGrouping), ...
    labkit.app.layout.button("autoGroup", "Auto-group unassigned", @eis.workbench.autoGroup), ...
    labkit.app.layout.button("deleteGroup", "Delete group", @eis.workbench.deleteGroup)}, ...
    Layout="horizontal", ColumnWidths={'1x',160,130});
assignmentBar = labkit.app.layout.group("assignmentBar", { ...
    labkit.app.layout.field("groupName", Label="Name", Kind="text", Bind="project.parameters.groupName"), ...
    labkit.app.layout.button("addGroup", "Add group", @eis.workbench.addGroup), ...
    labkit.app.layout.field("selectedGroup", Label="Group", Kind="choice", ...
        Choices=eis.workbench.groupChoices(struct("name", {})), Bind="project.parameters.selectedGroup"), ...
    labkit.app.layout.button("assignGroup", "Assign selected files", @eis.workbench.assignGroup), ...
    labkit.app.layout.button("ungroupFiles", "Unassign selected", @eis.workbench.ungroupFiles)}, ...
    Layout="horizontal", ColumnWidths={'1x',90,'1x',140,135});
groupStatus = labkit.app.layout.statusPanel("groupStatus", Presentation="note", Lines=2);
selectionNote = labkit.app.layout.statusPanel("selectionNote", Presentation="note", Lines=2, ...
    Text="Selection controls grouping and raw export. All imported scans appear in raw overlays.");
scopeNote = labkit.app.layout.statusPanel("scopeNote", Presentation="note", Lines=2, ...
    Text="Gamry ZCURVE impedance data · full-frequency custom export.");
metric = @(id,label) labkit.app.layout.statusPanel(id, Title=label, Lines=1, Presentation="label");
summary = labkit.app.layout.section("summarySection", "SESSION SUMMARY", { ...
    labkit.app.layout.group("scanMetrics", {metric("scanCount","Loaded scans"), ...
        metric("groupCount","Scan groups")}, Layout="horizontal"), ...
    labkit.app.layout.group("plotMetrics", {metric("pointCount","Points / scan"), ...
        metric("summary","Plot mode")}, Layout="horizontal")});
exportAction = labkit.app.layout.button("exportPlot", "Export custom CSV", ...
    @eis.resultFiles.exportCurrentPlot, Tooltip="Export the selected scans or group statistics for the custom coordinates.");
custom = labkit.app.layout.plotArea("plot", eis.overlayPlot.styleAwareRenderer(@eis.overlayPlot.draw), ...
    Title="", AxisIds="main", AxisTitles="EIS Overlay", ...
    XLabels="Zreal (" + units.choices(3) + ")", ...
    YLabels="-Zimag (" + units.choices(3) + ")");
nyquist = labkit.app.layout.plotArea("nyquistOverview", eis.overlayPlot.styleAwareRenderer(@eis.overlayPlot.drawOverview), ...
    Title="", AxisIds="nyquist", AxisTitles="");
bode = labkit.app.layout.plotArea("bodeOverview", eis.overlayPlot.styleAwareRenderer(@eis.overlayPlot.drawOverview), ...
    Title="", Layout="pair", AxisIds=["magnitude" "phase"], ...
    AxisTitles=["Impedance magnitude" "Phase"]);
workspace = labkit.app.layout.workspace(Title="EIS plots");
workspace = workspace.page("overviewPage", "Nyquist + Bode", { ...
    frequencySection, nyquist, bode}, Heading="Impedance overview", ...
    Subtitle="Inspect complex impedance, magnitude and phase in a shared frequency window.", ...
    Note="The frequency window applies to the overview. Custom plots and exports use the full frequency range.");
customView = labkit.app.layout.group("customView", {custom, plotOptions}, ...
    Layout="horizontal", ColumnWidths={'1x', 210});
workspace = workspace.page("customPage", "Custom plot", customView, Heading="Custom plot", ...
    Subtitle="Choose independent coordinates across the full recorded frequency range.");
assignments = labkit.app.layout.group("assignments", { ...
    labkit.app.layout.dataTable("groupSummary", Title="Groups and scan counts", Columns=["Group" "Scans"]), ...
    labkit.app.layout.dataTable("groupTable", Title="All imported files and assignments", Columns=["File" "Group"])}, ...
    Layout="horizontal");
workspace = workspace.page("groupsPage", "Groups", {groupMode, assignmentBar, assignments, groupStatus}, Heading="Repeat-scan groups", ...
    Subtitle="Organize repeated scans by sample and compare group means and sample SD.");
workspace = workspace.initialPage("overviewPage");
layout = labkit.app.layout.workbench({ ...
    labkit.app.layout.tab("filesAnalysis", "Scans & display", {files, selectionNote, display, summary, scopeNote})}, ...
    Workspace=workspace, HeaderAction=exportAction);
end
