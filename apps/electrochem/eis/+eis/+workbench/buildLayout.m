function layout = buildLayout()
%BUILDLAYOUT Assemble EIS file-bound overlay controls.
axes = eis.overlayPlot.axisItems();
files = labkit.app.layout.fileList("files", Label="Gamry DTA files", ...
    Filters=["*.DTA;*.dta" "Gamry DTA (*.DTA)"], ...
    Bind="project.inputs.sources", SelectionBind="session.selection.files", ...
    SourceRole="eis", SourceIdPrefix="dta");
controls = {files, ...
    labkit.app.layout.button("exportPlot", "Export current plot CSV", @eis.resultFiles.exportCurrentPlot), ...
    labkit.app.layout.field("xAxis", Label="X axis", Kind="choice", Choices=axes, Bind="project.parameters.xName"), ...
    labkit.app.layout.field("yAxis", Label="Y axis", Kind="choice", Choices=axes, Bind="project.parameters.yName"), ...
    labkit.app.layout.slider("lineWidth", Label="Line width", Limits=[.1 10], Step=.1, Bind="project.parameters.lineWidth"), ...
    labkit.app.layout.slider("markerSize", Label="Marker size", Limits=[1 20], Step=1, Bind="project.parameters.markerSize"), ...
    labkit.app.layout.field("showMarkers", Label="Show markers", Kind="logical", Bind="project.parameters.showMarkers"), ...
    labkit.app.layout.field("logX", Label="Log X", Kind="logical", Bind="project.parameters.logX"), ...
    labkit.app.layout.field("logY", Label="Log Y", Kind="logical", Bind="project.parameters.logY"), ...
    labkit.app.layout.field("showLegend", Label="Legend", Kind="logical", Bind="project.parameters.showLegend"), ...
    labkit.app.layout.field("showGrid", Label="Grid", Kind="logical", Bind="project.parameters.showGrid"), ...
    labkit.app.layout.statusPanel("summary")};
layout = labkit.app.layout.workbench({ ...
    labkit.app.layout.tab("analysis", "Files + Analysis", {labkit.app.layout.section("settings", "Plot options", controls)}), ...
    labkit.app.layout.tab("log", "Log", {labkit.app.layout.logPanel("appLog")})}, ...
    Workspace=labkit.app.layout.workspace(labkit.app.layout.plotArea("plot", @eis.overlayPlot.draw)));
end
