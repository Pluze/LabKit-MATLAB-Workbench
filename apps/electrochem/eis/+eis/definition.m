% App-owned runtime definition for labkit_EIS_app. Expected caller: the
% public app entrypoint. Output is a declarative LabKit app definition; side
% effects are none.
function def = definition()
    def = labkit.ui.app.define( ...
        "Id", "eis", ...
        "Title", "Gamry EIS Multi-DTA Plot GUI", ...
        "InitialState", @eis.appLifecycle.createInitialState, ...
        "Spec", @(callbacks, state)eis.userInterface.buildWorkbenchSpec( ...
            state.axisItems, callbacks), ...
        "Actions", eis.definitionActions(), ...
        "Render", @eis.userInterface.updateWorkbenchFromState, ...
        "Startup", "startup");
end
