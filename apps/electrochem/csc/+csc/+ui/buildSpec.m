    emptyChoice = {'(none)'};
    modeItems = {'Full', 'Cathodic', 'Anodic'};

    spec = labkit.ui.spec.app("cscApp", ...
        "Gamry DTA GUI (literature CSC)", ...
        "position", [50 30 1580 950], ...
        "leftWidth", 390, ...
        "controlTabs", { ...
            labkit.ui.spec.tab("filesAnalysis", "Files + Analysis", { ...
                labkit.ui.spec.section("filesSection", "Files", { ...
                    labkit.ui.spec.pathPanel("files", "Files", ...
                        "mode", "multiFile", ...
                        "selectionMode", "single", ...
                        "chooseLabel", "Open DTA file(s)", ...
                        "clearLabel", "Clear all", ...
                        "filters", {'*.DTA;*.dta', 'Gamry DTA files (*.DTA)'}, ...
                        "status", "No files loaded", ...
                        "emptyText", "No files loaded", ...
                        "onChoose", callbackValue(callbacks, "openFilesChosen"), ...
                        "onClear", callbackValue(callbacks, "clearAll"), ...
                        "onSelectionChange", callbackValue(callbacks, "fileSelectionChanged")), ...
                    labkit.ui.spec.actionGroup("fileActions", { ...
                        labkit.ui.spec.action("openFolder", ...
                            "Open folder recursively", callbackValue(callbacks, "openFolder")), ...
                        labkit.ui.spec.action("reloadSelected", ...
                            "Reload selected", callbackValue(callbacks, "reloadSelected"))})}), ...
                labkit.ui.spec.section("curveSection", "Curve", { ...
                    labkit.ui.spec.field("filePath", "File:", ...
                        "kind", "readonly", ...
                        "value", ""), ...
                    labkit.ui.spec.field("scanRate", "Scan rate:", ...
                        "kind", "readonly", ...
                        "value", ""), ...
                    labkit.ui.spec.field("curve", "Curve:", ...
                        "kind", "dropdown", ...
                        "items", emptyChoice, ...
                        "value", emptyChoice{1}, ...
                        "onChange", callbackValue(callbacks, "curveChanged")), ...
                    labkit.ui.spec.action("autoCvCt", "Auto CV + CT", ...
                        callbackValue(callbacks, "autoPresetAndRefresh"))}), ...
                labkit.ui.spec.section("actions", "Actions", { ...
                    labkit.ui.spec.actionGroup("plotActions", { ...
                        labkit.ui.spec.action("swapPlots", ...
                            "Swap Top/Bottom", callbackValue(callbacks, "swapPlots")), ...
                        labkit.ui.spec.action("compareQ", ...
                            "Compare Q / CSC", callbackValue(callbacks, "refreshCompare")), ...
                        labkit.ui.spec.action("refreshPlots", ...
                            "Refresh Plots", callbackValue(callbacks, "refreshPlotsOnly")), ...
                        labkit.ui.spec.action("clearBoth", ...
                            "Clear Both", callbackValue(callbacks, "clearBothAxes"))})}), ...
                labkit.ui.spec.section("plotSelections", "Plot Selections", { ...
                    labkit.ui.spec.field("topX", "Top X:", ...
                        "kind", "dropdown", ...
                        "items", emptyChoice, ...
                        "value", emptyChoice{1}, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("topY", "Top Y:", ...
                        "kind", "dropdown", ...
                        "items", emptyChoice, ...
                        "value", emptyChoice{1}, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("topGrid", "Grid", ...
                        "kind", "checkbox", ...
                        "value", true, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("topHold", "Hold", ...
                        "kind", "checkbox", ...
                        "value", false), ...
                    labkit.ui.spec.field("topTrim", "Show Trim", ...
                        "kind", "checkbox", ...
                        "value", true, ...
                        "onChange", callbackValue(callbacks, "refreshCompare")), ...
                    labkit.ui.spec.field("bottomX", "Bottom X:", ...
                        "kind", "dropdown", ...
                        "items", emptyChoice, ...
                        "value", emptyChoice{1}, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("bottomY", "Bottom Y:", ...
                        "kind", "dropdown", ...
                        "items", emptyChoice, ...
                        "value", emptyChoice{1}, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("bottomGrid", "Grid", ...
                        "kind", "checkbox", ...
                        "value", true, ...
                        "onChange", callbackValue(callbacks, "refreshPlotsOnly")), ...
                    labkit.ui.spec.field("bottomHold", "Hold", ...
                        "kind", "checkbox", ...
                        "value", false), ...
                    labkit.ui.spec.field("bottomTrim", "Show Trim", ...
                        "kind", "checkbox", ...
                        "value", true, ...
                        "onChange", callbackValue(callbacks, "refreshCompare"))})}), ...
            labkit.ui.spec.tab("summaryResults", "Summary + Results", { ...
                labkit.ui.spec.section("comparisonSection", "CSC / Comparison", { ...
                    labkit.ui.spec.field("mode", "Mode:", ...
                        "kind", "dropdown", ...
                        "items", modeItems, ...
                        "value", modeItems{1}, ...
                        "onChange", callbackValue(callbacks, "refreshCompare")), ...
                    labkit.ui.spec.field("area", "Area (cm^2):", ...
                        "kind", "text", ...
                        "value", "", ...
