            labkit.ui.spec.previewArea("plotAxes", "Plots", ...
                "layout", "stack", ...
                "count", 2, ...
                "axisIds", {'top', 'bottom'}, ...
                "axisTitles", {'Top Plot', 'Bottom Plot'}, ...
                "xLabels", {'X', 'X'}, ...
                "yLabels", {'Y', 'Y'})}, ...
            "rowSpacing", 10));
end

function spec = summaryField(id, labelText)
    spec = labkit.ui.spec.field(id, labelText, ...
        "kind", "readonly", ...
        "value", "");
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
