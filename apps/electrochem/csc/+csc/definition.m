% App-owned runtime definition for labkit_CSC_app. Expected caller: the
% public app entrypoint. Output is a declarative LabKit app definition; side
% effects are none.
function def = definition()
    def = labkit.ui.app.define( ...
        "Id", "csc", ...
        "Title", "Gamry DTA GUI (literature CSC)", ...
        "InitialState", @csc.appLifecycle.createInitialState, ...
        "Spec", @(callbacks, ~) csc.userInterface.buildWorkbenchSpec(callbacks), ...
        "Actions", csc.definitionActions(), ...
        "Render", @csc.userInterface.updateWorkbenchFromState, ...
        "Startup", "startup");
end
