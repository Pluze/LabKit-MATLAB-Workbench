% App-owned implementation for csc.workbench.buildLayout within the csc product workflow.
function layout = buildLayout()
%BUILDLAYOUT Compose the CSC source, comparison, plot, and export workflow.
choices = csc.analysisRun.analysisChoices();
files = labkit.app.layout.fileList("files", ...
    Label="Files", ChooseLabel="Add DTA files", ...
    ChooseTooltip="Add Gamry CV/CT DTA data used to calculate and compare charge-storage capacity.", ...
    FolderLabel="Add folder", RecursiveFolderLabel="Add folder tree", ...
    RemoveLabel="Remove selected", ClearLabel="Clear all", ...
    EmptyText="No files loaded", ...
    Filters=["*.DTA;*.dta", "Gamry DTA files (*.DTA)"], ...
    SelectionMode="single", ...
    Bind="project.inputs.sources", ...
    SelectionBind="session.selection.files", ...
    SourceRole="cvct", SourceIdPrefix="dta", ...
    OnSelectionChanged=@csc.sourceFiles.selectFile);

sourceSection = labkit.app.layout.section("filesSection", "Files", { ...
    files, ...
    labkit.app.layout.button("reloadSelected", ...
        "Reload selected", @csc.sourceFiles.reloadSelected, ...
        Tooltip="Re-read the selected DTA file and recompute its CV/CT curves and CSC comparison.")});
curveSection = labkit.app.layout.section("curveSection", "Curve", { ...
    readonlyField("filePath", "File:"), ...
    readonlyField("scanRate", "Scan rate:"), ...
    labkit.app.layout.field("curve", Label="Curve:", Kind="choice", ...
        Choices=choices.empty, Bind="session.selection.currentCurve")});
plotSection = labkit.app.layout.section( ...
    "plotSelections", "Plot Selections", { ...
        axisChoice("topX", "Top X:", choices.empty), ...
        axisChoice("topY", "Top Y:", choices.empty), ...
        logicalField("topGrid", "Grid"), ...
        logicalField("topHold", "Hold"), ...
        logicalField("topTrim", "Show Trim"), ...
        axisChoice("bottomX", "Bottom X:", choices.empty), ...
        axisChoice("bottomY", "Bottom Y:", choices.empty), ...
        logicalField("bottomGrid", "Grid"), ...
        logicalField("bottomHold", "Hold"), ...
        logicalField("bottomTrim", "Show Trim")});

comparison = labkit.app.layout.section( ...
    "comparisonSection", "CSC / Comparison", { ...
        labkit.app.layout.field("mode", Label="Mode", Kind="choice", ...
            Choices=choices.modes, Bind="project.parameters.mode"), ...
        labkit.app.layout.field("area", Label="Area (cm^2)", Kind="text", ...
            Bind="project.parameters.area"), ...
        labkit.app.layout.field("ignoreEdgeCycles", ...
            Label="Ignore first/last cycle", Kind="logical", ...
            Bind="project.parameters.ignoreEdgeCycles"), ...
        readonlyField("qct", "CT charge / CSC:"), ...
        readonlyField("qcv", "CV charge / CSC:"), ...
        readonlyField("diff", "Difference:"), ...
        readonlyField("relativeDiff", "Relative diff:"), ...
        readonlyField("dtError", "max|dt-|dV|/v|:"), ...
        readonlyField("status", "Status:"), ...
        labkit.app.layout.dataTable("cycleResults", ...
            Title="All Cycle CSC Results"), ...
        labkit.app.layout.group("exportActions", { ...
            labkit.app.layout.button("exportResults", ...
                "Export all cycles CSV", @csc.resultFiles.exportResults, ...
                Tooltip="Export per-cycle CV charge, CT charge, CSC, and comparison diagnostics."), ...
            labkit.app.layout.button("exportVoltageCurrent", ...
                "Export CV data CSV", ...
                @csc.resultFiles.exportVoltageCurrent, ...
                Tooltip="Export the selected cyclic-voltammetry voltage and current samples used by the CSC calculation.")})});

controls = { ...
    labkit.app.layout.tab("filesAnalysis", "Files + Analysis", { ...
        sourceSection, curveSection, plotSection}), ...
    labkit.app.layout.tab("summaryResults", "Summary + Results", { ...
        comparison}), ...
    labkit.app.layout.tab("log", "Log", { ...
        labkit.app.layout.logPanel("appLog")})};
plot = labkit.app.layout.plotArea("plotAxes", ...
    @csc.analysisPlot.draw, Title="Plots", Layout="stack", ...
    AxisIds=["top", "bottom"], AxisTitles=["Top Plot", "Bottom Plot"], ...
    XLabels=["X", "X"], YLabels=["Y", "Y"]);
layout = labkit.app.layout.workbench(controls, ...
    Workspace=labkit.app.layout.workspace(plot, Title="Plots"));
end

function node = axisChoice(id, label, choices)
node = labkit.app.layout.field(id, Label=label, Kind="choice", ...
    Choices=choices, Bind="project.parameters." + id);
end

function node = logicalField(id, label)
node = labkit.app.layout.field(id, Label=label, Kind="logical", ...
    Bind="project.parameters." + id);
end

function node = readonlyField(id, label)
node = labkit.app.layout.field(id, Label=label, Kind="readonly", Value="");
end
