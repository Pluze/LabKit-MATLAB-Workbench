% Expected caller: Runtime V2. Input is a candidate CSC project. Output is
% true or the function throws for malformed sources, settings, or results.
function accepted = validateProject(project)
    buckets = ["inputs", "parameters", "annotations", "results", "extensions"];
    assert(isstruct(project) && isscalar(project) && ...
        all(isfield(project, cellstr(buckets))), ...
        'csc:InvalidProject', 'CSC project buckets are incomplete.');
    assert(isstruct(project.inputs) && isscalar(project.inputs) && ...
        isfield(project.inputs, 'sources') && ...
        isstruct(project.inputs.sources), ...
        'csc:InvalidProject', 'CSC inputs must contain source records.');
    if ~isempty(project.inputs.sources)
        assert(all(isfield(project.inputs.sources, ...
            {'id', 'required', 'role', 'reference'})), ...
            'csc:InvalidProject', ...
            'CSC sources must use the canonical source-record contract.');
    end
    p = project.parameters;
    fields = ["mode", "area", "ignoreEdgeCycles", ...
        "topX", "topY", "topGrid", "topHold", "topTrim", ...
        "bottomX", "bottomY", "bottomGrid", "bottomHold", "bottomTrim"];
    choices = csc.userInterface.analysisChoices();
    assert(isstruct(p) && isscalar(p) && ...
        all(isfield(p, cellstr(fields))) && ...
        any(string(p.mode) == choices.modes) && textScalar(p.area) && ...
        textScalar(p.topX) && textScalar(p.topY) && ...
        textScalar(p.bottomX) && textScalar(p.bottomY) && ...
        logicalScalar(p.ignoreEdgeCycles) && logicalScalar(p.topGrid) && ...
        logicalScalar(p.topHold) && logicalScalar(p.topTrim) && ...
        logicalScalar(p.bottomGrid) && logicalScalar(p.bottomHold) && ...
        logicalScalar(p.bottomTrim), ...
        'csc:InvalidProject', 'CSC project parameters are invalid.');
    assert(isstruct(project.results) && isscalar(project.results) && ...
        all(isfield(project.results, ...
        {'lastResultsExport', 'lastVoltageCurrentExport'})), ...
        'csc:InvalidProject', 'CSC result references are invalid.');
    accepted = true;
end

function tf = textScalar(value)
    tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = logicalScalar(value)
    tf = islogical(value) && isscalar(value);
end
