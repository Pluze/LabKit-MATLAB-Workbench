% Expected caller: vt_resistance.definition. Output is the version-1 durable
% project. Source records and reproducible analysis/view choices are durable;
% decoded DTA items and analyses are rebuildable session cache.
function project = createProject()
    choices = vt_resistance.userInterface.analysisChoices();
    project = struct();
    project.inputs = struct("sources", ...
        labkit.ui.runtime.emptySourceRecords());
    project.parameters = struct( ...
        "pulseMode", choices.pulseModes(1), ...
        "steadyWindow", choices.steadyWindows(1), ...
        "voltageMode", choices.voltageModes(1), ...
        "showMarkers", true, ...
        "showShading", true, ...
        "topX", choices.xAxes(1), ...
        "topY", choices.yAxes(1), ...
        "topGrid", true, ...
        "bottomX", choices.xAxes(1), ...
        "bottomY", choices.yAxes(2), ...
        "bottomGrid", true);
    project.annotations = struct();
    project.results = struct("lastExport", []);
    project.extensions = struct();
end
