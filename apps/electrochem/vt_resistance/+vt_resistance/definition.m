%DEFINE Declare VT Resistance's explicit App SDK contract.
function app = definition()
app = labkit.app.Definition( ...
    Entrypoint="labkit_VTResistance_app", AppId="vt_resistance", ...
    Title="VT Steady Resistance", DisplayName="VT Resistance", ...
    Family="Electrochem", AppVersion="1.6.3", Updated="2026-08-19", ...
    Requirements=labkit.contract.requirements("dta", ">=3 <4"), ...
    CreateState=@createInitialState, RefreshState=@refreshState, ...
    Workbench=vt_resistance.workbench.buildLayout(), ...
    PresentWorkbench=@vt_resistance.workbench.present, ...
    BuildSyntheticSample=@vt_resistance.syntheticInputs.writeSamplePack);
end

function state = createInitialState(context, initialInput)
if isempty(initialInput)
    project = vt_resistance.initialData();
else
    project = initialInput;
end
state = struct("project", project, ...
    "session", vt_resistance.createSession(project, context));
end

function state = refreshState(state, context)
state.session = vt_resistance.createSession(state.project, context);
end
