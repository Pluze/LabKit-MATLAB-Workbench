function layout = buildLayout()
%BUILDLAYOUT Compose VT Resistance's file, analysis, plot, and export flow.
choices = vt_resistance.analysisRun.analysisChoices();
files = labkit.app.layout.fileList("files", Label="Files", ...
    Filters=["*.DTA;*.dta", "Gamry DTA (*.DTA)"], SelectionMode="single", ...
    ChooseLabel="Add DTA files", FolderLabel="Add folder", ...
    RecursiveFolderLabel="Add folder tree", ...
    RemoveLabel="Remove selected", ClearLabel="Clear all", ...
    EmptyText="No files loaded", ...
    Bind="project.inputs.sources", SelectionBind="session.selection.files", ...
    SourceRole="chrono", SourceIdPrefix="dta");

analysis = labkit.app.layout.section("analysisSettings", ...
    "Analysis Settings", { ...
        choiceField("pulseMode", "Pulse detection:", choices.pulseModes, ...
            @vt_resistance.analysisRun.settingsChanged), ...
        choiceField("steadyWindow", "Steady window:", choices.steadyWindows, ...
            @vt_resistance.analysisRun.settingsChanged), ...
        choiceField("voltageMode", "Resistance voltage:", choices.voltageModes, ...
            @vt_resistance.analysisRun.settingsChanged)});
display = labkit.app.layout.section("plotDisplay", "Plot Display", { ...
    logicalField("showMarkers", "Show markers"), ...
    logicalField("showShading", "Shade windows")});
plotSelections = labkit.app.layout.section("plotSelections", ...
    "Plot Selections", { ...
    choiceField("topX", "Top X:", choices.xAxes), ...
    choiceField("topY", "Top Y:", choices.yAxes), ...
    logicalField("topGrid", "Grid"), ...
    choiceField("bottomX", "Bottom X:", choices.xAxes), ...
    choiceField("bottomY", "Bottom Y:", choices.yAxes), ...
    logicalField("bottomGrid", "Grid")});
summary = labkit.app.layout.section("currentSummary", ...
    "Current File Summary", { ...
        summaryField("controlMode", "Control mode:"), ...
        summaryField("detect", "Detection:"), ...
        summaryField("window", "Window:"), ...
        summaryField("cathIV", "Cathodic I / Vss:"), ...
        summaryField("anodIV", "Anodic I / Vss:"), ...
        summaryField("cathBase", "Cathodic baseline:"), ...
        summaryField("anodBase", "Anodic baseline:"), ...
        summaryField("cathBaseWindow", "Cath baseline window:"), ...
        summaryField("anodBaseWindow", "Anod baseline window:"), ...
        summaryField("cathR", "Cathodic R:"), ...
        summaryField("anodR", "Anodic R:"), ...
        summaryField("averageR", "Average R:"), ...
        summaryField("status", "Status:")});
results = labkit.app.layout.section("batchResults", "Batch Results", { ...
    labkit.app.layout.dataTable("results", Title="Batch Results")});

controls = { ...
    labkit.app.layout.tab("filesAnalysis", "Files + Analysis", { ...
        labkit.app.layout.section("filesSection", "Files", { ...
            files, labkit.app.layout.button("exportResults", ...
                "Export results CSV", @vt_resistance.resultFiles.exportResults)}), ...
        analysis, display, plotSelections}), ...
    labkit.app.layout.tab("summaryResults", "Summary + Results", { ...
        summary, results}), ...
    labkit.app.layout.tab("log", "Log", { ...
        labkit.app.layout.logPanel("appLog")})};
plots = labkit.app.layout.plotArea("plotAxes", ...
    @vt_resistance.analysisPlot.draw, Title="Plots", Layout="stack", ...
    AxisIds=["top", "bottom"], AxisTitles=["Top Plot", "Bottom Plot"]);
layout = labkit.app.layout.workbench(controls, ...
    Workspace=labkit.app.layout.workspace(plots, Title="Plots"));
end

function node = choiceField(id, label, choices, callback)
arguments
    id
    label
    choices
    callback = []
end
node = labkit.app.layout.field(id, Label=label, Kind="choice", ...
    Choices=choices, Bind="project.parameters." + id, ...
    OnValueChanged=callback);
end

function node = logicalField(id, label)
node = labkit.app.layout.field(id, Label=label, Kind="logical", ...
    Bind="project.parameters." + id);
end

function node = summaryField(id, label)
node = labkit.app.layout.field(id, Label=label, Kind="readonly", Value="-");
end
