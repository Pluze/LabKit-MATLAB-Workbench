    presetItems = {'Pt (-0.6 to 0.8 V)', 'PEDOT:PSS (-0.9 to 0.6 V)', 'Custom'};
    pulseModes = {'Metadata first, then auto', 'Metadata only', 'Auto from Im only'};
    cicModes = {'Cathodic phase', 'Anodic phase', 'Total biphasic'};
