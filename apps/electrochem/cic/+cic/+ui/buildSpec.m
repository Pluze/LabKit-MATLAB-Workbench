    xChoices = {'Time (s)', 'Sample #'};
    yChoices = {'VT: Vf vs time', 'IT: Im vs time'};

    spec = labkit.ui.spec.app("cicApp", ...
        "Gamry CIC GUI (Voltage Transient)", ...
        "position", [40 30 1680 980], ...
        "leftWidth", 430, ...
        "controlTabs", { ...
            labkit.ui.spec.tab("filesAnalysis", "Files + Analysis", { ...
                labkit.ui.spec.section("filesSection", "Files", { ...
                    labkit.ui.spec.pathPanel("files", "Files", ...
                        "mode", "multiFile", ...
                        "selectionMode", "single", ...
                        "chooseLabel", "Open DTA file(s)", ...
                        "clearLabel", "Clear all", ...
                        "filters", {'*.DTA;*.dta', 'Gamry DTA (*.DTA)'; '*.*', 'All files'}, ...
                        "status", "No files loaded", ...
                        "emptyText", "No files loaded", ...
                        "onChoose", callbackValue(callbacks, "openFilesChosen"), ...
                        "onClear", callbackValue(callbacks, "clearAll"), ...
                        "onSelectionChange", callbackValue(callbacks, "fileSelectionChanged")), ...
                    labkit.ui.spec.actionGroup("fileActions", { ...
                        labkit.ui.spec.action("openFolder", ...
                            "Open folder recursively", callbackValue(callbacks, "openFolder")), ...
                        labkit.ui.spec.action("exportResults", ...
                            "Export results CSV", callbackValue(callbacks, "exportResults"))})}), ...
                labkit.ui.spec.section("analysisSettings", "Analysis Settings", { ...
                    labkit.ui.spec.field("preset", "Window preset:", ...
                        "kind", "dropdown", ...
                        "items", presetItems, ...
                        "value", presetItems{1}, ...
                        "onChange", callbackValue(callbacks, "presetChanged")), ...
                    labkit.ui.spec.field("cathLimit", "Cathodic limit (V):", ...
                        "kind", "spinner", ...
                        "value", -0.6, ...
                        "limits", [-10 10], ...
                        "step", 0.01, ...
                        "valueDisplayFormat", "%.6g", ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile")), ...
                    labkit.ui.spec.field("anodLimit", "Anodic limit (V):", ...
                        "kind", "spinner", ...
                        "value", 0.8, ...
                        "limits", [-10 10], ...
                        "step", 0.01, ...
                        "valueDisplayFormat", "%.6g", ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile")), ...
                    labkit.ui.spec.field("delayUs", "Sample delay after pulse end:", ...
                        "kind", "spinner", ...
                        "value", 10, ...
                        "limits", [0 inf], ...
                        "step", 1, ...
                        "valueDisplayFormat", "%.6g", ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile")), ...
                    labkit.ui.spec.field("area", "Area override (cm^2):", ...
                        "kind", "text", ...
                        "value", "", ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile")), ...
                    labkit.ui.spec.field("pulseMode", "Pulse detection:", ...
                        "kind", "dropdown", ...
                        "items", pulseModes, ...
                        "value", pulseModes{1}, ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile")), ...
                    labkit.ui.spec.field("cicMode", "CIC summary mode:", ...
                        "kind", "dropdown", ...
                        "items", cicModes, ...
                        "value", "Total biphasic", ...
                        "onChange", callbackValue(callbacks, "refreshResultsSummary")), ...
                    labkit.ui.spec.field("cicUnit", "CIC unit:", ...
                        "kind", "dropdown", ...
                        "items", cicUnits, ...
                        "value", cicUnits{1}, ...
                        "onChange", callbackValue(callbacks, "refreshCICUnitDisplays")), ...
                    labkit.ui.spec.field("useMeasuredCurrent", ...
                        "Use measured Im integration for charge (recommended)", ...
                        "kind", "checkbox", ...
                        "value", true, ...
                        "onChange", callbackValue(callbacks, "analyzeCurrentFile"))}), ...
                labkit.ui.spec.section("plotDebug", "Plot / Debug", { ...
                    labkit.ui.spec.actionGroup("plotActions", { ...
                        labkit.ui.spec.action("refreshPlots", ...
                            "Refresh plots", callbackValue(callbacks, "refreshPlots")), ...
                        labkit.ui.spec.action("swapPlots", ...
                            "Swap top / bottom", callbackValue(callbacks, "swapPlots")), ...
                        labkit.ui.spec.action("resetAxes", ...
                            "Reset axes", callbackValue(callbacks, "resetAxes"))}), ...
                    labkit.ui.spec.field("showMarkers", "Show debug markers", ...
                        "kind", "checkbox", ...
                        "value", true, ...
