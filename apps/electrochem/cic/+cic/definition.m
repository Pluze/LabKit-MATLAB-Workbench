%DEFINE Declare CIC's explicit App SDK contract.
function app = definition()
app = labkit.app.Definition( ...
    Entrypoint="labkit_CIC_app", AppId="cic", ...
    Title="Gamry CIC GUI (Voltage Transient)", DisplayName="CIC", ...
    Family="Electrochem", AppVersion="1.6.3", Updated="2026-08-19", ...
    Requirements=labkit.contract.requirements("dta", ">=3 <4"), ...
    CreateState=@createInitialState, RefreshState=@refreshState, ...
    Workbench=cic.workbench.buildLayout(), ...
    PresentWorkbench=@cic.workbench.present, ...
    BuildSyntheticSample=@cic.syntheticInputs.writeSamplePack);
end

function state = createInitialState(context, initialInput)
if isempty(initialInput)
    project = cic.initialData();
else
    project = initialInput;
end
state = struct("project", project, ...
    "session", cic.createSession(project, context));
end

function state = refreshState(state, context)
state.session = cic.createSession(state.project, context);
end
