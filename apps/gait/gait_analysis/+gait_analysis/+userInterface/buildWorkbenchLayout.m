% Expected caller: gait_analysis.definition. Inputs are app-owned callbacks.
% Output is a data-only UI 5 workbench layout for Gait Analysis.
function layout = buildWorkbenchLayout(callbacks, ~)
    layout = labkit.ui.layout.workbench("gaitAnalysisApp", "Gait Analysis", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", gaitWorkspace(callbacks), ...
        "usageTitle", "Workflow Notes", ...
        "usage", workflowNotesLines());
end

function tabs = controlTabs(callbacks)
    tabs = {sourceTab(callbacks), optionsTab(callbacks), resultsTab(callbacks), logTab()};
end

function tab = sourceTab(callbacks)
    filters = {'*.csv;*.tsv;*.txt;*.mat', 'Pose coordinate files'; '*.*', 'All files'};
    tab = labkit.ui.layout.tab("source", "Source", { ...
        labkit.ui.layout.section("sourceSection", "Pose Data", { ...
            labkit.ui.layout.filePanel("poseFile", "Pose file", ...
                "mode", "single", ...
                "filters", filters, ...
                "chooseLabel", "Open pose file", ...
                "status", "No pose file loaded", ...
                "emptyText", "No pose file loaded", ...
                "onChoose", callbackValue(callbacks, "openPoseFile")), ...
            labkit.ui.layout.field("sourceSummary", "Source summary", ...
                "kind", "readonly", ...
                "value", "No pose file loaded")}), ...
        labkit.ui.layout.section("runSection", "Run", { ...
            labkit.ui.layout.action("runAnalysis", "Run analysis", ...
                callbackValue(callbacks, "runAnalysis"), "enabled", false), ...
            labkit.ui.layout.field("analysisStatus", "Status", ...
                "kind", "readonly", ...
                "value", "No analysis run")})});
end

function tab = optionsTab(callbacks)
    tab = labkit.ui.layout.tab("options", "Roles + Detection", { ...
        roleSection(callbacks), ...
        calibrationSection(callbacks), ...
        detectionSection(callbacks)});
end

function section = roleSection(callbacks)
    section = labkit.ui.layout.section("roleSection", "Keypoint Roles", { ...
        labkit.ui.layout.field("iliacPoint", "Iliac point", ...
            "kind", "text", "value", "iliac", ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("hipPoint", "Hip point", ...
            "kind", "text", "value", "hip", ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("kneePoint", "Knee point", ...
            "kind", "text", "value", "knee", ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("anklePoint", "Ankle point", ...
            "kind", "text", "value", "ankle", ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("footPoint", "Foot point", ...
            "kind", "text", "value", "foot", ...
            "onChange", callbackValue(callbacks, "optionsChanged"))});
end

function section = calibrationSection(callbacks)
    section = labkit.ui.layout.section("calibrationSection", "Time + Scale", { ...
        labkit.ui.layout.field("frameRate", "Frame rate Hz", ...
            "kind", "number", "value", 30, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("pixelsPerUnit", "Pixels per unit", ...
            "kind", "number", "value", 1, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("unitName", "Unit name", ...
            "kind", "text", "value", "px", ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("originAtFirstFrameFirstPoint", ...
            "Use first-frame first point as origin", ...
            "kind", "checkbox", "value", false, ...
            "onChange", callbackValue(callbacks, "optionsChanged"))});
end

function section = detectionSection(callbacks)
    section = labkit.ui.layout.section("detectionSection", "Step Detection", { ...
        labkit.ui.layout.field("smoothWindow", "Smooth window frames", ...
            "kind", "number", "value", 5, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("minStepFrames", "Min step frames", ...
            "kind", "number", "value", 3, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("maxStepFrames", "Max step frames", ...
            "kind", "number", "value", 300, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("minStride", "Min stride", ...
            "kind", "number", "value", 1, ...
            "onChange", callbackValue(callbacks, "optionsChanged")), ...
        labkit.ui.layout.field("maxBodyDrift", "Max hip drift", ...
            "kind", "number", "value", 1000000, ...
            "onChange", callbackValue(callbacks, "optionsChanged"))});
end

function tab = resultsTab(callbacks)
    tab = labkit.ui.layout.tab("results", "Results + Export", { ...
        labkit.ui.layout.section("summarySection", "Summary", { ...
            labkit.ui.layout.resultTable("summaryTable", "Summary", ...
                "columns", {'Metric', 'Value'}, ...
                "data", {'Status', 'No analysis run'})}), ...
        labkit.ui.layout.section("stepSection", "Steps", { ...
            labkit.ui.layout.resultTable("stepTable", "Step Preview", ...
                "columns", {'Step', 'Valid', 'Time_s', 'Stride'}, ...
                "data", cell(0, 4))}), ...
        labkit.ui.layout.section("exportSection", "Export", { ...
            labkit.ui.layout.action("chooseOutputFolder", "Choose output folder", ...
                callbackValue(callbacks, "chooseOutputFolder")), ...
            labkit.ui.layout.field("outputFolder", "Output folder", ...
                "kind", "readonly", ...
                "value", "No output folder chosen"), ...
            labkit.ui.layout.action("exportResults", "Export CSV set", ...
                callbackValue(callbacks, "exportResults"), "enabled", false)})});
end

function tab = logTab()
    tab = labkit.ui.layout.tab("log", "Log", { ...
        labkit.ui.layout.section("logSection", "Log", { ...
            labkit.ui.layout.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function workspace = gaitWorkspace(callbacks)
    workspace = labkit.ui.layout.workspace("gaitPreview", "Gait Preview", { ...
        labkit.ui.layout.previewArea("gaitAxes", "Gait Preview", ...
            "layout", "single", ...
            "axisIds", {'main'}, ...
            "axisTitles", {'Trajectory'}, ...
            "viewModes", {'Trajectory', 'Angles', 'Steps'}, ...
            "onModeChange", callbackValue(callbacks, "previewModeChanged"))});
end

function lines = workflowNotesLines()
    lines = { ...
        '1. Load a pose coordinate CSV, TSV, TXT, or MAT file.', ...
        '2. Map the iliac, hip, knee, ankle, and foot keypoints.', ...
        '3. Tune smoothing and step-detection thresholds, then run analysis.', ...
        '4. Review frame, step, and summary metrics before exporting CSV files.', ...
        '5. Export coordinates include raw pixel columns plus optional scaled/origin-shifted columns.'};
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
