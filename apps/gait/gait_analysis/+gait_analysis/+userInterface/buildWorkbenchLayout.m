% Expected caller: gait_analysis.definition. Inputs are app-owned callbacks.
% Output is a data-only UI 5 workbench layout for Gait Analysis.
function layout = buildWorkbenchLayout(callbacks, ~)
    layout = labkit.ui.layout.workbench("gaitAnalysisApp", "Gait Analysis", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", gaitWorkspace(callbacks), ...
        "usageTitle", "Workflow Notes", ...
        "usage", workflowNotesLines());
end

function tabs = controlTabs(callbacks)
    tabs = {sourceTab(callbacks), optionsTab(callbacks), resultsTab(callbacks), logTab()};
end

function tab = sourceTab(callbacks)
    filters = {'*.mat', 'Video Marker project or autosave (*.mat)'};
    tab = labkit.ui.layout.tab("source", "Source", { ...
        labkit.ui.layout.section("sourceSection", "Video Marker Project", { ...
            labkit.ui.layout.filePanel("poseFile", "Project or autosave", ...
                "mode", "single", ...
                "filters", filters, ...
                "chooseLabel", "Open Video Marker MAT", ...
                "status", "No Video Marker project loaded", ...
                "emptyText", "No Video Marker project loaded", ...
                "onChoose", callbackValue(callbacks, "openPoseFile")), ...
            labkit.ui.layout.field("sourceSummary", "Source summary", ...
                "kind", "readonly", ...
                "value", "No pose file loaded")}), ...
        labkit.ui.layout.section("runSection", "Run", { ...
            labkit.ui.layout.action("runAnalysis", "Run analysis", ...
                callbackValue(callbacks, "runAnalysis"), "enabled", false), ...
            labkit.ui.layout.field("analysisStatus", "Status", ...
                "kind", "readonly", ...
                "value", "No analysis run")})});
end

function tab = optionsTab(~)
    tab = labkit.ui.layout.tab("options", "Roles + Detection", { ...
        roleSection(), ...
        calibrationSection(), ...
        detectionSection()});
end

