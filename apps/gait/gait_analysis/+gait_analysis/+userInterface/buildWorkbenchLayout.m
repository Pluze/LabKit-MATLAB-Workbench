function tab = resultsTab(callbacks)
    tab = labkit.ui.layout.tab("results", "Results + Export", { ...
        labkit.ui.layout.section("summarySection", "Summary", { ...
            labkit.ui.layout.resultTable("summaryTable", "Summary", ...
                "columns", {'Metric', 'Value'}, ...
                "data", {'Status', 'No analysis run'})}), ...
        labkit.ui.layout.section("stepSection", "Steps", { ...
            labkit.ui.layout.group("stepNavigation", "Selected step", { ...
                labkit.ui.layout.action("previousStep", "Previous step", ...
                    callbackValue(callbacks, "previousStep"), "enabled", false), ...
                labkit.ui.layout.action("nextStep", "Next step", ...
                    callbackValue(callbacks, "nextStep"), "enabled", false)}), ...
            labkit.ui.layout.resultTable("stepTable", "Step Preview", ...
                "columns", {'Step', 'Valid', 'Swing_s', 'Step length'}, ...
                "data", cell(0, 4), ...
                "onSelectionChange", callbackValue(callbacks, "stepSelected"))}), ...
        labkit.ui.layout.section("exportSection", "Export", { ...
            labkit.ui.layout.action("chooseOutputFolder", "Choose output folder", ...
                callbackValue(callbacks, "chooseOutputFolder")), ...
            labkit.ui.layout.field("outputFolder", "Output folder", ...
                "kind", "readonly", ...
                "value", "No output folder chosen"), ...
            labkit.ui.layout.action("exportResults", "Export CSV set", ...
                callbackValue(callbacks, "exportResults"), "enabled", false)})});
end

function tab = logTab()
    tab = labkit.ui.layout.tab("log", "Log", { ...
        labkit.ui.layout.section("logSection", "Log", { ...
            labkit.ui.layout.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function workspace = gaitWorkspace(~)
    workspace = labkit.ui.layout.workspace("gaitPreview", "Gait Preview", { ...
        labkit.ui.layout.previewArea("gaitAxes", "Gait Preview", ...
            "layout", "stack", ...
            "axisIds", {'skeleton', 'angles', 'segments'}, ...
            "axisTitles", {'Skeleton trajectories', ...
                'Joint angles', 'Segment lengths'}, ...
            "scrollZoomAxes", {'xy', 'x', 'x'})});
end

function lines = workflowNotesLines()
    lines = { ...
        '1. Open a current Video Marker project or autosave MAT.', ...
        '2. Embedded frame rate, skeleton, calibration, and annotations are the analysis source.', ...
        '3. Loading immediately shows all overlaid skeleton trajectories.', ...
        '4. Run analysis, then select one step to review its skeleton, angles, lengths, and translations.', ...
        '5. Export coordinates include raw pixel columns plus optional scaled/origin-shifted columns.'};
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
