% App-owned implementation for figure_studio.styleLibrary.layoutSection within the figure_studio product workflow.
function section = layoutSection()
section = labkit.app.layout.section("styleSection", "Text Style", { ...
    labkit.app.layout.field("stylePreset", Label="Preset:", ...
        Kind="choice", Choices=figure_studio.styleLibrary.presetNames(), ...
        Bind="project.parameters.preset", ...
        OnValueChanged=@figure_studio.styleLibrary.applyPreset), ...
    stylePanner("titleFontSize", "Title font:", [4 96], 0.5, ...
        @titleFontChanged), ...
    stylePanner("labelFontSize", "Label font:", [4 96], 0.5, ...
        @labelFontChanged), ...
    stylePanner("tickFontSize", "Tick font:", [4 96], 0.5, ...
        @tickFontChanged), ...
    stylePanner("annotationFontSize", "Annotation font:", [4 96], 0.5, ...
        @annotationFontChanged), ...
    labkit.app.layout.field("xTickLabelAngle", ...
        Label="X tick labels:", Kind="choice", ...
        Choices=["Source", "Horizontal", "45 deg"], ...
        Bind="project.parameters.style.xTickLabelAngle", ...
        OnValueChanged=@xTickLabelAngleChanged), ...
    labkit.app.layout.field("gridVisible", Label="Grid:", ...
        Kind="choice", Choices=["Off", "On"], ...
        Bind="project.parameters.gridChoice", ...
        OnValueChanged=@gridVisibleChanged)});
end

function node = stylePanner(id, label, limits, step, callback)
node = labkit.app.layout.slider(id, Label=label, Limits=limits, Step=step, ...
    ValueDisplayFormat="%.6g", ...
    Bind="project.parameters.style." + id, OnValueChanged=callback);
end

function state = titleFontChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "titleFontSize");
end

function state = labelFontChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "labelFontSize");
end

function state = tickFontChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "tickFontSize");
end

function state = annotationFontChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "annotationFontSize");
end

function state = xTickLabelAngleChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "xTickLabelAngle");
end

function state = gridVisibleChanged(state, ~, ~)
state = figure_studio.styleLibrary.refreshStyle(state, "gridVisible");
end
