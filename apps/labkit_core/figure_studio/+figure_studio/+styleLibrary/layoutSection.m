function section = layoutSection()
section = labkit.app.layout.section("styleSection", "Style", { ...
    labkit.app.layout.field("stylePreset", Label="Preset", Kind="choice", Choices=figure_studio.styleLibrary.presetNames(), Bind="project.parameters.preset", OnValueChanged=@figure_studio.styleLibrary.applyPreset), ...
    labkit.app.layout.field("baseFontSize", Label="All font", Kind="numeric", Bind="project.parameters.style.baseFontSize", OnValueChanged=@figure_studio.styleLibrary.refreshStyle), ...
    labkit.app.layout.field("dataLineWidth", Label="Plot line", Kind="numeric", Bind="project.parameters.style.dataLineWidth", OnValueChanged=@figure_studio.styleLibrary.refreshStyle)});
end
