    "canvasWidth", 900, ...
    "canvasHeight", 725, ...
    "titleFontSize", 45, ...
    "labelFontSize", 45, ...
    "tickFontSize", 45, ...
    "annotationFontSize", 45, ...
    "legendFontSize", 45, ...
    "legendTokenWidth", 100, ...
    "dataLineWidth", 6.5, ...
    "uncertaintyLineWidth", 2.0, ...
    "boundaryLineWidth", 1.5, ...
    "referenceLineWidth", 1.5, ...
    "axesLineWidth", 1.5);
end
