%LAYOUTSECTION Declare complete axis text, locator, formatter, and tick edits.
function section = layoutSection()
section = labkit.app.layout.section("axisEditor", "Axes + Tick Labels", { ...
    labkit.app.layout.group("axisText", { ...
        textField("figureTitle", "Title", "title"), ...
        textField("figureSubtitle", "Subtitle", "subtitle"), ...
        textField("xAxisLabel", "X label", "xLabel"), ...
        textField("yAxisLabel", "Y label", "yLabel"), ...
        textField("rightYAxisLabel", "Right Y label", "yRightLabel")}), ...
    labkit.app.layout.group("axisChoice", { ...
        choiceField("axisTarget", "Edit axis", ["X", "Y", "Right Y", "Z"], ...
            @changeTarget), ...
        choiceField("axisScale", "Scale", ["linear", "log"], ...
            @changeScale), ...
        choiceField("axisDirection", "Direction", ["normal", "reverse"], ...
            @changeDirection), ...
        numericField("axisMinimum", "Minimum", [-1e100 1e100], 0.1, ...
            @changeMinimum), ...
        numericField("axisMaximum", "Maximum", [-1e100 1e100], 0.1, ...
            @changeMaximum), ...
        choiceField("axisLocation", "Position", ...
            ["auto", "bottom", "top", "left", "right", "origin"], ...
            @changeLocation)}), ...
    labkit.app.layout.group("tickPlanner", { ...
        choiceField("tickLocator", "Ticks", ...
            ["Auto", "Nice count", "Fixed step", "Explicit"], ...
            @changeLocator), ...
        numericField("tickCount", "Approx. count", [2 30], 1, ...
            @changeCount), ...
        numericField("tickStep", "Fixed step", [1e-100 1e100], 0.1, ...
            @changeStep), ...
        choiceField("tickFormatter", "Format", ...
            ["Auto", "Fixed", "Scientific", "Engineering", "Percent", "Explicit"], ...
            @changeFormatter), ...
        numericField("tickPrecision", "Precision", [0 15], 1, ...
            @changePrecision), ...
        textField("tickPrefix", "Prefix", "prefix"), ...
        textField("tickSuffix", "Suffix", "suffix")}), ...
    labkit.app.layout.dataTable("tickTable", ...
        Title="Each tick — values and text remain independent", ...
        Columns=["Value", "Label", "Show", "Level", "Rotation", ...
            "Font size", "Weight", "Color"], ...
        ColumnEditable=true(1, 8), ...
        OnCellEdited=@figure_studio.axisEditing.editTick, ...
        OnCellSelectionChanged=@figure_studio.axisEditing.selectTicks), ...
    labkit.app.layout.group("tickActions", { ...
        labkit.app.layout.button("addTick", "Add tick", ...
            @figure_studio.axisEditing.addTick), ...
        labkit.app.layout.button("deleteTicks", "Delete selected", ...
            @figure_studio.axisEditing.deleteTicks), ...
        labkit.app.layout.button("undoFigureEdit", "Undo", ...
            @figure_studio.axisEditing.undo), ...
        labkit.app.layout.button("redoFigureEdit", "Redo", ...
            @figure_studio.axisEditing.redo)})});
end

function node = choiceField(id, label, choices, callback)
node = labkit.app.layout.field(id, Label=label, Kind="choice", ...
    Choices=choices, OnValueChanged=callback);
end

function node = numericField(id, label, limits, step, callback)
node = labkit.app.layout.field(id, Label=label, Kind="numeric", ...
    Limits=limits, Step=step, OnValueChanged=callback);
end

function node = textField(id, label, target)
callbacks = struct("title", @changeTitle, "subtitle", @changeSubtitle, ...
    "xLabel", @changeXLabel, "yLabel", @changeYLabel, ...
    "yRightLabel", @changeRightYLabel, ...
    "prefix", @changePrefix, "suffix", @changeSuffix);
node = labkit.app.layout.field(id, Label=label, Kind="text", ...
    OnValueChanged=callbacks.(char(target)));
end

function state = changeTarget(state, value, ~)
value = string(value);
if upper(value) == "RIGHT Y"
    state.session.editor.axisTarget = "Right Y";
else
    state.session.editor.axisTarget = upper(value);
end
state.session.editor.selectedTickRows = zeros(0, 1);
end

