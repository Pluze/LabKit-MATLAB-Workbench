% App-owned implementation for figure_studio.workbench.buildLayout within the figure_studio product workflow.
function layout = buildLayout()
controls = {labkit.app.layout.tab("figure", "Figure", { ...
    figure_studio.sourceAxes.layoutSection()}), ...
    labkit.app.layout.tab("appearance", "Appearance", { ...
    figure_studio.styleLibrary.layoutSection(), ...
    figure_studio.styleLibrary.lineLayoutSection(), ...
    figure_studio.styleLibrary.legendLayoutSection()}), ...
    labkit.app.layout.tab("geometry", "Geometry", { ...
        figure_studio.styleLibrary.canvasLayoutSection()}), ...
    labkit.app.layout.tab("export", "Export", { ...
        figure_studio.resultFiles.layoutSection()})};
workspace = labkit.app.layout.workspace( ...
    labkit.app.layout.plotArea("preview", ...
        @figure_studio.sourceAxes.drawPreview, ...
        Title="Current Figure", AxisIds="main", ...
        AxisTitles="No figure loaded"), ...
    Title="Figure Preview");
layout = labkit.app.layout.workbench(controls, Workspace=workspace);
end
