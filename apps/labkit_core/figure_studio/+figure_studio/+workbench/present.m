% App-owned implementation for figure_studio.workbench.present within the figure_studio product workflow.
function view = present(state)
hasFigure = ~isempty(state.session.cache.plotData);
panelChoices = state.session.cache.sourcePanelChoices;
hasNativePanel = ~isempty(state.session.cache.sourceAxes) && ...
    isgraphics(state.session.cache.sourceAxes, "axes");
view = labkit.app.view.Snapshot() ...
    .text("currentSource", state.session.cache.currentSource) ...
    .text("statusSummary", state.session.workflow.status) ...
    .choices("sourcePanel", panelChoices) ...
    .value("sourcePanel", state.session.selection.panel) ...
    .enabled("saveFig", hasFigure).enabled("exportPng", hasFigure) ...
    .enabled("exportJpg", hasFigure).enabled("exportSvg", hasFigure) ...
    .enabled("exportCurrent", hasFigure) ...
    .enabled("recalculateLimits", hasFigure) ...
    .enabled("sourcePanel", hasNativePanel) ...
    .text("outputFolder", state.project.parameters.outputFolder) ...
    .renderPlot("preview", struct( ...
        "plotData", state.session.cache.plotData, ...
        "sourceAxes", state.session.cache.sourceAxes, ...
        "style", state.project.parameters.style, "preview", true));
end
