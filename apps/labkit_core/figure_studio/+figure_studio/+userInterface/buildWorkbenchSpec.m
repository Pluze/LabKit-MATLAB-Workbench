% Expected caller: figure_studio.definition. Inputs are generated callbacks and
% initial app state. Output is a data-only UI 4.x workbench spec.
function spec = buildWorkbenchSpec(callbacks, state)
    spec = labkit.ui.spec.app("figureStudio", ...
        "Figure Studio", ...
        "controlTabs", controlTabs(callbacks, state), ...
        "workspace", previewWorkspace());
end

function tabs = controlTabs(callbacks, state)
    tabs = { ...
        figureTab(callbacks, state), ...
        exportTab(callbacks, state), ...
        logTab()};
end

function tab = figureTab(callbacks, state)
    tab = labkit.ui.spec.tab("figures", "Figures", { ...
        sourceSection(callbacks, state), ...
        canvasSection(callbacks), ...
        styleSection(callbacks)});
end

function section = sourceSection(callbacks, state)
    section = labkit.ui.spec.section("sourceSection", "MATLAB Figures", { ...
        labkit.ui.spec.filePanel("figFiles", "FIG files", ...
            "selectionMode", "single", ...
            "showStatus", false, ...
            "chooseLabel", "Add FIG files or scan folder", ...
            "clearLabel", "Clear figures", ...
            "filters", {'*.fig', 'MATLAB figure (*.fig)'}, ...
            "dialogTitle", "Select MATLAB figure files or scan a folder", ...
            "status", "No FIG files loaded", ...
            "emptyText", "No FIG files loaded", ...
            "onChoose", callbackValue(callbacks, "figuresChosen"), ...
            "onRemove", callbackValue(callbacks, "figuresRemoved"), ...
            "onClear", callbackValue(callbacks, "clearFigures"), ...
            "onSelectionChange", callbackValue(callbacks, "selectionChanged")), ...
        labkit.ui.spec.field("currentSource", "Current source", ...
            "kind", "readonly", ...
            "value", char(state.currentSource)), ...
        labkit.ui.spec.field("statusSummary", "Status", ...
            "kind", "readonly", ...
            "value", char(join(state.summary, " | "))), ...
        labkit.ui.spec.group("quickExports", "", { ...
            labkit.ui.spec.action("saveFig", "Save FIG", ...
                callbackValue(callbacks, "saveFig"), "enabled", false), ...
            labkit.ui.spec.action("exportPng", "PNG", ...
                callbackValue(callbacks, "exportPng"), "enabled", false), ...
            labkit.ui.spec.action("exportJpg", "JPG", ...
                callbackValue(callbacks, "exportJpg"), "enabled", false), ...
            labkit.ui.spec.action("exportSvg", "SVG", ...
                callbackValue(callbacks, "exportSvg"), "enabled", false)})});
end

function section = styleSection(callbacks)
    section = labkit.ui.spec.section("styleSection", "Style", { ...
        labkit.ui.spec.field("stylePreset", "Preset:", ...
            "kind", "dropdown", ...
            "items", cellstr(figure_studio.styleLibrary.presetNames()), ...
            "value", "LabKit figure", ...
            "onChange", callbackValue(callbacks, "styleChanged")), ...
        stylePanner("baseFontSize", "All font:", 36, [4 96], 1, callbacks), ...
        stylePanner("titleFontSize", "Title font:", 36, [4 96], 1, callbacks), ...
        stylePanner("labelFontSize", "Label font:", 36, [4 96], 1, callbacks), ...
        stylePanner("tickFontSize", "Tick font:", 36, [4 96], 1, callbacks), ...
        stylePanner("dataLineWidth", "Plot line:", 3, [0.25 8], 0.25, callbacks), ...
        stylePanner("axesLineWidth", "Axes line:", 3, [0.25 8], 0.25, callbacks), ...
        stylePanner("gridAlpha", "Grid alpha:", 0.12, [0 1], 0.05, callbacks), ...
        labkit.ui.spec.field("gridVisible", "Grid:", ...
            "kind", "dropdown", ...
            "items", {'Off', 'On'}, ...
            "value", "Off", ...
            "onChange", callbackValue(callbacks, "styleParameterChanged"))});
end

function section = canvasSection(callbacks)
    section = labkit.ui.spec.section("canvasSection", "Canvas", { ...
        labkit.ui.spec.field("aspectPreset", "Aspect:", ...
            "kind", "dropdown", ...
            "items", {'4:3', '16:9', '1:1', '3:2', 'Custom'}, ...
            "value", "4:3", ...
            "onChange", callbackValue(callbacks, "styleParameterChanged")), ...
        stylePanner("canvasWidth", "Width px:", 720, [400 8000], 50, callbacks), ...
        stylePanner("canvasHeight", "Height px:", 540, [300 8000], 50, callbacks), ...
        stylePanner("exportScale", "Export x:", 2, [1 8], 0.5, callbacks), ...
        labkit.ui.spec.field("boundaryLines", "Boundary:", ...
            "kind", "dropdown", ...
            "items", {'Off', 'On'}, ...
            "value", "On", ...
            "onChange", callbackValue(callbacks, "styleParameterChanged"))});
end

function spec = stylePanner(id, labelText, value, limits, step, callbacks)
    spec = labkit.ui.spec.panner(id, labelText, ...
        "value", value, ...
        "limits", limits, ...
        "step", step, ...
        "onChange", callbackValue(callbacks, "styleParameterChanged"));
end

function tab = exportTab(callbacks, state)
    tab = labkit.ui.spec.tab("export", "Export", { ...
        labkit.ui.spec.section("exportSection", "Export Package", { ...
            labkit.ui.spec.field("outputFolder", "Output folder", ...
                "kind", "readonly", ...
                "value", char(state.outputFolder)), ...
            labkit.ui.spec.group("exportActions", "", { ...
                labkit.ui.spec.action("chooseOutputFolder", ...
                    "Choose output folder", callbackValue(callbacks, ...
                    "chooseOutputFolder")), ...
                labkit.ui.spec.action("exportCurrent", ...
                    "Export data + script", callbackValue(callbacks, ...
                    "exportCurrent"), "enabled", false)})})});
end

function tab = logTab()
    tab = labkit.ui.spec.tab("log", "Log", { ...
        labkit.ui.spec.section("logSection", "Log", { ...
            labkit.ui.spec.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function workspace = previewWorkspace()
    workspace = labkit.ui.spec.workspace("previewWorkspace", ...
        "Figure Preview", { ...
        labkit.ui.spec.previewArea("preview", ...
            "Current Figure", ...
            "layout", "single", ...
            "axisIds", {'main'}, ...
            "axisTitles", {'No figure loaded'})});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
