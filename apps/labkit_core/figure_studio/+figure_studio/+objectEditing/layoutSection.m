%LAYOUTSECTION Declare layers, selection, cascade, grouping, and ordering.
function section = layoutSection()
section = labkit.app.layout.section("objectEditor", "Objects + Layers", { ...
    labkit.app.layout.field("objectSelectionSummary", ...
        Label="Selection", Kind="readonly", Value="No objects selected"), ...
    labkit.app.layout.dataTable("objectTable", ...
        Title="Figure elements", ...
        Columns=["Show", "Lock", "Legend", "Type", "Role", "Name", ...
            "Group", "Axis"], ...
        ColumnEditable=[true true true false true true true true], ...
        OnCellEdited=@figure_studio.objectEditing.editObject, ...
        OnCellSelectionChanged=@figure_studio.objectEditing.selectObjects), ...
    labkit.app.layout.group("styleCascade", { ...
        labkit.app.layout.field("objectStyleScope", Label="Apply to", ...
            Kind="choice", ...
            Choices=["Selection", "Type", "Role", "Group", "Document"], ...
            OnValueChanged=@figure_studio.objectEditing.changeScope), ...
        labkit.app.layout.field("objectStyleProperty", Label="Property", ...
            Kind="choice", Choices=styleProperties(), ...
            OnValueChanged=@figure_studio.objectEditing.changeProperty), ...
        labkit.app.layout.field("objectStyleValue", Label="Value", ...
            Kind="text", OnValueChanged=@figure_studio.objectEditing.changeDraft), ...
        labkit.app.layout.button("applyObjectStyle", "Apply", ...
            @figure_studio.objectEditing.applyStyle), ...
        labkit.app.layout.button("resetObjectStyle", "Reset to parent", ...
            @figure_studio.objectEditing.resetStyle)}), ...
    labkit.app.layout.group("objectGroups", { ...
        labkit.app.layout.button("groupObjects", "Group", ...
            @figure_studio.objectEditing.group), ...
        labkit.app.layout.button("ungroupObjects", "Ungroup", ...
            @figure_studio.objectEditing.ungroup), ...
        labkit.app.layout.button("duplicateObjects", "Duplicate", ...
            @figure_studio.objectEditing.duplicate)}), ...
    labkit.app.layout.group("objectOrder", { ...
        labkit.app.layout.button("objectsToFront", "To front", ...
            @figure_studio.objectEditing.toFront), ...
        labkit.app.layout.button("objectsForward", "Forward", ...
            @figure_studio.objectEditing.forward), ...
        labkit.app.layout.button("objectsBackward", "Backward", ...
            @figure_studio.objectEditing.backward), ...
        labkit.app.layout.button("objectsToBack", "To back", ...
            @figure_studio.objectEditing.toBack)}), ...
    labkit.app.layout.group("objectTransform", { ...
        transformField("objectMoveX", "Move X", @moveX), ...
        transformField("objectMoveY", "Move Y", @moveY), ...
        scaleField("objectScaleX", "Scale X", @scaleX), ...
        scaleField("objectScaleY", "Scale Y", @scaleY), ...
        labkit.app.layout.button("applyObjectTransform", "Apply transform", ...
            @figure_studio.objectEditing.applyTransform)}), ...
    labkit.app.layout.group("objectAlignment", { ...
        alignButton("alignObjectsLeft", "Align left", @alignLeft), ...
        alignButton("alignObjectsCenter", "Center X", @alignCenter), ...
        alignButton("alignObjectsRight", "Align right", @alignRight), ...
        alignButton("alignObjectsBottom", "Align bottom", @alignBottom), ...
        alignButton("alignObjectsMiddle", "Center Y", @alignMiddle), ...
        alignButton("alignObjectsTop", "Align top", @alignTop), ...
        alignButton("distributeObjectsH", "Distribute H", @distributeH), ...
        alignButton("distributeObjectsV", "Distribute V", @distributeV)})});
end

function node = transformField(id, label, callback)
node = labkit.app.layout.field(id, Label=label, Kind="numeric", ...
    Limits=[-1e100 1e100], OnValueChanged=callback);
end

function node = scaleField(id, label, callback)
node = labkit.app.layout.field(id, Label=label, Kind="numeric", ...
    Limits=[1e-6 1e6], OnValueChanged=callback);
end

function node = alignButton(id, label, callback)
node = labkit.app.layout.button(id, label, callback);
end

function state = moveX(state, value, context), state = figure_studio.objectEditing.changeTransform(state, "dx", value, context); end
function state = moveY(state, value, context), state = figure_studio.objectEditing.changeTransform(state, "dy", value, context); end
function state = scaleX(state, value, context), state = figure_studio.objectEditing.changeTransform(state, "sx", value, context); end
function state = scaleY(state, value, context), state = figure_studio.objectEditing.changeTransform(state, "sy", value, context); end
function state = alignLeft(state, context), state = figure_studio.objectEditing.align(state, "Align left", context); end
function state = alignCenter(state, context), state = figure_studio.objectEditing.align(state, "Align center", context); end
function state = alignRight(state, context), state = figure_studio.objectEditing.align(state, "Align right", context); end
function state = alignBottom(state, context), state = figure_studio.objectEditing.align(state, "Align bottom", context); end
function state = alignMiddle(state, context), state = figure_studio.objectEditing.align(state, "Align middle", context); end
function state = alignTop(state, context), state = figure_studio.objectEditing.align(state, "Align top", context); end
function state = distributeH(state, context), state = figure_studio.objectEditing.align(state, "Distribute horizontally", context); end
function state = distributeV(state, context), state = figure_studio.objectEditing.align(state, "Distribute vertically", context); end

function values = styleProperties()
values = ["Color", "LineWidth", "LineStyle", "Marker", "MarkerSize", ...
    "MarkerFaceColor", "MarkerEdgeColor", "FaceColor", "FaceAlpha", ...
    "EdgeColor", "EdgeAlpha", "FontName", "FontSize", "FontWeight", ...
    "FontAngle", "Rotation"];
end
