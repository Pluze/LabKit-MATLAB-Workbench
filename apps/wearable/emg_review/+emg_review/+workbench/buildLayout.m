function layout = buildLayout()
    controls = labkit.app.layout.tab("settings", "Recording + Analysis", { ...
        emg_review.sourceFiles.layoutSection(), emg_review.regions.layoutSection(), ...
        emg_review.analysisRun.layoutSection()});
    wave = labkit.app.layout.plotArea("waveform", @emg_review.regions.drawWaveform, ...
        ScrollZoomAxes="x");
    spectrum = labkit.app.layout.plotArea("spectrum", @emg_review.analysisRun.drawSpectrum, ...
        Layout="stack", AxisIds=["broadband", "lineBand"], ScrollZoomAxes=["x","x"]);
    timeFrequency = labkit.app.layout.plotArea("timeFrequency", ...
        @emg_review.analysisRun.drawTimeFrequency, ScrollZoomAxes="x");
    metrics = labkit.app.layout.dataTable("metrics", Columns=[ ...
        "Pair", "Baseline start (s)", "Baseline end (s)", "Activity start (s)", ...
        "Activity end (s)", "Baseline RMS", "Activity RMS", "SNR (dB)", ...
        "Contrast (dB)", "Baseline 58–62 Hz (%)", "Activity 58–62 Hz (%)"]);
    workspace = labkit.app.layout.workspace(Title="EMG Review");
    workspace = workspace.page("waveformPage", "Waveform", wave);
    workspace = workspace.page("metricsPage", "Pair metrics", metrics);
    workspace = workspace.page("spectrumPage", "Spectrum", spectrum);
    workspace = workspace.page("timeFrequencyPage", "Time–frequency", timeFrequency);
    layout = labkit.app.layout.workbench({controls}, Workspace=workspace, ...
        Usage=["Open a recording and choose the EMG channel.", ...
        "Set both start times or auto-mark a pair, then choose Analyze EMG."]);
end
