function section = layoutSection()
    source = labkit.app.layout.fileList("recording", Label="Recording", ...
        Filters=["*.acq;*.mat;*.csv;*.tsv;*.txt", ...
        "Biosignal recordings (*.acq, *.mat, *.csv, *.tsv, *.txt)", ...
        "*.*", "All files"], ...
        SelectionMode="single", MaxFiles=1, ChooseLabel="Open recording", ...
        Bind="project.inputs.sources", SourceRole="recording", SourceIdPrefix="recording");
    channel = labkit.app.layout.field("channel", Label="EMG channel", ...
        Kind="choice", Choices="(none)", OnValueChanged=@changeChannel);
    section = labkit.app.layout.section("recordingSection", "Recording", { ...
        source, channel, labkit.app.layout.statusPanel("sourceStatus", Lines=2)});
end

function applicationState = changeChannel(applicationState, channel, ~)
    session = emg_review.sourceFiles.selectChannel(applicationState.session, string(channel));
    session.revision = session.revision + 1;
    applicationState.session = session;
end
