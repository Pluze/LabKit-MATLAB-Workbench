function section = layoutSection()
    choices = emg_review.analysisRun.bands();
    section = labkit.app.layout.section("analysis", "Analysis", { ...
        labkit.app.layout.field("band", Label="Measurement band", Kind="choice", ...
            Choices=choices, Bind="session.band", ...
            OnValueChanged=@emg_review.regions.settingsChanged), ...
        labkit.app.layout.button("analyze", "Analyze EMG", @emg_review.analysisRun.analyze), ...
        labkit.app.layout.statusPanel("analysisStatus", Lines=3), ...
        labkit.app.layout.button("exportMetrics", "Export pair metrics CSV", ...
            @emg_review.resultFiles.exportMetrics)});
end
