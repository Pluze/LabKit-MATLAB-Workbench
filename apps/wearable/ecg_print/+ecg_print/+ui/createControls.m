% Expected caller: ecg_print.ui.runApp. Input is the LabKit shell struct plus
% app callback handles. Output is a struct of app-specific UI handles used by
% the runner. Side effects are limited to constructing ECG Print controls,
% panels, tables, text areas, and axes under the supplied shell.

function controls = createControls(ui, callbacks)
%CREATECONTROLS Build ECG Print app-specific controls and axes.

    layFA = ui.filesAnalysisGrid;
    laySR = ui.summaryResultsGrid;
    layLog = ui.logGrid;

    recordingPanel = labkit.ui.view.section(layFA, 'Recording', 1, [3 2], ...
        struct('rowHeight', {repmat({'fit'}, 1, 3)}, ...
        'columnWidth', {{135, '1x'}}));
    recordingGrid = recordingPanel.grid;

    btnOpen = uibutton(recordingGrid, 'Text', 'Open recording', ...
        'ButtonPushedFcn', callbacks.onOpenRecording);
    btnOpen.Layout.Row = 1;
    btnOpen.Layout.Column = [1 2];

    txtFile = labkit.ui.view.form(recordingGrid, struct( ...
        'kind', 'readonly', ...
        'value', 'No file loaded'));
    txtFile.Layout.Row = 2;
    txtFile.Layout.Column = [1 2];

    btnPreviewHeader = uibutton(recordingGrid, 'Text', 'Preview file header', ...
        'ButtonPushedFcn', callbacks.onPreviewHeader);
    btnPreviewHeader.Layout.Row = 3;
    btnPreviewHeader.Layout.Column = [1 2];

    importPanel = labkit.ui.view.section(layFA, 'Import Parsing', 2, [8 2], ...
        struct('rowHeight', {repmat({'fit'}, 1, 8)}, ...
        'columnWidth', {{135, '1x'}}));
    importGrid = importPanel.grid;

    txtImportStatus = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'readonly', ...
        'value', 'Open a recording to inspect import settings.'));
    txtImportStatus.Layout.Row = 1;
    txtImportStatus.Layout.Column = [1 2];

    [lblHeaderLine, edtHeaderLine] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'CSV header line:', ...
        'value', 0, ...
        'limits', [0 Inf], ...
        'step', 1, ...
        'callback', callbacks.onImportOptionChanged));
    lblHeaderLine.Layout.Row = 2;
    lblHeaderLine.Layout.Column = 1;
    edtHeaderLine.Layout.Row = 2;
    edtHeaderLine.Layout.Column = 2;

    [lblHasHeader, ddHasHeader] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'CSV header:', ...
        'items', {{'Auto', 'Yes', 'No'}}, ...
        'value', 'Auto', ...
        'callback', callbacks.onImportOptionChanged));
    lblHasHeader.Layout.Row = 3;
    lblHasHeader.Layout.Column = 1;
    ddHasHeader.Layout.Row = 3;
    ddHasHeader.Layout.Column = 2;

    [lblTimeColumn, edtTimeColumn] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'edit', ...
        'label', 'Time column:', ...
        'style', 'text', ...
        'value', '', ...
        'callback', callbacks.onImportOptionChanged));
    lblTimeColumn.Layout.Row = 4;
    lblTimeColumn.Layout.Column = 1;
    edtTimeColumn.Layout.Row = 4;
    edtTimeColumn.Layout.Column = 2;

    [lblTimeUnit, ddTimeUnit] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Time unit:', ...
        'items', {{'Auto', 'seconds', 'milliseconds', 'microseconds', 'nanoseconds'}}, ...
        'value', 'Auto', ...
        'callback', callbacks.onImportOptionChanged));
    lblTimeUnit.Layout.Row = 5;
    lblTimeUnit.Layout.Column = 1;
    ddTimeUnit.Layout.Row = 5;
    ddTimeUnit.Layout.Column = 2;

    [lblSignalColumns, edtSignalColumns] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'edit', ...
        'label', 'Signal columns:', ...
        'style', 'text', ...
        'value', '', ...
        'callback', callbacks.onImportOptionChanged));
    lblSignalColumns.Layout.Row = 6;
    lblSignalColumns.Layout.Column = 1;
    edtSignalColumns.Layout.Row = 6;
    edtSignalColumns.Layout.Column = 2;

    [lblFallbackFs, edtFallbackFs] = labkit.ui.view.form(importGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Fallback Fs:', ...
        'value', 2000, ...
        'limits', [0 Inf], ...
        'step', 100, ...
        'callback', callbacks.onImportOptionChanged));
    lblFallbackFs.Layout.Row = 7;
    lblFallbackFs.Layout.Column = 1;
    edtFallbackFs.Layout.Row = 7;
    edtFallbackFs.Layout.Column = 2;

    btnRefreshImport = uibutton(importGrid, 'Text', 'Parse / refresh file', ...
        'ButtonPushedFcn', callbacks.onRefreshImport);
    btnRefreshImport.Layout.Row = 8;
    btnRefreshImport.Layout.Column = [1 2];

    channelPanel = labkit.ui.view.section(layFA, 'Channel + ROI', 3, [3 2], ...
        struct('rowHeight', {repmat({'fit'}, 1, 3)}, ...
        'columnWidth', {{135, '1x'}}));
    channelGrid = channelPanel.grid;

    [lblChannel, ddChannel] = labkit.ui.view.form(channelGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Channel:', ...
        'items', {{'(none)'}}, ...
        'value', '(none)', ...
        'callback', callbacks.onChannelChanged));
    lblChannel.Layout.Row = 1;
    lblChannel.Layout.Column = 1;
    ddChannel.Layout.Row = 1;
    ddChannel.Layout.Column = 2;

    [lblStart, edtStart] = labkit.ui.view.form(channelGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'ROI start (s):', ...
        'value', 0, ...
        'limits', [0 Inf], ...
        'step', 1));
    lblStart.Layout.Row = 2;
    lblStart.Layout.Column = 1;
    edtStart.Layout.Row = 2;
    edtStart.Layout.Column = 2;

    [lblEnd, edtEnd] = labkit.ui.view.form(channelGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'ROI end (s):', ...
        'value', 0, ...
        'limits', [0 Inf], ...
        'step', 1));
    lblEnd.Layout.Row = 3;
    lblEnd.Layout.Column = 1;
    edtEnd.Layout.Row = 3;
    edtEnd.Layout.Column = 2;

    procPanel = labkit.ui.view.section(layFA, 'Signal Processing + SNR', 4, [9 2], ...
        struct('rowHeight', {repmat({'fit'}, 1, 9)}, ...
        'columnWidth', {{135, '1x'}}));
    procGrid = procPanel.grid;

    [lblLow, edtLow] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Bandpass low Hz:', ...
        'value', 0.5, ...
        'limits', [0 Inf], ...
        'step', 0.1));
    lblLow.Layout.Row = 1;
    lblLow.Layout.Column = 1;
    edtLow.Layout.Row = 1;
    edtLow.Layout.Column = 2;

    [lblHigh, edtHigh] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Bandpass high Hz:', ...
        'value', 40, ...
        'limits', [0 Inf], ...
        'step', 1));
    lblHigh.Layout.Row = 2;
    lblHigh.Layout.Column = 1;
    edtHigh.Layout.Row = 2;
    edtHigh.Layout.Column = 2;

    [lblPeakMethod, ddPeakMethod] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Peak method:', ...
        'items', {{'QRS streaming', 'Pan-Tompkins', 'Local peaks'}}, ...
        'value', 'QRS streaming'));
    lblPeakMethod.Layout.Row = 3;
    lblPeakMethod.Layout.Column = 1;
    ddPeakMethod.Layout.Row = 3;
    ddPeakMethod.Layout.Column = 2;

    [lblPeakDist, edtPeakDist] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Peak distance (s):', ...
        'value', 0.28, ...
        'limits', [0.01 Inf], ...
        'step', 0.01));
    lblPeakDist.Layout.Row = 4;
    lblPeakDist.Layout.Column = 1;
    edtPeakDist.Layout.Row = 4;
    edtPeakDist.Layout.Column = 2;

    [lblWin, edtWin] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Segment half win (s):', ...
        'value', 0.7, ...
        'limits', [0.01 Inf], ...
        'step', 0.05));
    lblWin.Layout.Row = 5;
    lblWin.Layout.Column = 1;
    edtWin.Layout.Row = 5;
    edtWin.Layout.Column = 2;

    [lblTopN, edtTopN] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Template top N:', ...
        'value', 30, ...
        'limits', [1 Inf], ...
        'step', 1));
    lblTopN.Layout.Row = 6;
    lblTopN.Layout.Column = 1;
    edtTopN.Layout.Row = 6;
    edtTopN.Layout.Column = 2;

    [lblSmooth, edtSmooth] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'spinner', ...
        'label', 'Smooth beats:', ...
        'value', 15, ...
        'limits', [1 Inf], ...
        'step', 1, ...
        'callback', callbacks.onRefreshPlots));
    lblSmooth.Layout.Row = 7;
    lblSmooth.Layout.Column = 1;
    edtSmooth.Layout.Row = 7;
    edtSmooth.Layout.Column = 2;

    [lblView, ddTemplateView] = labkit.ui.view.form(procGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Template plot:', ...
        'items', {{'Template + residual band', 'Template + segments'}}, ...
        'value', 'Template + residual band', ...
        'callback', callbacks.onRefreshPlots));
    lblView.Layout.Row = 8;
    lblView.Layout.Column = 1;
    ddTemplateView.Layout.Row = 8;
    ddTemplateView.Layout.Column = 2;

    btnAnalyze = uibutton(procGrid, 'Text', 'Analyze current ROI', ...
        'ButtonPushedFcn', callbacks.onAnalyze);
    btnAnalyze.Layout.Row = 9;
    btnAnalyze.Layout.Column = [1 2];

    exportPanel = labkit.ui.view.section(layFA, 'Exports', 5, [2 1], ...
        struct('rowHeight', {{'fit','fit'}}));
    exportGrid = exportPanel.grid;
    btnExportSegments = uibutton(exportGrid, 'Text', 'Export segment SNR CSV', ...
        'ButtonPushedFcn', callbacks.onExportSegments);
    btnExportSegments.Layout.Row = 1;
    btnExportOverlay = uibutton(exportGrid, 'Text', 'Export waveform PNG', ...
        'ButtonPushedFcn', callbacks.onExportWaveform);
    btnExportOverlay.Layout.Row = 2;

    labkit.ui.view.panel(layFA, 'text', 'Workflow Notes', 6, { ...
        '1. Open MAT/CSV data, select a numeric channel, and optionally set a time ROI.', ...
        '2. Use File Header Preview and Import Parsing only when CSV/text auto-detection needs correction.', ...
        '3. Analysis filters the selected channel with edge padding, then crops the filtered signal to the ROI for peak/SNR measurement.'});

    summaryTable = uitable(laySR, 'ColumnName', {'Metric','Value'}, ...
        'Data', ecg_print.view.initialSummaryRows());
    labkit.ui.view.place(summaryTable, laySR, 1);

    previewUi = labkit.ui.view.panel(laySR, 'text', 'File Header Preview', 2, ...
        {'Open a CSV/text file, then use Preview file header.'});
    txtFilePreview = previewUi.textArea;

    logUi = labkit.ui.view.panel(layLog, 'log', 1, {'Ready.'});
    txtLog = logUi.textArea;

    waveAxes = uiaxes(ui.rightGrid);
    waveAxes.Layout.Row = 1;
    noiseAxes = uiaxes(ui.rightGrid);
    noiseAxes.Layout.Row = 2;
    snrAxes = uiaxes(ui.rightGrid);
    snrAxes.Layout.Row = 3;
    templateAxes = uiaxes(ui.rightGrid);
    templateAxes.Layout.Row = 4;

    controls = struct( ...
        'txtFile', txtFile, ...
        'txtImportStatus', txtImportStatus, ...
        'edtHeaderLine', edtHeaderLine, ...
        'ddHasHeader', ddHasHeader, ...
        'edtTimeColumn', edtTimeColumn, ...
        'ddTimeUnit', ddTimeUnit, ...
        'edtSignalColumns', edtSignalColumns, ...
        'edtFallbackFs', edtFallbackFs, ...
        'ddChannel', ddChannel, ...
        'edtStart', edtStart, ...
        'edtEnd', edtEnd, ...
        'edtLow', edtLow, ...
        'edtHigh', edtHigh, ...
        'ddPeakMethod', ddPeakMethod, ...
        'edtPeakDist', edtPeakDist, ...
        'edtWin', edtWin, ...
        'edtTopN', edtTopN, ...
        'edtSmooth', edtSmooth, ...
        'ddTemplateView', ddTemplateView, ...
        'summaryTable', summaryTable, ...
        'txtFilePreview', txtFilePreview, ...
        'txtLog', txtLog, ...
        'waveAxes', waveAxes, ...
        'noiseAxes', noiseAxes, ...
        'snrAxes', snrAxes, ...
        'templateAxes', templateAxes);
end
