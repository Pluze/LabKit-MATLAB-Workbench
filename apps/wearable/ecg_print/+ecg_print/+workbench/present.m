function view = present(applicationState)
cache=applicationState.session.cache; parameters=applicationState.project.parameters;
model=ecg_print.analysisRun.previewModels(cache);
choices=string(cache.channelItems);channel=string(parameters.channel);
if ~any(channel==choices),channel=choices(1);end
duration=0;
if ~isempty(cache.signal),duration=cache.signal.time(end);end
rangeLimits=[0 max(eps,duration)];
debug=ecg_print.analysisRun.debugModel(cache, ...
    applicationState.session.debugOverlay);
recording=ecg_print.analysisRun.recordingModel(cache,parameters);
result=cache.ecgNext;hasResult=~isempty(result)&&result.ok;
sourceIds = strings(1,0);
if ~isempty(applicationState.project.inputs.sources)
    sourceIds = string({applicationState.project.inputs.sources.id});
end
revision = string(jsonencode(struct('sourceIds',{sourceIds}, ...
    'resultRevision',cache.plotViewRevision)));
rangePending=hasResult && (parameters.roiStart~=result.parameters.roiStart || parameters.roiEnd~=result.parameters.roiEnd);
model.recording=recording;model.showRecording=~hasResult || rangePending;
view=ecg_print.sourceFiles.present(applicationState) ...
    .limits("roiStart",rangeLimits).limits("roiEnd",rangeLimits) ...
    .value("roiStart",parameters.roiStart).value("roiEnd",parameters.roiEnd) ...
    .enabled("roiStart",duration>0).enabled("roiEnd",duration>0) ...
    .text("recordingRange",sprintf('File %.3f s | selected %.3f s',duration,parameters.roiEnd-parameters.roiStart)) ...
    .text("debugDescription",debug.description) ...
    .renderPlot("debugAxes",debug,ViewRevision=revision+":"+string(debug.overlay)) ...
    .choices("channel",choices).value("channel",channel) ...
    .enabled("channel",~isempty(cache.signal)&&~applicationState.session.importDirty) ...
    .enabled("analyze",~isempty(cache.signal)&&~applicationState.session.importDirty) ...
    .text("analysisStatus",applicationState.session.analysisStatus) ...
    .tableData("summaryTable",ecg_print.analysisRun.summaryRows(result)) ...
    .tableData("beatTable",model.beats) ...
    .text("filePreview",strjoin(string(cache.filePreview),newline)) ...
    .renderPlot("resultsAxes",model,ViewRevision=revision+":"+string(model.showRecording)) ...
    .include(ecg_print.resultFiles.present(hasResult,hasResult));
end
