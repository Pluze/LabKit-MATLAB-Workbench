function layout = buildLayout()
%BUILDLAYOUT One file-to-beat ECGNExT workflow.
sources = ecg_print.sourceFiles.layoutSections();
analysis = ecg_print.analysisRun.layoutSections();
debugControls = labkit.app.layout.section("debugSettings","SNR inputs",{ ...
    labkit.app.layout.field("debugOverlay",Label="Overlay signals",Kind="logical",Bind="session.debugOverlay"), ...
    labkit.app.layout.statusPanel("debugDescription",Title="Calculation",Text="Analyze a recording.",Lines=2)});
controls = {labkit.app.layout.tab("analysisControls","Recording + Analysis", ...
    [sources(1),analysis,{debugControls,ecg_print.resultFiles.layoutSection()}]), ...
    labkit.app.layout.tab("importControls","Import Settings", ...
    [sources(2),{labkit.app.layout.section("headerSection","File header",{ ...
    labkit.app.layout.statusPanel("filePreview",Text="Open a recording.")})}])};
results = labkit.app.layout.plotArea("resultsAxes",@ecg_print.analysisRun.drawResults, ...
    Layout="stack",AxisIds=["wave","noise","peak","ratio"],ScrollZoomAxes=["x","x","x","x"]);
workspace = labkit.app.layout.workspace(Title="ECG Analysis");
workspace = workspace.page("resultsPage","Results",{results});
debug = labkit.app.layout.plotArea("debugAxes",@ecg_print.analysisRun.drawDebug, ...
    Layout="stack",AxisIds=["raw","template","residual","noise","metricNoise","beatNoise","beatPeak","beatSnr"], ...
    ScrollZoomAxes=repmat("x",1,8));
workspace = workspace.page("debugPage","Signal chain",{debug});
workspace = workspace.initialPage("resultsPage");
layout = labkit.app.layout.workbench(controls,Workspace=workspace, ...
    UsageTitle="Workflow",Usage=[ ...
    "Open a recording, choose the ECG channel, then Analyze ECG.", ...
    "Long files use overlapping ECGNExT windows automatically.", ...
    "Results shows noise, QRS amplitude and SNR for every beat; Signal chain preserves ECGNExT noise."]);
end
