function layout = buildLayout()
controls = { ...
    labkit.app.layout.tab("filesAnalysis", "Files + Analysis", { ...
        ecg_print.sourceFiles.layoutSection(), ...
        ecg_print.analysisRun.layoutSection(), ...
        ecg_print.resultFiles.layoutSection()}), ...
    labkit.app.layout.tab("summaryResults", "Summary + Results", { ...
        labkit.app.layout.dataTable("summaryTable", Columns=["Metric", "Value"]), ...
        labkit.app.layout.statusPanel("filePreview")}), ...
    labkit.app.layout.tab("log", "Log", {labkit.app.layout.logPanel("appLog")})};
workspace = labkit.app.layout.workspace(labkit.app.layout.plotArea("previewAxes", ...
    @ecg_print.analysisRun.drawPreview, AxisIds=["wave", "noise", "snr", "template"]));
layout = labkit.app.layout.workbench(controls, Workspace=workspace);
end
