function view = present(applicationState)
recording = applicationState.session.cache.recording;
hasSource = ~isempty(applicationState.project.inputs.sources);
hasAcqClock = ~isempty(recording) && recording.metadata.sourceKind == "biopac_acq";
view = labkit.app.view.Snapshot() ...
    .text("importStatus", string(applicationState.session.workflow.importStatus)) ...
    .enabled("previewHeader", hasSource && ~hasAcqClock) ...
    .enabled("refreshImport", hasSource) ...
    .enabled("headerLine", ~hasAcqClock) ...
    .enabled("hasHeader", ~hasAcqClock) ...
    .enabled("timeColumn", ~hasAcqClock) ...
    .enabled("timeUnit", ~hasAcqClock) ...
    .enabled("signalColumns", ~hasAcqClock) ...
    .enabled("fallbackFs", ~hasAcqClock);
end
