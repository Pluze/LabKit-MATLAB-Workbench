function sections = layoutSections()
%LAYOUTSECTIONS Present one analysis configuration and beat navigation.
sections = {labkit.app.layout.section("analysisSection","Analyze ECG",{ ...
    labkit.app.layout.field("channel",Label="Channel",Kind="choice", ...
        Choices="(none)",Bind="project.parameters.channel", ...
        OnValueChanged=@ecg_print.analysisRun.changeChannel), ...
    field("roiStart","Start (s)",[0 1],.1), ...
    field("roiEnd","End (s)",[0 1],.1), ...
    labkit.app.layout.field("recordingRange",Label="Duration / selection",Kind="readonly"), ...
    labkit.app.layout.field("peakMethod",Label="R-peak detector",Kind="choice", ...
        Choices=["QRS streaming","Pan-Tompkins","Local peaks"], ...
        Bind="project.parameters.peakMethod",OnValueChanged=@ecg_print.analysisRun.settingsChanged), ...
    field("peakDistance","Minimum RR (s)",[.201 10],.01), ...
    labkit.app.layout.button("analyze","Analyze ECG",@ecg_print.analysisRun.analyze), ...
    labkit.app.layout.field("analysisStatus",Label="Analysis",Kind="readonly",Value="Ready to analyze.")}), ...
    labkit.app.layout.section("beatSection","Results",{ ...
    labkit.app.layout.dataTable("summaryTable",Columns=["Metric","Mean / value","Variance","n"]), ...
    labkit.app.layout.dataTable("beatTable",Columns=["Beat","R time (s)","Window","QRS p-p", ...
        "Noise RMS (NST-centered)","SNR (dB)","Noise samples","Status"])})};
end
function node = field(id,label,limits,step)
node = labkit.app.layout.slider(id,Label=label,Limits=limits,Step=step, ...
    Bind="project.parameters."+id,OnValueChanged=@ecg_print.analysisRun.settingsChanged);
end
