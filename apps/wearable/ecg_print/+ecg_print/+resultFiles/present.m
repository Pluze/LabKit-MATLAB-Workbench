function view = present(hasMeasurements, hasWaveform)
view = labkit.app.view.Snapshot() ...
    .enabled("exportStatistics",hasMeasurements) ...
    .enabled("exportEcgNext", hasMeasurements) ...
    .enabled("exportRegionWorkspace", hasWaveform) ...
    .enabled("exportRegionFile", hasWaveform) ...
    .enabled("exportSegments", hasMeasurements) ...
    .enabled("exportWaveform", hasWaveform);
end
