% Expected caller: Runtime V2. Input is a candidate Response Review Stats
% project. Output is true or this function throws for malformed durable state.
function accepted = validateProject(project)
    buckets = ["inputs", "parameters", "annotations", "results", "extensions"];
    assert(isstruct(project) && isscalar(project) && ...
        all(isfield(project, cellstr(buckets))), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats project buckets are incomplete.');
    assert(isstruct(project.inputs) && isscalar(project.inputs) && ...
        isfield(project.inputs, 'sources'), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats sources are incomplete.');
    sources = project.inputs.sources;
    assert(isstruct(sources) && (isempty(sources) || ...
        all(isfield(sources, {'id', 'required', 'role', 'reference'}))), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats source records are invalid.');
    parameters = project.parameters;
    assert(isstruct(parameters) && isscalar(parameters) && ...
        all(isfield(parameters, {'baselineWindowSec', 'noiseWindowSec'})) && ...
        validRange(parameters.baselineWindowSec) && ...
        validRange(parameters.noiseWindowSec), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats metric windows are invalid.');
    assert(isstruct(project.annotations) && isscalar(project.annotations), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats annotations are invalid.');
    assert(isstruct(project.results) && isscalar(project.results) && ...
        isfield(project.results, 'lastExport'), ...
        'response_review_stats:InvalidProject', ...
        'Response Review Stats result state is invalid.');
    accepted = true;
end

function tf = validRange(value)
    value = double(value);
    tf = isequal(size(value), [1 2]) && all(isfinite(value));
end
