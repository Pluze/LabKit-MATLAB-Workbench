% App-owned durable RHS Preview contract. Runtime V2 applies the single
% source-schema migration, then validates preview settings, role-based source
% collections, durable annotations, and compact export state.
function spec = projectSpec()
    spec = struct( ...
        "Version", 2, ...
        "Create", @createProject, ...
        "Validate", @validateProject, ...
        "Migrate", @migrateProject);
end

function project = createProject()
    project = struct();
    project.inputs = struct( ...
        "sources", labkit.ui.runtime.emptySourceRecords());
    project.parameters = struct( ...
        "family", "amplifier", ...
        "maxPreviewChannels", 8);
    project.annotations = struct( ...
        "protocol", struct(), ...
        "previewChannelRows", table(), ...
        "filterLabels", strings(0, 1), ...
        "filterComments", strings(0, 1));
    project.results = struct( ...
        "lastProtocolExport", [], ...
        "lastFilterExport", []);
    project.extensions = struct();
end

function project = migrateProject(project, fromVersion)
    switch double(fromVersion)
        case 1
            project.inputs.sources = [project.inputs.rhsSource, ...
                project.inputs.protocolSource, project.inputs.filterSources];
            project.inputs = rmfield(project.inputs, ...
                {'rhsSource', 'protocolSource', 'filterSources'});
        otherwise
            error('rhs_preview:UnsupportedProjectMigration', ...
                'RHS Preview cannot migrate project version %d.', fromVersion);
    end
end

function accepted = validateProject(project)
    buckets = ["inputs", "parameters", "annotations", "results", "extensions"];
    assert(isstruct(project) && isscalar(project) && ...
        all(isfield(project, cellstr(buckets))), ...
        'rhs_preview:InvalidProject', 'RHS Preview project buckets are incomplete.');
    assert(isstruct(project.inputs) && isscalar(project.inputs) && ...
        isfield(project.inputs, 'sources'), ...
        'rhs_preview:InvalidProject', 'RHS Preview sources are incomplete.');
    sources = project.inputs.sources;
    assert(isstruct(sources) && (isempty(sources) || ...
        all(isfield(sources, {'id', 'required', 'role', 'reference'}))), ...
        'rhs_preview:InvalidProject', 'RHS Preview source records are invalid.');
    ids = string({sources.id});
    roles = string({sources.role});
    assert(all(strlength(ids) > 0) && numel(unique(ids)) == numel(ids) && ...
        all(ismember(roles, ["recording", "protocol", "filterRecording"])) && ...
        nnz(roles == "recording") <= 1 && nnz(roles == "protocol") <= 1, ...
        'rhs_preview:InvalidProject', 'RHS Preview source roles are invalid.');
    parameters = project.parameters;
    assert(isstruct(parameters) && isscalar(parameters) && ...
        all(isfield(parameters, {'family', 'maxPreviewChannels'})) && ...
        isscalar(string(parameters.family)) && ...
        strlength(string(parameters.family)) > 0 && ...
        finiteScalar(parameters.maxPreviewChannels) && ...
        parameters.maxPreviewChannels >= 1, ...
        'rhs_preview:InvalidProject', 'RHS Preview parameters are invalid.');
    annotations = project.annotations;
    assert(isstruct(annotations) && isscalar(annotations) && ...
        all(isfield(annotations, {'protocol', 'previewChannelRows', ...
        'filterLabels', 'filterComments'})) && ...
        isstruct(annotations.protocol) && ...
        istable(annotations.previewChannelRows) && ...
        isstring(annotations.filterLabels) && ...
        isstring(annotations.filterComments), ...
        'rhs_preview:InvalidProject', 'RHS Preview annotations are invalid.');
    assert(isstruct(project.results) && isscalar(project.results) && ...
        all(isfield(project.results, ...
        {'lastProtocolExport', 'lastFilterExport'})), ...
        'rhs_preview:InvalidProject', 'RHS Preview result state is invalid.');
    accepted = true;
end

function tf = finiteScalar(value)
    tf = isnumeric(value) && isscalar(value) && isfinite(double(value));
end
