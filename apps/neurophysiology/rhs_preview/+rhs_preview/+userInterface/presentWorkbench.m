% Expected caller: Runtime V2. Input is canonical RHS Preview state. Output
% is deterministic controls, tables, waveform model, and controlled interval
% interaction with no UI registry access or side effects.
function view = presentWorkbench(state)
    context = previewContext(state);
    selection = rhs_preview.userInterface.channelSelection( ...
        context.info, state.project.parameters.family, "");
    bounds = rhs_preview.analysisRun.previewWindowBounds(context);
    hasChannels = rhs_preview.analysisRun.hasReadableChannel(context);
    hasRows = height(context.previewChannelRows) > 0;
    hasFilters = height(context.filterRows) > 0;
    rhsSources = roleSources(state, "recording");
    filterSources = roleSources(state, "filterRecording");
    protocolSources = roleSources(state, "protocol");

    view = struct();
    view.controls.rhsFile = sourcePanel( ...
        rhsSources, "No RHS file selected");
    view.controls.rhsFolder = sourcePanel( ...
        filterSources, "No RHS files selected");
    view.controls.protocolFile = sourcePanel( ...
        protocolSources, "No protocol selected");
    view.controls.channelFamily = struct();
    view.controls.channelFamily.Items = cellstr(selection.families);
    view.controls.channelFamily.Value = selection.family;
    view.controls.channelFamily.Enabled = selection.hasChannels;
    view.controls.windowStartPanner = struct( ...
        "Limits", [0 max(bounds.maxStartSec, eps)], ...
        "Enabled", bounds.hasIndexedDuration && bounds.maxStartSec > 0);
    view.controls.windowSummary = valueSpec( ...
        rhs_preview.analysisRun.windowSummaryText(context));
    view.controls.statusField = valueSpec(context.statusMessage);
    view.controls.refreshPreviewWindow = enabledSpec(hasChannels);
    view.controls.zoomToRoiWindow = enabledSpec( ...
        hasChannels && rhs_preview.analysisRun.hasValidRoi(context));
    view.controls.saveProtocol = enabledSpec(hasRows);
    view.controls.refreshFolderFiles = enabledSpec(hasFilters);
    view.controls.saveFilterRecord = enabledSpec(hasFilters);
    view.controls.previewChannelsTable = tableSpec( ...
        rhs_preview.userInterface.previewChannelsTableData(context));
    view.controls.fileFilterTable = tableSpec( ...
        rhs_preview.userInterface.fileFilterTableData(context));
    view.controls.summaryTable = tableSpec( ...
        rhs_preview.userInterface.summaryTableData(context));
    view.controls.details = valueSpec( ...
        rhs_preview.userInterface.detailLines(context));
    view.previews.preview = struct( ...
        "Renderer", "stackedPreview", "Model", context);
    if ~isempty(context.preview) && ~isempty(context.preview.timeSec)
        view.interactions.previewRange = struct( ...
            "Kind", "interval", "Targets", "preview", ...
            "Value", context.roiSec, "Event", "previewRoiEdited", ...
            "ScrollEvent", "previewWindowScrolled", ...
            "ChangePolicy", "commit", ...
            "Options", struct("color", [0.75 0.55 0.12], ...
            "faceColor", [0.94 0.78 0.28], "faceAlpha", 0.22));
    end
end

function spec = sourcePanel(sources, emptyStatus)
    files = struct("id", {}, "path", {}, "status", {});
    for k = 1:numel(sources)
        files(end + 1) = struct("id", "item" + string(k), ...
            "path", string(sources(k).reference.originalPath), "status", "");
    end
    status = string(emptyStatus);
    if ~isempty(files)
        status = string(numel(files)) + " file(s) selected";
    end
    spec = struct();
    spec.Files = files;
    spec.Status = status;
end

function spec = valueSpec(value)
    spec = struct();
    spec.Value = value;
end

function spec = enabledSpec(value)
    spec = struct("Enabled", logical(value));
end

function spec = tableSpec(value)
    spec = struct();
    spec.Data = value;
end

function context = previewContext(state)
    context = struct( ...
        "rhsFile", state.session.cache.rhsPath, ...
        "rhsFolder", commonParent(roleSources(state, "filterRecording")), ...
        "protocolFile", state.session.cache.protocolPath, ...
        "protocol", state.project.annotations.protocol, ...
        "family", state.project.parameters.family, ...
        "previewChannelRows", state.session.cache.previewChannelRows, ...
        "filterRows", state.session.cache.filterRows, ...
        "windowStartSec", state.session.view.windowStartSec, ...
        "windowDurationSec", state.session.view.windowDurationSec, ...
        "roiSec", state.session.view.roiSec, ...
        "autoWindow", state.session.view.autoWindow, ...
        "maxPreviewChannels", state.project.parameters.maxPreviewChannels, ...
        "info", state.session.cache.info, "index", state.session.cache.index, ...
        "preview", state.session.cache.preview, ...
        "statusMessage", state.session.workflow.statusMessage, ...
        "lastAction", state.session.workflow.lastAction);
end

function sources = roleSources(state, role)
    sources = rhs_preview.appLifecycle.sourceRecordsForRole( ...
        state.project.inputs.sources, role);
end

function folder = commonParent(sources)
    folder = "";
    if ~isempty(sources)
        folder = string(fileparts(char(sources(1).reference.originalPath)));
    end
end
