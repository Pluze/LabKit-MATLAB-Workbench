% App-owned implementation for rhs_preview.workbench.present within the rhs_preview product workflow.
function view = present(applicationState)
%PRESENT Build the complete derived RHS Preview visible state.
context = presentationContext(applicationState);
selection = rhs_preview.analysisRun.channelSelection( ...
    context.info, context.family, "");
bounds = rhs_preview.analysisRun.previewWindowBounds(context);
hasChannels = rhs_preview.analysisRun.hasReadableChannel(context);
hasRows = height(context.previewChannelRows) > 0;
hasFilters = height(context.filterRows) > 0;
hasPreview = isstruct(context.preview) && ...
    isfield(context.preview, "timeSec") && ...
    ~isempty(context.preview.timeSec);

view = labkit.app.view.Snapshot() ...
    .choices("channelFamily", selection.families) ...
    .value("channelFamily", selection.family) ...
    .enabled("channelFamily", selection.hasChannels) ...
    .limits("windowStartPanner", [0 max(bounds.maxStartSec, eps)]) ...
    .enabled("windowStartPanner", ...
        bounds.hasIndexedDuration && bounds.maxStartSec > 0) ...
    .text("windowSummary", ...
        rhs_preview.analysisRun.windowSummaryText(context)) ...
    .text("statusField", context.statusMessage) ...
    .enabled("refreshPreviewWindow", hasChannels) ...
    .enabled("zoomToRoiWindow", ...
        hasChannels && rhs_preview.analysisRun.hasValidRoi(context)) ...
    .enabled("saveProtocol", hasRows) ...
    .enabled("refreshFolderFiles", hasFilters) ...
    .enabled("saveFilterRecord", hasFilters) ...
    .tableData("previewChannelsTable", ...
        rhs_preview.analysisRun.previewChannelsTableData(context), ...
        Columns=["Plot", "Role", "Label", "Channel"], ...
        ColumnEditable=[true true true false]) ...
    .tableData("fileFilterTable", ...
        rhs_preview.analysisRun.fileFilterTableData(context), ...
        Columns=["Label", "File", "Comment"], ...
        ColumnEditable=[true false true]) ...
    .tableData("summaryTable", ...
        rhs_preview.analysisRun.summaryTableData(context), ...
        Columns=["Field", "Value"]) ...
    .text("details", join(string( ...
        rhs_preview.analysisRun.detailLines(context)), newline)) ...
    .renderPlot("preview", context, ...
        ViewRevision=rhs_preview.analysisRun.viewportRevision( ...
            applicationState.project.inputs.sources, ...
            context.family, context.preview)) ...
    .interval("previewRange", context.roiSec, Enabled=hasPreview);
end

function context = presentationContext(applicationState)
session = applicationState.session;
project = applicationState.project;
filterPaths = strings(0, 1);
if istable(session.cache.filterRows) && ...
        ismember("filePath", session.cache.filterRows.Properties.VariableNames)
    filterPaths = string(session.cache.filterRows.filePath);
end
context = struct( ...
    "rhsFile", session.cache.rhsPath, ...
    "rhsFolder", commonParent(filterPaths), ...
    "protocolFile", session.cache.protocolPath, ...
    "protocol", session.cache.protocol, ...
    "family", project.parameters.family, ...
    "maxPreviewChannels", project.parameters.maxPreviewChannels, ...
    "previewChannelRows", session.cache.previewChannelRows, ...
    "filterRows", session.cache.filterRows, ...
    "windowStartSec", session.view.windowStartSec, ...
    "windowDurationSec", session.view.windowDurationSec, ...
    "roiSec", session.view.roiSec, ...
    "autoWindow", session.view.autoWindow, ...
    "info", session.cache.info, ...
    "index", session.cache.index, ...
    "preview", session.cache.preview, ...
    "statusMessage", session.workflow.statusMessage, ...
    "lastAction", session.workflow.lastAction);
end

function folder = commonParent(paths)
folder = "";
if ~isempty(paths)
    folder = string(fileparts(char(paths(1))));
end
end
