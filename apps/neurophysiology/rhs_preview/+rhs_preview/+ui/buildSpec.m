% Expected caller: rhs_preview.run. Inputs are app callback handles. Output
% is a data-only UI 3.0 workbench spec.
function spec = buildSpec(callbacks)
%BUILDSPEC Build the RHS Preview UI spec.

    spec = labkit.ui.spec.app("rhs_preview", "RHS Preview", ...
        "controlTabs", {setupTab(callbacks), protocolTab(callbacks), ...
        filterTab(callbacks), reviewTab(callbacks), logTab()}, ...
        "workspace", previewWorkspace());
end

function tab = setupTab(callbacks)
    tab = labkit.ui.spec.tab("setup", "Setup", { ...
        rhsSection(callbacks), ...
        folderSection(callbacks), ...
        previewOptionsSection(callbacks), ...
        previewActionsSection(callbacks)});
end

function tab = protocolTab(callbacks)
    tab = labkit.ui.spec.tab("protocol", "Protocol", { ...
        protocolSection(callbacks), ...
        protocolActionsSection(callbacks), ...
        protocolRolesSection(callbacks)});
end

function tab = filterTab(callbacks)
    tab = labkit.ui.spec.tab("filter", "Filter", { ...
        filterActionsSection(callbacks), ...
        filterTableSection(callbacks)});
end

function tab = reviewTab(~)
    tab = labkit.ui.spec.tab("review", "Review", { ...
        summarySection(), ...
        detailsSection()});
end

function tab = logTab()
    tab = labkit.ui.spec.tab("log", "Log", { ...
        labkit.ui.spec.section("logSection", "Log", { ...
            labkit.ui.spec.logPanel("logPanel", "Log", ...
                "value", {"Ready."})})});
end

function section = rhsSection(callbacks)
    section = labkit.ui.spec.section("rhsSection", "RHS File", { ...
        labkit.ui.spec.filePanel("rhsFile", "RHS file", ...
            "mode", "single", ...
            "filters", {'*.rhs', 'Intan RHS files'}, ...
            "chooseLabel", "Choose RHS", ...
            "status", "No RHS file selected", ...
            "onChoose", callbackValue(callbacks, "rhsChosen"))});
end

function section = folderSection(callbacks)
    section = labkit.ui.spec.section("folderSection", "RHS filter files", { ...
        labkit.ui.spec.filePanel("rhsFolder", "RHS filter files", ...
            "selectionMode", "multiple", ...
            "filters", {'*.rhs', 'Intan RHS files'}, ...
            "chooseLabel", "Add RHS files or folder", ...
            "removeLabel", "Remove selected", ...
            "clearLabel", "Clear all", ...
            "status", "No RHS files selected", ...
            "onChoose", callbackValue(callbacks, "folderChosen"), ...
            "onRemove", callbackValue(callbacks, "folderRemoved"), ...
            "onClear", callbackValue(callbacks, "folderCleared"))});
end

function section = protocolSection(callbacks)
    section = labkit.ui.spec.section("protocolSection", "Protocol (optional)", { ...
        labkit.ui.spec.filePanel("protocolFile", "Protocol JSON", ...
            "mode", "single", ...
            "filters", {'*.json', 'Protocol JSON'}, ...
            "chooseLabel", "Choose JSON", ...
            "status", "No protocol selected", ...
            "onChoose", callbackValue(callbacks, "protocolChosen"))});
end

function section = previewOptionsSection(callbacks)
    section = labkit.ui.spec.section("previewOptionsSection", "Preview Window", { ...
        labkit.ui.spec.field("channelFamily", "Family", ...
            "kind", "dropdown", ...
            "items", {"amplifier"}, ...
            "value", "amplifier", ...
            "enabled", false, ...
            "onChange", callbackValue(callbacks, "settingChanged")), ...
        labkit.ui.spec.panner("windowStartPanner", "Pan", ...
            "limits", [0 1], ...
            "value", 0, ...
            "enabled", false, ...
            "stepFraction", 0.002, ...
            "maxStep", 0.250, ...
            "showTicks", false, ...
            "onChange", callbackValue(callbacks, "settingChanged")), ...
        labkit.ui.spec.field("windowSummary", "Window", ...
            "kind", "readonly", ...
            "value", "Select RHS to estimate preview length."), ...
        labkit.ui.spec.field("maxPreviewChannels", "Max channels", ...
            "kind", "number", ...
            "value", 8, ...
            "onChange", callbackValue(callbacks, "settingChanged")), ...
        labkit.ui.spec.field("statusField", "Status", ...
            "kind", "readonly", ...
            "value", "No RHS file selected.")});
end

function section = protocolRolesSection(callbacks)
    section = labkit.ui.spec.section("protocolRolesSection", ...
        "Protocol Channel Roles", { ...
        labkit.ui.spec.resultTable("previewChannelsTable", ...
            "Roles", ...
            "columns", {"Plot", "Role", "Label", "Channel"}, ...
            "data", rhs_preview.view.previewChannelsTableData(struct()), ...
            "columnEditable", [true true true false], ...
            "columnFormat", {'logical', 'char', 'char', 'char'}, ...
            "onCellEdit", callbackValue(callbacks, "previewChannelEdited"))});
end

function section = previewActionsSection(callbacks)
    section = labkit.ui.spec.section("previewActionsSection", "Preview Actions", { ...
        labkit.ui.spec.actionGroup("rhsActions", { ...
            labkit.ui.spec.action("refreshPreviewWindow", ...
                "Refresh Preview", ...
                callbackValue(callbacks, "refreshPreviewWindow"), ...
                "priority", "primary"), ...
            labkit.ui.spec.action("zoomToRoiWindow", ...
                "Zoom to ROI", ...
                callbackValue(callbacks, "zoomToRoi")), ...
            labkit.ui.spec.action("resetWorkflow", ...
                "Reset", ...
                callbackValue(callbacks, "resetWorkflow"))})});
end

function section = protocolActionsSection(callbacks)
    section = labkit.ui.spec.section("protocolActionsSection", ...
        "Protocol Actions", { ...
        labkit.ui.spec.actionGroup("protocolActions", { ...
            labkit.ui.spec.action("saveProtocol", ...
                "Save Protocol Draft", ...
                callbackValue(callbacks, "saveProtocol"), ...
                "priority", "primary")})});
end

function section = filterActionsSection(callbacks)
    section = labkit.ui.spec.section("filterActionsSection", "Filter Actions", { ...
        labkit.ui.spec.actionGroup("filterActions", { ...
            labkit.ui.spec.action("refreshFolderFiles", ...
                "Refresh Folder", ...
                callbackValue(callbacks, "refreshFolderFiles"), ...
                "priority", "primary"), ...
            labkit.ui.spec.action("saveFilterRecord", ...
                "Save Filter Record", ...
                callbackValue(callbacks, "saveFilterRecord"))})});
end

function section = filterTableSection(callbacks)
    section = labkit.ui.spec.section("filterTableSection", "File Filter", { ...
        labkit.ui.spec.resultTable("fileFilterTable", ...
            "Files", ...
            "columns", {"Label", "File", "Comment"}, ...
            "data", rhs_preview.view.fileFilterTableData(struct()), ...
            "columnEditable", [true false true], ...
            "columnFormat", {'char', 'char', 'char'}, ...
            "onCellEdit", callbackValue(callbacks, "fileFilterEdited"))});
end

function section = summarySection()
    section = labkit.ui.spec.section("summarySection", "Summary", { ...
        labkit.ui.spec.resultTable("summaryTable", ...
            "RHS Summary", ...
            "columns", {"Field", "Value"}, ...
            "data", rhs_preview.view.summaryTableData(struct()))});
end

function section = detailsSection()
    section = labkit.ui.spec.section("detailsSection", "Details", { ...
        labkit.ui.spec.statusPanel("details", "Details", ...
            "value", rhs_preview.view.detailLines(struct()))});
end

function workspace = previewWorkspace()
    workspace = labkit.ui.spec.workspace("workspace", "Preview", { ...
        labkit.ui.spec.previewArea("preview", "Stacked Waveforms", ...
            "layout", "single", ...
            "axisIds", {"main"}, ...
            "axisTitles", {"RHS Stacked Preview"}, ...
            "xLabels", {"Time (s)"}, ...
            "yLabels", {"Channel"})});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
