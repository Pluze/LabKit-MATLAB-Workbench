% App-owned implementation for dic_preprocess.analysisRun.present within the dic_preprocess product workflow.
function view = present(applicationState)
%PRESENT Describe registration, crop, and preview state.
cache = applicationState.session.cache;
annotations = applicationState.project.annotations;
hasPair = dic_preprocess.sourceFiles.hasImagePair(cache);
mode = applicationState.session.workflow.mode;
model = previewModel(applicationState);
imageSize = previewSize(model.reference.imageData);
matching = mode == "matching" && hasPair;
cropping = mode == "crop" && hasPair;
view = labkit.app.view.Snapshot() ...
    .enabled("startPointMatching", hasPair) ...
    .enabled("applyPointAlignment", matching && ...
        size(annotations.matchReferencePoints, 1) >= 2 && ...
        size(annotations.matchReferencePoints, 1) == ...
        size(annotations.matchMovingPoints, 1)) ...
    .enabled("cancelPointMatching", matching) ...
    .enabled("undoPointPair", matching && ...
        ~isempty(annotations.matchReferencePoints)) ...
    .enabled("autoAlign", hasPair) ...
    .enabled("startCropRoi", hasPair) ...
    .enabled("applyCropRoi", cropping) ...
    .enabled("cancelCropRoi", cropping) ...
    .enabled("undoEdit", ~isempty(annotations.history)) ...
    .enabled("resetToOriginals", hasPair) ...
    .renderPlot("preview", model, ...
        ViewRevision=cache.plotViewRevision) ...
    .pairedAnchors("matchPoints", ...
        {annotations.matchReferencePoints, ...
         annotations.matchMovingPoints}, ...
        ImageSize=imageSize, Enabled=matching) ...
    .rectangle("cropRectangle", cropPosition(annotations.cropRect), ...
        ImageSize=imageSize, Enabled=cropping);
end

function model = previewModel(state)
request = dic_preprocess.analysisRun.previewRequest( ...
    state, state.project.parameters.previewMode);
model = struct( ...
    "reference", axisModel(request.topImage, request.topTitle), ...
    "moving", axisModel(request.bottomImage, request.bottomTitle));
if state.session.workflow.mode == "crop"
    model.reference.rectangle = state.project.annotations.cropRect;
    model.moving.rectangle = state.project.annotations.cropRect;
elseif state.session.workflow.mode == "matching"
    model.reference.pointLabels = ...
        state.project.annotations.matchReferencePoints;
    model.moving.pointLabels = ...
        state.project.annotations.matchMovingPoints;
elseif state.session.workflow.mode == "mask"
    model.reference.pointLabels = state.project.annotations.maskPoints;
end
end

function model = axisModel(imageData, title)
model = struct("imageData", imageData, "title", title, ...
    "rectangle", [], "pointLabels", zeros(0, 2));
end

function value = previewSize(imageData)
value = [1 1];
if ~isempty(imageData)
    value = [size(imageData, 1), size(imageData, 2)];
end
end

function value = cropPosition(rectangle)
value = [1 1 1 1];
if numel(rectangle) == 4 && all(isfinite(rectangle))
    value = double(rectangle);
end
end
