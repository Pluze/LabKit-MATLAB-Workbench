% Expected caller: DIC preprocess runner. Inputs are callback handles for app
% actions and preview scrolling. Outputs are the shell/UI handle struct and the
% app-specific control handle struct. Side effects: creates GUI controls.

function [ui, controls] = createLayout(callbacks)
%CREATELAYOUT Build DIC preprocess shell, controls, and preview runtime.

    workbenchOpts = struct( ...
        'rightTitle', 'Image Preview', ...
        'rightGridSize', [2 1], ...
        'rightRowHeight', {{'1x', '1x'}}, ...
        'rightRowSpacing', 10);
    workbenchOpts.tabs = [ ...
        labkit.ui.app.tab('filesAnalysis', 'Files + Analysis', [4 1], ...
            {240, 210, 330, 170}, ...
            struct('resizeRows', [1 2 3], ...
            'resizeOptions', struct('minTopHeight', 120, 'minBottomHeight', 80))), ...
        labkit.ui.app.tab('summaryResults', 'Summary + Results', [2 1], ...
            {150, '1x'}, ...
            struct('resizeRows', 1, ...
            'resizeOptions', struct('minTopHeight', 90, 'minBottomHeight', 90))), ...
        labkit.ui.app.tab('log', 'Log', [1 1], {'1x'})];
    ui = labkit.ui.app.createShell(struct( ...
        'title', 'DIC Image Preprocess', ...
        'position', [80 60 1400 860], ...
        'leftWidth', 370, ...
        'options', workbenchOpts));
    ui = dic_preprocess.ui.createRightAxesPair(ui, ...
        'Reference', 'Current Preview', false);
    ui.imageRuntime = labkit.ui.tool.createRuntime(ui.topAxes, ...
        struct('figure', ui.fig, 'defaultScrollFcn', callbacks.scrollZoom));

    filePanel = labkit.ui.view.section(ui.filesAnalysisGrid, ...
        'Images', 1, [4 2], ...
        struct('rowHeight', {{'fit', 'fit', 'fit', 'fit'}}, ...
        'columnWidth', {{'1x', '1x'}}));
    fileGrid = filePanel.grid;

    controls.btnReference = uibutton(fileGrid, 'Text', 'Open reference image', ...
        'ButtonPushedFcn', callbacks.openReference);
    controls.btnReference.Layout.Row = 1;
    controls.btnReference.Layout.Column = 1;
    controls.btnMoving = uibutton(fileGrid, 'Text', 'Open moving image', ...
        'ButtonPushedFcn', callbacks.openMoving);
    controls.btnMoving.Layout.Row = 1;
    controls.btnMoving.Layout.Column = 2;

    controls.txtReference = labkit.ui.view.form(fileGrid, struct( ...
        'kind', 'readonly', ...
        'value', 'No reference image loaded'));
    controls.txtReference.Layout.Row = 2;
    controls.txtReference.Layout.Column = [1 2];
    controls.txtMoving = labkit.ui.view.form(fileGrid, struct( ...
        'kind', 'readonly', ...
        'value', 'No moving image loaded'));
    controls.txtMoving.Layout.Row = 3;
    controls.txtMoving.Layout.Column = [1 2];

    [controls.lblPreview, controls.ddPreview] = labkit.ui.view.form( ...
        fileGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Preview:', ...
        'items', {{'Current pair', 'Current moving image', ...
        'False-color overlay', 'Original pair', 'ROI mask'}}, ...
        'value', 'Current pair', ...
        'callback', callbacks.previewChanged));
    controls.lblPreview.Layout.Row = 4;
    controls.lblPreview.Layout.Column = 1;
    controls.ddPreview.Layout.Row = 4;
    controls.ddPreview.Layout.Column = 2;

    actionPanel = labkit.ui.view.section(ui.filesAnalysisGrid, ...
        'Registration + Crop', 2, [6 2], ...
        struct('rowHeight', {{'fit', 'fit', 'fit', 'fit', 'fit', 'fit'}}, ...
        'columnWidth', {{'1x', '1x'}}));
    actionGrid = actionPanel.grid;
    controls.btnAlign = uibutton(actionGrid, 'Text', 'Select points + align', ...
        'ButtonPushedFcn', callbacks.align);
    controls.btnAlign.Layout.Row = 1;
    controls.btnAlign.Layout.Column = [1 2];
    controls.btnAutoAlign = uibutton(actionGrid, 'Text', 'Auto align current pair', ...
        'ButtonPushedFcn', callbacks.autoAlign);
    controls.btnAutoAlign.Layout.Row = 2;
    controls.btnAutoAlign.Layout.Column = [1 2];
    controls.btnCrop = uibutton(actionGrid, 'Text', 'Start/reset crop ROI', ...
        'ButtonPushedFcn', callbacks.startCropRoi);
    controls.btnCrop.Layout.Row = 3;
    controls.btnCrop.Layout.Column = [1 2];
    controls.btnApplyCrop = uibutton(actionGrid, 'Text', 'Apply ROI crop', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.applyCropRoi);
    controls.btnApplyCrop.Layout.Row = 4;
    controls.btnApplyCrop.Layout.Column = 1;
    controls.btnCancelCrop = uibutton(actionGrid, 'Text', 'Cancel ROI', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.cancelCropRoi);
    controls.btnCancelCrop.Layout.Row = 4;
    controls.btnCancelCrop.Layout.Column = 2;
    controls.btnUndoEdit = uibutton(actionGrid, 'Text', 'Undo align/crop', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.undoEdit);
    controls.btnUndoEdit.Layout.Row = 5;
    controls.btnUndoEdit.Layout.Column = 1;
    controls.btnSaveCurrent = uibutton(actionGrid, 'Text', 'Save current images', ...
        'ButtonPushedFcn', callbacks.saveCurrentImages);
    controls.btnSaveCurrent.Layout.Row = 5;
    controls.btnSaveCurrent.Layout.Column = 2;
    controls.btnResetCurrent = uibutton(actionGrid, 'Text', 'Reset to originals', ...
        'ButtonPushedFcn', callbacks.resetToOriginals);
    controls.btnResetCurrent.Layout.Row = 6;
    controls.btnResetCurrent.Layout.Column = [1 2];

    maskPanel = labkit.ui.view.section(ui.filesAnalysisGrid, ...
        'Mask ROI', 3, [7 2], ...
        struct('rowHeight', {{'fit', 'fit', 'fit', 'fit', 'fit', 'fit', 'fit'}}, ...
        'columnWidth', {{'1x', '1x'}}));
    maskGrid = maskPanel.grid;
    controls.btnStartMask = uibutton(maskGrid, 'Text', 'Start ROI edit', ...
        'ButtonPushedFcn', callbacks.startMaskEdit);
    controls.btnStartMask.Layout.Row = 1;
    controls.btnStartMask.Layout.Column = [1 2];
    [controls.lblBoundaryStyle, controls.ddBoundaryStyle] = labkit.ui.view.form( ...
        maskGrid, struct( ...
        'kind', 'dropdown', ...
        'label', 'Boundary:', ...
        'items', {{'Curve', 'Straight lines'}}, ...
        'value', 'Curve', ...
        'callback', callbacks.boundaryStyleChanged));
    controls.lblBoundaryStyle.Layout.Row = 2;
    controls.lblBoundaryStyle.Layout.Column = 1;
    controls.ddBoundaryStyle.Layout.Row = 2;
    controls.ddBoundaryStyle.Layout.Column = 2;
    controls.ddBoundaryStyle.Enable = 'off';
    controls.btnPreviewMask = uibutton(maskGrid, 'Text', 'Preview ROI mask', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.previewMaskRoi);
    controls.btnPreviewMask.Layout.Row = 3;
    controls.btnPreviewMask.Layout.Column = 1;
    controls.btnUnionMask = uibutton(maskGrid, 'Text', 'Add to mask', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.addBoundaryToMask);
    controls.btnUnionMask.Layout.Row = 3;
    controls.btnUnionMask.Layout.Column = 2;
    controls.btnSubtractMask = uibutton(maskGrid, 'Text', 'Subtract from mask', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.subtractBoundaryFromMask);
    controls.btnSubtractMask.Layout.Row = 4;
    controls.btnSubtractMask.Layout.Column = 1;
    controls.btnUndoMask = uibutton(maskGrid, 'Text', 'Undo point', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.undoMaskAnchor);
    controls.btnUndoMask.Layout.Row = 4;
    controls.btnUndoMask.Layout.Column = 2;
    controls.btnUndoMaskEdit = uibutton(maskGrid, 'Text', 'Undo mask edit', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.undoMaskEdit);
    controls.btnUndoMaskEdit.Layout.Row = 5;
    controls.btnUndoMaskEdit.Layout.Column = 1;
    controls.btnClearBoundary = uibutton(maskGrid, 'Text', 'Clear boundary', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.clearMaskBoundary);
    controls.btnClearBoundary.Layout.Row = 5;
    controls.btnClearBoundary.Layout.Column = 2;
    controls.btnClearMask = uibutton(maskGrid, 'Text', 'Clear mask', ...
        'Enable', 'off', ...
        'ButtonPushedFcn', callbacks.clearMaskCanvas);
    controls.btnClearMask.Layout.Row = 6;
    controls.btnClearMask.Layout.Column = [1 2];
    controls.btnSaveMask = uibutton(maskGrid, 'Text', 'Save ROI mask', ...
        'ButtonPushedFcn', callbacks.saveMask);
    controls.btnSaveMask.Layout.Row = 7;
    controls.btnSaveMask.Layout.Column = [1 2];

    labkit.ui.view.panel(ui.filesAnalysisGrid, 'text', 'Workflow Notes', 4, { ...
        '1. Load a reference image and a moving image.', ...
        '2. Align or crop the current working pair in any order; each apply step can be undone.', ...
        '3. False-color preview compares the current pair even before alignment.', ...
        '4. Draw curve or straight-line ROI boundaries, add/subtract them on the mask canvas, then save the mask.'});

    ui.txtSummary = uitextarea(ui.summaryResultsGrid, 'Editable', 'off');
    ui.txtSummary.Layout.Row = 1;
    ui.txtSummary.Value = {'No images loaded.'};
    ui.txtDetails = uitextarea(ui.summaryResultsGrid, 'Editable', 'off');
    labkit.ui.view.place(ui.txtDetails, ui.summaryResultsGrid, 2);
    ui.txtDetails.Value = {'Alignment and crop details will appear here.'};

    logUi = labkit.ui.view.panel(ui.logGrid, 'log', 1, {'Ready.'});
    ui.txtLog = logUi.textArea;
end
