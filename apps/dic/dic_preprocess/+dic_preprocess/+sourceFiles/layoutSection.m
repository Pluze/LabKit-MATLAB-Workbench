% App-owned implementation for dic_preprocess.sourceFiles.layoutSection within the dic_preprocess product workflow.
function section = layoutSection()
section = labkit.app.layout.section("imagesSection", "Images", { ...
    labkit.app.layout.fileList("referenceFile", Label="Reference image", ...
        ChooseLabel="Choose reference", ...
        EmptyText="No reference image loaded", SelectionMode="single", ...
        MaxFiles=1, Bind="project.inputs.sources", ...
        OnSelectionChanged=@dic_preprocess.sourceFiles.sourceChanged, ...
        SourceRole="referenceImage", SourceIdPrefix="reference", ...
        Required=true), ...
    labkit.app.layout.fileList("movingFile", Label="Moving image", ...
        ChooseLabel="Choose moving", EmptyText="No moving image loaded", ...
        SelectionMode="single", MaxFiles=1, Bind="project.inputs.sources", ...
        OnSelectionChanged=@dic_preprocess.sourceFiles.sourceChanged, ...
        SourceRole="movingImage", SourceIdPrefix="moving", Required=true), ...
    labkit.app.layout.field("previewMode", Label="Preview:", ...
        Kind="choice", Choices=["Current pair", "Current moving image", ...
        "False-color overlay", "Original pair", "ROI mask"], ...
        Bind="project.parameters.previewMode", ...
        OnValueChanged=@dic_preprocess.analysisRun.changePreviewMode)});
end
