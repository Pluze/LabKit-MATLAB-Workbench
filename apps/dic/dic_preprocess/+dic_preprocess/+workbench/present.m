% App-owned implementation for dic_preprocess.workbench.present within the dic_preprocess product workflow.
function view = present(state)
%PRESENT Assemble DIC feature fragments at the only application-state view boundary.
view = dic_preprocess.analysisRun.present(state) ...
    .include(dic_preprocess.maskEditing.present(state)) ...
    .include(dic_preprocess.resultFiles.present(state)) ...
    .text("summary", join( ...
        dic_preprocess.workbench.summaryLines(state), newline)) ...
    .text("workflowNotes", join( ...
        dic_preprocess.workbench.workflowNotes(), newline)) ...
    .text("details", join(string(state.session.workflow.details), newline));
end
