% Expected caller: the LabKit V2 runtime. Input is a validated durable DIC
% project. Output owns ephemeral overlays, workflow log, selection, and view.
function session = createSession(project)
    cache = dic_postprocess.sourceFiles.loadProjectInputs( ...
        project.inputs.sources, ~isempty(project.results.summaryTable));
    [cache.overlayExx, cache.overlayEyy] = preparedOverlays( ...
        cache, project.parameters);
    session = struct( ...
        "selection", struct("preview", "both"), ...
        "workflow", struct("logLines", strings(0, 1)), ...
        "view", struct(), ...
        "cache", cache);
end

function [overlayExx, overlayEyy] = preparedOverlays(cache, parameters)
    overlayExx = [];
    overlayEyy = [];
    if ~hasPreparedInputs(cache) || ...
            parameters.colorMax <= parameters.colorMin
        return;
    end
    [~, overlayExx, overlayEyy] = ...
        dic_postprocess.analysisRun.prepareOutputs( ...
        cache, parameters);
end

function tf = hasPreparedInputs(inputs)
    tf = isfield(inputs.strain, 'exx') && ...
        ~isempty(inputs.referenceImage) && ~isempty(inputs.maskImage);
end
