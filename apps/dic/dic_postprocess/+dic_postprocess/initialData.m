function project = initialData()
%INITIALDATA Create the App-owned initial in-memory data.
project = createProject();
end

function project = createProject()
    project = struct();
    project.inputs = struct("sources", struct([]));
    project.parameters = struct( ...
        "alpha", 0.60, ...
        "colorMin", -0.15, ...
        "colorMax", 0.15, ...
        "oversample", 6, ...
        "smoothSigma", 0.8, ...
        "edgeTrim", 1, ...
        "brightness", 0, ...
        "contrast", 1, ...
        "gamma", 1, ...
        "saturation", 1, ...
        "redGain", 1, ...
        "greenGain", 1, ...
        "blueGain", 1);
    project.results = struct("summaryTable", table());
end
