% App-owned runtime definition for labkit_BatchImageCrop_app. Expected
% caller: the public app entrypoint. Output is a declarative LabKit app
% definition; side effects are none.
function def = definition()
    def = labkit.ui.app.define( ...
        "Id", "batch_crop", ...
        "Title", "Microscope Batch Image Crop", ...
        "InitialState", @batch_crop.state.initial, ...
        "Spec", @buildSpec, ...
        "Actions", batch_crop.actions.table(), ...
        "Render", @batch_crop.view.render, ...
        "Startup", "startup");
end

function spec = buildSpec(callbacks, state)
    outputFolder = state.outputFolder;
    if strlength(outputFolder) == 0
        outputFolder = string(labkit.ui.app.defaultDialogFolder("output"));
    end
    spec = batch_crop.ui.buildSpec(outputFolder, callbacks);
end
