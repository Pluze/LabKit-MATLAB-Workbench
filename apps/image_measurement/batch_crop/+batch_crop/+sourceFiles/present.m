function view = present(applicationState)
%PRESENT Describe crop-task navigation and current source.
items = batch_crop.sourceFiles.workingItems( ...
    applicationState.project.inputs.items, ...
    applicationState.session.cache.images, ...
    applicationState.session.cache.paths);
index = batch_crop.sourceFiles.currentIndex(applicationState);
hasImage = batch_crop.sourceFiles.hasCurrentImage(applicationState);
source = "No images loaded";
if index >= 1 && index <= numel(items)
    source = items(index).path;
end
physical = strcmpi(applicationState.project.parameters.scaleMode, "Physical");
entries = batch_crop.sourceFiles.taskEntries(items, ...
    applicationState.project.parameters.scaleMode);
statuses = strings(1, numel(entries));
if ~isempty(entries)
    statuses = reshape(string({entries.status}), 1, []);
end
selection = labkit.app.event.ListSelection();
if index >= 1 && index <= numel(items)
    selection = labkit.app.event.ListSelection( ...
        Ids=string(applicationState.project.inputs.sources(index).id), ...
        Indices=index);
end
view = labkit.app.view.Snapshot() ...
    .fileItemStatuses("images", statuses) ...
    .listSelection("images", selection) ...
    .enabled("duplicateImage", hasImage) ...
    .enabled("previousImage", hasImage && index > 1) ...
    .enabled("nextImage", hasImage && index < numel(items)) ...
    .value("imageSource", source) ...
    .value("imageStatus", imageStatus(items, physical));
end

function value = imageStatus(items, physical)
if isempty(items)
    value = "No images loaded";
elseif physical
    summary = batch_crop.scaleCalibration.summarize(items);
    value = sprintf("Images: %d | centers: %d | scales: %d", ...
        numel(items), batch_crop.cropTasks.countConfirmedCenters(items), ...
        summary.calibratedCount);
else
    value = sprintf("Images: %d | confirmed centers: %d", ...
        numel(items), batch_crop.cropTasks.countConfirmedCenters(items));
end
end
