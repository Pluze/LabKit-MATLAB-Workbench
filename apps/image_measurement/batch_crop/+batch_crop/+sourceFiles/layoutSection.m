function section = layoutSection()
%LAYOUTSECTION Declare source collection and crop-task navigation.
files = labkit.app.layout.fileList("images", ...
    Label="Microscope images", Filters=labkit.image.fileDialogFilter(), ...
    SelectionMode="single", Bind="project.inputs.sources", ...
    OnSelectionChanged=@batch_crop.sourceFiles.selectionChanged, ...
    SourceRole="cropSource", SourceIdPrefix="image", Required=true);
actions = labkit.app.layout.group("taskActions", { ...
    labkit.app.layout.button("duplicateImage", "Duplicate crop task", ...
        @batch_crop.sourceFiles.duplicateCurrent), ...
    labkit.app.layout.button("removeCurrentTask", "Remove crop task", ...
        @batch_crop.sourceFiles.removeCurrent), ...
    labkit.app.layout.button("previousImage", "Previous task", ...
        @batch_crop.sourceFiles.previous), ...
    labkit.app.layout.button("nextImage", "Next task", ...
        @batch_crop.sourceFiles.next)});
section = labkit.app.layout.section("imagesSection", "Images", { ...
    files, actions, ...
    labkit.app.layout.field("imageSource", Label="Current image", ...
        Enabled=false), ...
    labkit.app.layout.field("imageStatus", Label="Status", Enabled=false)});
end
