% Expected caller: labkit_BatchImageCrop_app. Inputs are the initial output
% folder and app-owned callback handles. Output is a data-only UI 3.0
% workbench spec for the Batch Image Crop app.
function spec = buildSpec(initialOutputFolder, callbacks)

    spec = labkit.ui.spec.app("batchCropApp", ...
        "Microscope Batch Image Crop", ...
        "controlTabs", controlTabs(initialOutputFolder, callbacks), ...
        "workspace", previewWorkspace());
end

function tabs = controlTabs(initialOutputFolder, callbacks)
    tabs = { ...
        filesAnalysisTab(initialOutputFolder, callbacks), ...
        scaleTab(callbacks), ...
        summaryResultsTab(), ...
        logTab()};
end

function tab = filesAnalysisTab(initialOutputFolder, callbacks)
    tab = labkit.ui.spec.tab("filesAnalysis", "Files + Analysis", { ...
        imagesSection(callbacks), ...
        cropGeometrySection(callbacks), ...
        exportSection(initialOutputFolder, callbacks)});
end

function tab = scaleTab(callbacks)
    tab = labkit.ui.spec.tab("scale", "Scale", { ...
        scaleSettingsSection(callbacks), ...
        labkit.ui.spec.section("scaleBarSection", "Current Image Scale", {})});
end

function section = scaleSettingsSection(callbacks)
    section = labkit.ui.spec.section("scaleSettings", "Scale Mode", { ...
        labkit.ui.spec.field("scaleMode", "Mode:", ...
            "kind", "dropdown", ...
            "items", {'Pixels', 'Physical'}, ...
            "value", "Pixels", ...
            "onChange", callbackValue(callbacks, "scaleSettingChanged")), ...
        labkit.ui.spec.field("scaleUnit", "Unit:", ...
            "kind", "dropdown", ...
            "items", {'m', 'cm', 'mm', 'um', 'nm'}, ...
            "value", "um", ...
            "onChange", callbackValue(callbacks, "scaleSettingChanged")), ...
        cropSpinner("physicalWidth", "Width:", 100, [eps Inf], 1, ...
            false, "scaleSettingChanged", callbacks), ...
        cropSpinner("physicalHeight", "Height:", 100, [eps Inf], 1, ...
            false, "scaleSettingChanged", callbacks), ...
        cropSpinner("targetPixelsPerUnit", "Target px/unit (0=auto):", 0, [0 Inf], 1, ...
            false, "scaleSettingChanged", callbacks), ...
        cropSpinner("maxUpsamplePercent", "Max upsample warning (%):", 15, [0 Inf], 1, ...
            false, "scaleSettingChanged", callbacks), ...
        labkit.ui.spec.field("scaleStatus", "Status", ...
            "kind", "readonly", ...
            "value", "Pixel mode: output size uses crop width/height in px.")});
end

function tab = summaryResultsTab()
    tab = labkit.ui.spec.tab("summaryResults", "Summary + Results", { ...
        labkit.ui.spec.section("summarySection", "Summary", { ...
            labkit.ui.spec.resultTable("resultTable", ...
                "Batch Results", ...
                "columns", {'Metric', 'Value'}, ...
                "data", {'Images loaded', '0'}), ...
            labkit.ui.spec.statusPanel("details", "Details", ...
                "value", {'Load microscope images to begin.'})})});
end

function tab = logTab()
    tab = labkit.ui.spec.tab("log", "Log", { ...
        labkit.ui.spec.section("logSection", "Log", { ...
            labkit.ui.spec.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

