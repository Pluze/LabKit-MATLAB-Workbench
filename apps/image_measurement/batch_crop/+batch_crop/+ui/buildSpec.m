                        "onChange", callbackValue(callbacks, ...
                        "cropGeometryChanged")), ...
                    labkit.ui.spec.field("cropHeight", "Height (px):", ...
                        "kind", "spinner", ...
                        "value", 1024, ...
                        "limits", [1 Inf], ...
                        "step", 1, ...
                        "onChange", callbackValue(callbacks, ...
                        "cropGeometryChanged")), ...
                    labkit.ui.spec.field("rotation", "Rotation (deg):", ...
