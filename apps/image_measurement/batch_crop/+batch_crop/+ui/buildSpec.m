                        "clearLabel", "Clear images", ...
                        "filters", batch_crop.io.imageDialogFilter(), ...
                        "dialogTitle", "Select microscope images", ...
                        "status", "No images loaded", ...
                        "emptyText", "No images loaded", ...
                        "onChoose", callbackValue(callbacks, "imagesChosen"), ...
                        "onClear", callbackValue(callbacks, "clearImages"), ...
                        "onSelectionChange", callbackValue(callbacks, ...
                        "imageSelectionChanged")), ...
                    labkit.ui.spec.actionGroup("imageNavigation", { ...
                        labkit.ui.spec.action("previousImage", ...
                            "Previous image", callbackValue(callbacks, ...
                            "previousImage"), "enabled", false), ...
                        labkit.ui.spec.action("nextImage", ...
                            "Next image", callbackValue(callbacks, ...
                            "nextImage"), "enabled", false)}), ...
                    labkit.ui.spec.field("imageSource", "Current image", ...
                        "kind", "readonly", ...
                        "value", "No images loaded"), ...
                    labkit.ui.spec.field("imageStatus", "Status", ...
                        "kind", "readonly", ...
                        "value", "Images: 0")}, ...
                    "height", 250), ...
                labkit.ui.spec.section("cropGeometry", "Crop Geometry", { ...
                    labkit.ui.spec.field("cropWidth", "Width (px):", ...
                        "kind", "spinner", ...
                        "value", 1024, ...
