function section = exportSection(initialOutputFolder, callbacks)
    section = labkit.ui.spec.section("exportSection", "Export", { ...
        labkit.ui.spec.field("format", "Format:", ...
            "kind", "dropdown", ...
            "items", {'PNG', 'TIFF', 'JPEG'}, ...
            "value", "PNG", ...
            "onChange", callbackValue(callbacks, "exportSettingChanged")), ...
        labkit.ui.spec.field("outputFolder", "Output folder", ...
            "kind", "readonly", ...
            "value", char(initialOutputFolder)), ...
        labkit.ui.spec.actionGroup("exportActions", { ...
            labkit.ui.spec.action("chooseOutputFolder", ...
                "Choose export folder", callbackValue(callbacks, ...
                "chooseOutputFolder")), ...
            labkit.ui.spec.action("exportCrops", ...
                "Export cropped images", callbackValue(callbacks, ...
                "exportCrops"), "enabled", false)})});
end

function workspace = previewWorkspace()
    workspace = labkit.ui.spec.workspace("previewWorkspace", ...
        "Crop Preview", { ...
        labkit.ui.spec.previewArea("preview", ...
            "Padded rotation preview + fixed crop", ...
            "layout", "single", ...
            "axisIds", {'crop'}, ...
            "axisTitles", {'Padded rotation preview + fixed crop'})});
end

function spec = cropSpinner(id, labelText, value, limits, step, enabled, ...
        callbackName, callbacks)
    args = {"kind", "spinner", ...
        "value", value, ...
        "limits", limits, ...
        "step", step};
    if ~enabled
        args = [args, {"enabled", false}];
    end
    args = [args, {"onChange", callbackValue(callbacks, callbackName)}];
    spec = labkit.ui.spec.field(id, labelText, args{:});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
