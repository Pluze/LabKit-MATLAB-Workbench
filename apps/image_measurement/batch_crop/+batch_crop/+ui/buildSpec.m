                        "onChange", callbackValue(callbacks, "centerChanged")), ...
                    labkit.ui.spec.field("centerY", "Center Y:", ...
                        "kind", "spinner", ...
                        "value", 1, ...
                        "limits", [1 Inf], ...
                        "step", 1, ...
                        "enabled", false, ...
                        "onChange", callbackValue(callbacks, "centerChanged")), ...
                    labkit.ui.spec.action("useCanvasCenter", ...
                        "Use canvas center", callbackValue(callbacks, ...
