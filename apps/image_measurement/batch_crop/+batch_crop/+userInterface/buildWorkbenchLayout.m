% Expected caller: batch_crop.definition. Inputs are app-owned callback
% handles and initial app state. Output is a data-only UI 5 workbench layout
% for the Batch Image Crop app.
function layout = buildWorkbenchLayout(callbacks, state)
    initialOutputFolder = state.outputFolder;
    if strlength(initialOutputFolder) == 0
        initialOutputFolder = string(labkit.ui.runtime.defaultDialogFolder("output"));
    end

    layout = labkit.ui.layout.workbench("batchCropApp", ...
        "Microscope Batch Image Crop", ...
        "controlTabs", controlTabs(initialOutputFolder, callbacks), ...
        "workspace", previewWorkspace());
end

function tabs = controlTabs(initialOutputFolder, callbacks)
    tabs = { ...
        filesAnalysisTab(initialOutputFolder, callbacks), ...
        scaleTab(callbacks), ...
        summaryResultsTab(), ...
        logTab()};
end

function tab = filesAnalysisTab(initialOutputFolder, callbacks)
    tab = labkit.ui.layout.tab("filesAnalysis", "Files + Analysis", { ...
        imagesSection(callbacks), ...
        cropGeometrySection(callbacks), ...
        exportSection(initialOutputFolder, callbacks)});
end

function tab = scaleTab(callbacks)
    tab = labkit.ui.layout.tab("scale", "Scale", { ...
        scaleSettingsSection(callbacks), ...
        scaleBarSection()});
end

function section = scaleBarSection()
    section = labkit.ui.layout.section("scaleBarSection", "Current Image Scale", { ...
        labkit.ui.layout.toolPanel("scaleBarHost", "Scale Bar controls")});
end

function section = scaleSettingsSection(callbacks)
    section = labkit.ui.layout.section("scaleSettings", "Scale Mode", { ...
        labkit.ui.layout.field("scaleMode", "Mode:", ...
            "kind", "dropdown", ...
            "items", {'Pixels', 'Physical'}, ...
            "value", "Pixels", ...
