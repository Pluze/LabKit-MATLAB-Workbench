function layoutNode = cropPanner(id, labelText, value, limits, step, enabled, ...
        callbackName, callbacks)
    args = {"value", value, ...
        "limits", limits, ...
        "step", step};
    if ~enabled
        args = [args, {"enabled", false}];
    end
    args = [args, {"onChange", callbacks.(char(callbackName))}];
    layoutNode = labkit.ui.layout.panner(id, labelText, args{:});
end

function layoutNode = boundPanner(id, labelText, value, limits, step, ...
        enabled, path, eventId)
    args = {"value", value, "limits", limits, "step", step, ...
        "Bind", path, "Event", eventId};
    if ~enabled
        args = [args, {"enabled", false}];
    end
    layoutNode = labkit.ui.layout.panner(id, labelText, args{:});
end

function layoutNode = boundDropdown(id, labelText, items, value, path, ...
        eventId, enabled)
    layoutNode = labkit.ui.layout.field(id, labelText, ...
        "kind", "dropdown", "items", items, "value", value, ...
        "enabled", enabled, "Bind", path, "Event", eventId);
end
