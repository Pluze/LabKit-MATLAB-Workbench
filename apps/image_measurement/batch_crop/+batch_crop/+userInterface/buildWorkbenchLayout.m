function layoutNode = cropPanner(id, labelText, value, limits, step, enabled, ...
        callbackName, callbacks)
    args = {"value", value, ...
        "limits", limits, ...
        "step", step};
    if ~enabled
        args = [args, {"enabled", false}];
    end
    args = [args, {"onChange", callbackValue(callbacks, callbackName)}];
    layoutNode = labkit.ui.layout.panner(id, labelText, args{:});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
