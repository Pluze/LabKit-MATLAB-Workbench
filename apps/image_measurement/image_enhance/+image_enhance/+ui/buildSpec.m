% Expected caller: labkit_ImageEnhance_app. Inputs are tool labels, initial
% export folder text, and callback handles. Output is a data-only UI 2.0
% workbench spec for the Image Enhance app.
function spec = buildSpec(stepKinds, outputFolder, callbacks)

    spec = labkit.ui.spec.app('imageEnhanceApp', 'Paper Image Enhance', ...
        'controlTabs', controlTabs(stepKinds, outputFolder, callbacks), ...
        'workspace', previewWorkspace(callbacks));
end

function tabs = controlTabs(stepKinds, outputFolder, callbacks)
    tabs = { ...
        libraryExportTab(outputFolder, callbacks), ...
        toolsHistoryTab(stepKinds, callbacks), ...
        logTab()};
end

function tab = libraryExportTab(outputFolder, callbacks)
    tab = labkit.ui.spec.tab('libraryExport', 'Library + Export', { ...
        librarySection(callbacks), ...
        exportSection(outputFolder, callbacks), ...
        exportDetailsSection()});
end

function tab = toolsHistoryTab(stepKinds, callbacks)
    tab = labkit.ui.spec.tab('toolsHistory', 'Tools + History', { ...
        toolSection(stepKinds, callbacks), ...
        historySection(callbacks), ...
        currentImageSection()});
end

function tab = logTab()
    tab = labkit.ui.spec.tab('log', 'Log', { ...
        labkit.ui.spec.section('logSection', 'Log', { ...
            labkit.ui.spec.logPanel('logPanel', 'Log')})});
end

function section = librarySection(callbacks)
    section = labkit.ui.spec.section('librarySection', 'Library', { ...
        labkit.ui.spec.pathPanel('sourceImages', 'Source images', ...
            'mode', 'multiFile', ...
            'selectionMode', 'single', ...
            'filters', image_enhance.io.imageDialogFilter(), ...
            'status', 'No images loaded', ...
            'emptyText', 'No images loaded', ...
            'onChoose', callbackValue(callbacks, 'sourceImagesChosen'), ...
            'onSelectionChange', callbackValue(callbacks, 'imageSelectionChanged'), ...
            'onClear', callbackValue(callbacks, 'clearImages')), ...
        labkit.ui.spec.field('imageStatus', 'Status', ...
            'kind', 'readonly', ...
            'value', 'Images: 0')});
end

function section = exportSection(outputFolder, callbacks)
    section = labkit.ui.spec.section('exportSection', 'Batch Export', { ...
        labkit.ui.spec.field('outputFolder', 'Output folder', ...
            'kind', 'readonly', ...
            'value', outputFolder), ...
        labkit.ui.spec.field('exportFormat', 'Format', ...
            'kind', 'dropdown', ...
            'items', {'PNG', 'TIFF', 'JPEG'}, ...
            'value', 'PNG'), ...
        labkit.ui.spec.actionGroup('exportActions', { ...
            labkit.ui.spec.action('chooseOutputFolder', 'Choose folder', ...
                callbackValue(callbacks, 'chooseOutputFolder')), ...
            labkit.ui.spec.action('exportImages', 'Export enhanced images', ...
                callbackValue(callbacks, 'exportImages'), ...
                'enabled', false)})});
end

function section = exportDetailsSection()
    section = labkit.ui.spec.section('exportDetailsSection', 'Export Details', { ...
        labkit.ui.spec.statusPanel('exportDetails', 'Export Details', ...
            'value', image_enhance.view.detailLines( ...
            repmat(image_enhance.state.emptyItem(), 0, 1), 1, ...
            repmat(image_enhance.state.emptyStep(), 0, 1), []))});
end

function section = toolSection(stepKinds, callbacks)
    section = labkit.ui.spec.section('toolSection', 'Toolbox', { ...
        labkit.ui.spec.field('toolKind', 'Tool', ...
            'kind', 'dropdown', ...
            'items', stepKinds, ...
            'value', stepKinds{1}, ...
            'onChange', callbackValue(callbacks, 'toolChanged')), ...
        labkit.ui.spec.field('toolAmount', 'Brightness (%)', ...
            'kind', 'spinner', ...
            'value', 0, ...
            'limits', [-100 100], ...
            'step', 1, ...
            'onChange', callbackValue(callbacks, 'toolSettingChanged')), ...
        labkit.ui.spec.field('toolSecondary', 'Contrast (%)', ...
            'kind', 'spinner', ...
            'value', 15, ...
            'limits', [-100 100], ...
            'step', 1, ...
            'onChange', callbackValue(callbacks, 'toolSettingChanged')), ...
        labkit.ui.spec.field('toolStatus', 'Status', ...
            'kind', 'readonly', ...
            'value', 'Select an image, choose a tool, then apply it to history.'), ...
        labkit.ui.spec.action('applyTool', 'Apply tool', ...
            callbackValue(callbacks, 'applyTool'), ...
            'enabled', false)});
end

function section = historySection(callbacks)
    section = labkit.ui.spec.section('historySection', 'Step History', { ...
        labkit.ui.spec.actionGroup('historyActions', { ...
            labkit.ui.spec.action('undoHistory', 'Undo history', ...
                callbackValue(callbacks, 'undoHistory'), ...
                'enabled', false), ...
            labkit.ui.spec.action('resetHistory', 'Reset history', ...
                callbackValue(callbacks, 'resetHistory'), ...
                'enabled', false)}), ...
        labkit.ui.spec.resultTable('historyTable', 'Step History', ...
            'columns', {'#', 'Step', 'Settings'}, ...
            'data', image_enhance.view.historyTableData( ...
            repmat(image_enhance.state.emptyStep(), 0, 1))), ...
        labkit.ui.spec.field('historyStatus', 'Status', ...
            'kind', 'readonly', ...
            'value', 'History steps: 0')});
end

function section = currentImageSection()
    section = labkit.ui.spec.section('currentImageSection', 'Current Image', { ...
        labkit.ui.spec.resultTable('metricsTable', 'Current Image', ...
            'columns', {'Metric', 'Value'}, ...
            'data', image_enhance.view.resultTableData([], [], 0))});
end

function workspace = previewWorkspace(callbacks)
    workspace = labkit.ui.spec.workspace('workspace', 'Preview', { ...
        labkit.ui.spec.previewArea('preview', 'Preview', ...
            'layout', 'single', ...
            'axisTitles', {'Enhanced Preview'}, ...
            'viewModes', {'Enhanced', 'Original', 'Before | After'}, ...
            'onModeChange', callbackValue(callbacks, 'previewModeChanged'))});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
