% Expected caller: the LabKit V2 runtime. Output is the durable Image Enhance
% project: source references, processing choices, annotations, and results.
function project = createProject()
    project = struct();
    project.inputs = struct("sources", ...
        labkit.ui.runtime.emptySourceRecords());
    project.parameters = struct( ...
        "batchMode", true, ...
        "exportFormat", "PNG", ...
        "outputFolder", "");
    project.annotations = struct( ...
        "sharedSteps", repmat(image_enhance.appState.emptyStep(), 0, 1), ...
        "items", repmat(image_enhance.appState.emptyAnnotation(), 0, 1));
    project.results = struct( ...
        "lastExport", [], ...
        "lastExportFingerprint", "", ...
        "resultManifestPath", "");
    project.extensions = struct();
end
