% App-owned durable FLIR Thermal contract. App SDK runtime calls this single entry
% for current project creation and validation; version 1 needs no migration.
function spec = projectSpec()
    spec = labkit.app.project.Schema(Version=1, Create=@createProject, ...
        Validate=@validateProject, SourceBindings="inputs.sources");
end

function project = createProject()
    project = struct();
    project.inputs = struct("sources", ...
        labkit.app.project.emptySourceRecords());
    project.parameters = struct( ...
        "palette", "turbo", ...
        "colorMapping", "Linear", ...
        "gammaValue", 2.2, ...
        "roiMode", "mean", ...
        "exportFormat", "PNG", ...
        "outputFolder", "");
    project.annotations = struct("items", repmat( ...
        flir_thermal.thermalAnnotations.empty(), 0, 1));
    project.results = struct("lastExport", [], "resultManifestPath", "");
    project.extensions = struct();
end

function accepted = validateProject(project)
    assert(isfield(project.inputs, 'sources'), ...
        'flir_thermal:InvalidProject', 'Project sources are invalid.');
    fields = {'palette', 'colorMapping', 'gammaValue', 'roiMode', ...
        'exportFormat', 'outputFolder'};
    assert(all(isfield(project.parameters, fields)), ...
        'flir_thermal:InvalidProject', 'Project parameters are incomplete.');
    assert(isfield(project.annotations, 'items') && ...
        isstruct(project.annotations.items), ...
        'flir_thermal:InvalidProject', 'Thermal annotations are invalid.');
    accepted = true;
end
