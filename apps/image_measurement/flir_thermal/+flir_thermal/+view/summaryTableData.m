% Expected caller: FLIR thermal app UI and tests. Inputs are the current item,
% active display range, and palette. Output is metric/value table data.
function data = summaryTableData(item, range, palette)

    if isempty(item) || strlength(string(item.path)) == 0
        data = { ...
            'Files loaded', '0'; ...
            'Current image', '-'; ...
            'Matrix size', '-'; ...
            'Value range', '-'; ...
            'Palette', char(string(palette))};
        return;
    end
    [values, units, label] = flir_thermal.view.valueMatrix(item);
    finiteValues = values(isfinite(values));
    if isempty(finiteValues)
        measured = '-';
    else
        measured = sprintf('%.3g to %.3g %s', ...
            min(finiteValues), max(finiteValues), char(units));
    end
    data = { ...
        'Current image', char(item.name); ...
        'Matrix size', sprintf('%d x %d px', size(values, 2), size(values, 1)); ...
        'Displayed value', char(label); ...
        'Measured range', measured; ...
        'Display range', sprintf('%.3g to %.3g %s', range(1), range(2), char(units)); ...
        'Range status', rangeStatus(item); ...
        'Palette', char(string(palette))};
end

function text = rangeStatus(item)
    if isfield(item, 'rangeAdjusted') && logical(item.rangeAdjusted)
        text = 'range set';
    else
        text = 'needs range';
    end
end
