% App-owned runtime definition for labkit_FLIRThermal_app. Expected caller:
% the public app entrypoint. Output is a declarative LabKit app definition;
% side effects are none.
function def = definition()
    def = labkit.ui.app.define( ...
        "Id", "flir_thermal", ...
        "Title", "FLIR Thermal Postprocess", ...
        "InitialState", @initialState, ...
        "Spec", @(callbacks, state) flir_thermal.ui.buildSpec( ...
            char(state.outputFolder), callbacks), ...
        "Actions", flir_thermal.actions.table(), ...
        "Render", @flir_thermal.view.render, ...
        "Startup", "startup");
end

function S = initialState()
    S = struct();
    S.items = repmat(flir_thermal.state.emptyItem(), 0, 1);
    S.currentIndex = 0;
    S.outputFolder = string(labkit.ui.app.defaultDialogFolder("output"));
    S.lastExport = [];
    S.roiMode = "mean";
end
