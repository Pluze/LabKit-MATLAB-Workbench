% App-owned runtime definition for labkit_FocusStack_app. Expected caller:
% the public app entrypoint. Output is a declarative LabKit app definition;
% side effects are none.
function def = definition()
    def = labkit.ui.app.define( ...
        "Id", "focus_stack", ...
        "Title", "Microscope Focus Stack Fusion", ...
        "InitialState", @focus_stack.state.initial, ...
        "Spec", @buildSpec, ...
        "Actions", focus_stack.actions.table(), ...
        "Render", @focus_stack.view.render, ...
        "Startup", "startup");
end

function spec = buildSpec(callbacks)
    fusionPresets = {'Balanced', 'Crisp details', ...
        'Smooth transitions', 'Noisy images'};
    workflowNotes = { ...
        '1. Add a folder or selected image files from the same microscope field of view.', ...
        '2. Remove selected files when a folder contains bad frames that should be excluded.', ...
        '3. Start with Balanced. Use Crisp for fine texture, Smooth for visible seams, Noisy for grainy images.', ...
        '4. Detail scale controls feature size; Blend radius controls seam softness; Uncertain blend softens low-texture areas.'};
    spec = focus_stack.ui.buildSpec(fusionPresets, workflowNotes, callbacks);
end
