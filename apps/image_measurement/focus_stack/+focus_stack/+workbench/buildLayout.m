% App-owned implementation for focus_stack.workbench.buildLayout within the focus_stack product workflow.
function layout = buildLayout()
%BUILDLAYOUT Declare the Focus Stack workbench and its direct callbacks.
files = labkit.app.layout.fileList("sourceImages", ...
    Label="Focus images", Filters=labkit.image.fileDialogFilter(), ...
    SelectionMode="multiple", Bind="project.inputs.sources", ...
    SelectionBind="session.selection.sourceImages", SourceRole="focus-image", ...
    SourceIdPrefix="image", Required=true, ...
    ChooseLabel="Add images", FolderLabel="Add folder", ...
    ChooseTooltip="Add a z-stack of images from the same field of view at different focal planes.", ...
    RecursiveFolderLabel="Add folder tree", ...
    RemoveLabel="Remove selected", ClearLabel="Clear images", ...
    EmptyText="No images loaded", ...
    OnSelectionChanged=@focus_stack.sourceFiles.selectionChanged);
controls = { ...
    labkit.app.layout.tab("filesAnalysis", "Files + Analysis", { ...
        labkit.app.layout.section("imagesSection", "Images", { ...
            labkit.app.layout.field("sourceLocation", ...
                Label="Source", Kind="readonly", Value="No images loaded"), ...
            files, ...
            labkit.app.layout.button("sourceFolderChosen", ...
                "Choose folder", @focus_stack.sourceFiles.chooseFolder, ...
                Tooltip="Replace the source stack with supported images discovered in one folder.")}), ...
        labkit.app.layout.section("fusionOptions", "Fusion Options", { ...
            labkit.app.layout.field("fusionPreset", Label="Preset", Kind="choice", ...
                Choices=focus_stack.workbench.fusionPresets(), ...
                Bind="project.parameters.fusionPreset", ...
                OnValueChanged=@focus_stack.analysisRun.applyPreset), ...
            labkit.app.layout.field("autoRegister", ...
                Label="Auto-register stack to middle image", ...
                Kind="logical", Bind="project.parameters.autoRegister", ...
                OnValueChanged=@focus_stack.analysisRun.invalidate), ...
            labkit.app.layout.slider("focusWindow", Label="Detail scale (px)", ...
                Limits=[3 99], Step=2, Bind="project.parameters.focusWindow", ...
                OnValueChanged=@focus_stack.analysisRun.invalidate), ...
            labkit.app.layout.slider("smoothRadius", Label="Blend radius (px)", ...
                Limits=[0 50], Step=1, Bind="project.parameters.smoothRadius", ...
                OnValueChanged=@focus_stack.analysisRun.invalidate), ...
            labkit.app.layout.slider("uncertainBlend", Label="Uncertain blend (%)", ...
                Limits=[0 100], Step=1, Bind="project.parameters.uncertainBlend", ...
                OnValueChanged=@focus_stack.analysisRun.invalidate), ...
            labkit.app.layout.button("runFocusStack", "Run focus stack", ...
                @focus_stack.analysisRun.runFocusStack, ...
                Tooltip="Estimate local focus across the registered stack and blend the sharpest source regions into one image.")}), ...
        labkit.app.layout.section("exports", "Export", { ...
            labkit.app.layout.button("exportFused", "Export fused PNG", @focus_stack.resultFiles.exportFused, ...
                Tooltip="Export the all-in-focus composite generated from the current stack and fusion settings."), ...
            labkit.app.layout.button("exportFocusMap", "Export focus map PNG", @focus_stack.resultFiles.exportFocusMap, ...
                Tooltip="Export the source-depth index selected at each pixel by the focus estimator."), ...
            labkit.app.layout.button("exportSummary", "Export summary CSV", @focus_stack.resultFiles.exportSummary, ...
                Tooltip="Export focus-stack dimensions, registration, blend settings, and source-use summary.")})}), ...
    labkit.app.layout.tab("summaryResults", "Summary + Results", { ...
        labkit.app.layout.section("summaryTableSection", "Summary", { ...
            labkit.app.layout.dataTable("resultTable", ...
                Title="Summary", Columns=["Metric" "Value"])}), ...
        labkit.app.layout.section("detailsSection", "Details", { ...
            labkit.app.layout.statusPanel("details", Title="Details")})})};
workspace = labkit.app.layout.workspace(labkit.app.layout.plotArea("preview", ...
    @focus_stack.focusPreview.draw, Title="Focus Stack Preview", ...
    Layout="pair", AxisIds=["fused" "focusMap"], ...
    AxisTitles=["Fused all-in-focus image" "Focus-depth index map"]), ...
    Title="Focus Stack Preview");
workflowNotes = [ ...
    "1. Add a folder or selected image files from the same microscope field of view."
    "2. Remove selected files when a folder contains bad frames that should be excluded."
    "3. Start with Balanced. Use Crisp for fine texture, Smooth for visible seams, Noisy for grainy images."
    "4. Detail scale controls feature size; Blend radius controls seam softness; Uncertain blend softens low-texture areas."];
layout = labkit.app.layout.workbench(controls, Workspace=workspace, ...
    UsageTitle="Workflow Notes", Usage=workflowNotes);
end
