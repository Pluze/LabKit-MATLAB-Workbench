% Expected caller: the LabKit V2 runtime. Input is a candidate durable Focus
% Stack project. Output is true or this function throws for invalid buckets.
function accepted = validateProject(project)
    buckets = ["inputs", "parameters", "annotations", "results", "extensions"];
    assert(isstruct(project) && isscalar(project) && ...
        all(isfield(project, cellstr(buckets))), ...
        'focus_stack:InvalidProject', ...
        'Focus Stack project is missing required durable buckets.');
    assert(isfield(project.inputs, 'sources') && ...
        isstruct(project.inputs.sources), ...
        'focus_stack:InvalidProject', 'Project sources are invalid.');
    sources = project.inputs.sources;
    assert(isempty(sources) || all(isfield(sources, ...
        {'id', 'required', 'role', 'reference'})), ...
        'focus_stack:InvalidProject', ...
        'Sources must use the canonical source-record contract.');
    fields = {'fusionPreset', 'autoRegister', 'focusWindow', ...
        'smoothRadius', 'uncertainBlend', 'outputFolder'};
    assert(all(isfield(project.parameters, fields)), ...
        'focus_stack:InvalidProject', 'Project parameters are incomplete.');
    accepted = true;
end
