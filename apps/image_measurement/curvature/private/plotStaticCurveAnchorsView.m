% App-owned curvature static-anchor plotting helper. Expected caller:
% labkit_CurvatureMeasurement_app overlay rendering. Inputs are axes, anchor
% points, display curve, fit result, and dense-point visibility. Draws only into
% the supplied axes.
function plotStaticCurveAnchorsView(ax, points, curve, fit, showDense)
%PLOTSTATICCURVEANCHORSVIEW Draw inactive curve anchors and fit residuals.

    if isempty(points)
        return;
    end

    if ~isempty(curve)
        plot(ax, curve(:, 1), curve(:, 2), '-', ...
            'Color', [0 0.45 0.95], ...
            'LineWidth', 1.5, ...
            'HitTest', 'off', ...
            'DisplayName', 'curve');
    end
    if fit.ok
        if showDense
            plotDenseFitPoints(ax, fit);
        end
        plotAnchorResiduals(ax, points, fit);
    end
    plot(ax, points(:, 1), points(:, 2), 'o', ...
        'LineStyle', 'none', ...
        'Color', [1 0.85 0], ...
        'MarkerFaceColor', [0 0.45 0.95], ...
        'LineWidth', 1.2, ...
        'MarkerSize', 7, ...
        'HitTest', 'off', ...
        'DisplayName', 'anchors');
end
