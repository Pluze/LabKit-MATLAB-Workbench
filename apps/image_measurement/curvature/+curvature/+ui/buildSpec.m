% Expected caller: curvature.run. Input is a callback struct whose fields are
% app-owned callback handles. Output is a data-only UI 3.0 workbench spec for
% the Curvature Measurement app.
function spec = buildSpec(callbacks)

    spec = labkit.ui.spec.app("curvatureApp", ...
        "Image Curvature Measurement", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", curvatureWorkspace(), ...
        "usageTitle", "Workflow Notes", ...
        "usage", workflowNotesLines());
end

function tabs = controlTabs(callbacks)
    tabs = {filesAnalysisTab(callbacks), summaryResultsTab(), logTab()};
end

function tab = filesAnalysisTab(callbacks)
    tab = labkit.ui.spec.tab("filesAnalysis", "Files + Analysis", { ...
        imageSection(callbacks), ...
        curveEditingSection(callbacks), ...
        scaleBarSection(), ...
        fitExportSection(callbacks)});
end

function section = scaleBarSection()
    section = labkit.ui.spec.section("scaleBarSection", "Scale Bar", { ...
        labkit.ui.spec.toolPanel("scaleBarHost", "Scale Bar controls")});
end

function tab = summaryResultsTab()
    tab = labkit.ui.spec.tab("summaryResults", "Summary + Results", { ...
        labkit.ui.spec.section("resultsSection", "Results", { ...
            labkit.ui.spec.resultTable("resultTable", ...
                "Curvature Results", ...
                "columns", {'Metric', 'Value'}, ...
                "data", curvature.view.initialResultTable())}), ...
        labkit.ui.spec.section("detailsSection", "Details", { ...
            labkit.ui.spec.statusPanel("detailsText", "Details", ...
                "value", {'No curvature result yet.'})})});
end

function tab = logTab()
    tab = labkit.ui.spec.tab("log", "Log", { ...
        labkit.ui.spec.section("logSection", "Log", { ...
            labkit.ui.spec.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function section = imageSection(callbacks)
    section = labkit.ui.spec.section("imageSection", "Image", { ...
        labkit.ui.spec.filePanel("imageFile", "Image file", ...
            "mode", "single", ...
            "filters", {'*.png;*.jpg;*.jpeg;*.tif;*.tiff;*.bmp', ...
            'Image files'}, ...
            "chooseLabel", "Choose image", ...
            "status", "No image loaded", ...
            "emptyText", "No image loaded", ...
            "onChoose", callbackValue(callbacks, "onImageChosen")), ...
        labkit.ui.spec.field("pointCount", "Curve points", ...
            "kind", "readonly", ...
            "value", "Points: 0")});
end

function section = curveEditingSection(callbacks)
    section = labkit.ui.spec.section("curveEditing", "Curve Editing", { ...
        labkit.ui.spec.action("startCurveEdit", "Start curve edit", ...
            callbackValue(callbacks, "onStartCurveEdit")), ...
        labkit.ui.spec.actionGroup("curveEditActions", { ...
            labkit.ui.spec.action("undoCurvePoint", "Undo last point", ...
                callbackValue(callbacks, "onUndoCurvePoint"), "enabled", false), ...
            labkit.ui.spec.action("clearCurve", "Clear curve", ...
                callbackValue(callbacks, "onClearCurve"), "enabled", false)})});
end

function section = fitExportSection(callbacks)
    section = labkit.ui.spec.section("fitExport", "Fit + Export", { ...
        labkit.ui.spec.field("densify", ...
            "Densify before circle fit", ...
            "kind", "checkbox", "value", true), ...
        labkit.ui.spec.field("densePointCount", ...
            "Dense point count:", ...
            "kind", "spinner", "value", 300, ...
            "limits", [3 Inf], "step", 25), ...
        labkit.ui.spec.field("showDensePoints", ...
            "Show dense fit points", ...
            "kind", "checkbox", "value", true, ...
            "onChange", callbackValue(callbacks, "onShowDenseChanged")), ...
        labkit.ui.spec.action("fitCurvature", "Fit circle + curvature", ...
            callbackValue(callbacks, "onFitCurvature")), ...
        labkit.ui.spec.action("measureCurveLength", "Measure curve length", ...
            callbackValue(callbacks, "onMeasureCurveLength")), ...
        labkit.ui.spec.action("exportCsv", "Export result CSV", ...
            callbackValue(callbacks, "onExportCSV")), ...
        labkit.ui.spec.action("exportOverlay", "Export overlay PNG", ...
            callbackValue(callbacks, "onExportOverlay"))});
end

function lines = workflowNotesLines()
    lines = { ...
        '1. Open an image and start curve editing.', ...
        '2. Double-click blank image space to add/insert points; drag points to move; double-click a point to delete it.', ...
        '3. Calibrate with measured or typed reference pixels, a real reference length, and a unit.', ...
        '4. Place the final scale bar, then fit curvature or measure curve length.'};
end

function workspace = curvatureWorkspace()
    workspace = labkit.ui.spec.workspace("curvaturePreview", ...
        "Image Preview", { ...
        labkit.ui.spec.previewArea("imageAxes", "Image Preview", ...
            "layout", "single", ...
            "axisIds", {'image'}, ...
            "axisTitles", {'Image + Circle Fit'})});
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
