% App-owned durable Curvature contract. App SDK runtime calls this single entry for
% project creation, validation, and each required version migration step.
function spec = projectSpec()
    spec = labkit.app.project.Schema(Version=2, Create=@createProject, ...
        Validate=@validateProject, Migrate=@migrateProject);
end

function project = createProject()
    project = struct();
    project.inputs = struct("sources", ...
        labkit.app.project.emptySourceRecords());
    project.parameters = struct( ...
        "densify", true, ...
        "densePointCount", 300, ...
        "showDensePoints", true, ...
        "scaleBarLength", 100, ...
        "scaleBarPosition", "Bottom right", ...
        "scaleBarColor", "Black");
    project.annotations = struct( ...
        "curvePoints", zeros(0, 2), ...
        "calibration", labkit.app.interaction.scaleCalibration( ...
            [], 100, "um"));
    project.results = struct( ...
        "fit", curvature.analysisRun.emptyFitResult(), ...
        "length", curvature.analysisRun.emptyLengthResult(), ...
        "lastCsvExport", [], ...
        "lastOverlayExport", []);
    project.extensions = struct();
end

function accepted = validateProject(project)
    assert(isfield(project.inputs, 'sources'), ...
        'curvature:InvalidProject', 'Curvature image source is missing.');
    requiredParameters = ["densify", "densePointCount", "showDensePoints", ...
        "scaleBarLength", "scaleBarPosition", "scaleBarColor"];
    assert(all(isfield(project.parameters, cellstr(requiredParameters))), ...
        'curvature:InvalidProject', 'Curvature parameters are incomplete.');
    assert(islogical(project.parameters.densify) && ...
        isscalar(project.parameters.densify) && ...
        islogical(project.parameters.showDensePoints) && ...
        isscalar(project.parameters.showDensePoints) && ...
        finiteNonnegative(project.parameters.densePointCount) && ...
        finiteNonnegative(project.parameters.scaleBarLength), ...
        'curvature:InvalidProject', 'Curvature numeric parameters are invalid.');
    annotations = project.annotations;
    assert(all(isfield(annotations, {'curvePoints', 'calibration'})) && ...
        validPoints(annotations.curvePoints) && ...
        isstruct(annotations.calibration) && isscalar(annotations.calibration), ...
        'curvature:InvalidProject', 'Curvature annotations are invalid.');
    results = project.results;
    assert(all(isfield(results, {'fit', 'length', 'lastCsvExport', ...
        'lastOverlayExport'})), ...
        'curvature:InvalidProject', 'Curvature results are incomplete.');
    accepted = true;
end

function project = migrateProject(project, fromVersion)
    switch fromVersion
        case 1
            project.inputs.sources = project.inputs.source;
            project.inputs = rmfield(project.inputs, 'source');
        otherwise
            error('curvature:UnsupportedProjectVersion', ...
                'No Curvature migration is defined from version %d.', ...
                fromVersion);
    end
end

function tf = finiteNonnegative(value)
    tf = isnumeric(value) && isscalar(value) && isfinite(double(value)) && ...
        double(value) >= 0;
end

function tf = validPoints(value)
    tf = isnumeric(value) && ismatrix(value) && ...
        (isempty(value) || size(value, 2) == 2) && all(isfinite(value), 'all');
end
