function project = initialData()
%INITIALDATA Create the App-owned initial in-memory data.
project = createProject();
end

function project = createProject()
    project = struct();
    project.inputs = struct("sources", ...
        labkit.app.source.emptyRecords());
    project.parameters = struct( ...
        "densify", true, ...
        "densePointCount", 300, ...
        "showDensePoints", true, ...
        "scaleBarLength", 100, ...
        "scaleBarPosition", "Bottom right", ...
        "scaleBarColor", "Black");
    project.annotations = struct( ...
        "curvePoints", zeros(0, 2), ...
        "calibration", labkit.app.interaction.scaleCalibration( ...
            [], 100, "um"));
    project.results = struct( ...
        "fit", curvature.analysisRun.emptyFitResult(), ...
        "length", curvature.analysisRun.emptyLengthResult(), ...
        "lastCsvExport", [], ...
        "lastOverlayExport", []);
    project.extensions = struct();
end

