% App-owned curvature summary view-data helper. Expected caller:
% labkit_CurvatureMeasurement_app refreshSummary. Inputs are app state values
% and edit-mode flags. Output contains point text, result table data, and detail
% lines. This helper has no UI side effects.
function summary = summaryViewData(imagePath, xPix, fit, lengthResult, curveEditActive, referenceEditActive)
%SUMMARYVIEWDATA Build visible summary/table data for app state.

    summary = struct();
    summary.pointCountText = sprintf('Points: %d', numel(xPix));
    if fit.ok
        summary.tableData = curvature.view.fitResultTableData(fit, lengthResult);
        summary.details = { ...
            sprintf('Image: %s', curvature.view.emptyDash(imagePath)), ...
            sprintf('Center: xc = %.6f px, yc = %.6f px', fit.xc_px, fit.yc_px), ...
            sprintf('Radius: %.6f %s', fit.R_show, fit.unitLen), ...
            sprintf('Curvature: %.6f %s', fit.kappa_show, fit.unitK), ...
            sprintf('Curve length: %.6f %s', lengthResult.length_show, lengthResult.unitLen), ...
            sprintf('RMSE: %.6f %s', fit.rmse_show, fit.unitLen), ...
            sprintf('reference = %.6g px / %.6g %s; px/%s = %.6g', ...
            fit.referencePx, fit.referenceLength, fit.scaleUnit, ...
            fit.scaleUnit, fit.px_per_unit)};
    elseif lengthResult.ok
        summary.tableData = curvature.view.lengthResultTableData(lengthResult);
        summary.details = { ...
            sprintf('Image: %s', curvature.view.emptyDash(imagePath)), ...
            sprintf('Curve length: %.6f %s', lengthResult.length_show, lengthResult.unitLen), ...
            sprintf('Curve length: %.6f px', lengthResult.length_px), ...
            sprintf('Points used: %d; px/%s = %.6g', ...
            lengthResult.pointCount, lengthResult.scaleUnit, lengthResult.px_per_unit)};
    else
        summary.tableData = curvature.view.initialResultTable();
        if curveEditActive
            summary.details = {'Curve edit active. Double-click blank image space to add/insert points, drag points to move them, double-click a point to delete it. Use the scroll wheel over the image to zoom.'};
        elseif referenceEditActive
            summary.details = {'Reference-pixel edit active. Double-click two endpoints or drag existing endpoints; this sets the calibration pixel length only.'};
        elseif numel(xPix) >= 3
            summary.details = {'Curve points are ready. Fit curvature or measure curve length.'};
        elseif numel(xPix) >= 2
            summary.details = {'Curve points are ready. Measure curve length, or add more points before fitting curvature.'};
        else
            summary.details = {'Load an image and start curve editing.'};
        end
    end
end
