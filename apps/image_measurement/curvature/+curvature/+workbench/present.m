function view = present(applicationState)
%PRESENT Compose Curvature Measurement's complete semantic snapshot.
project = applicationState.project;
session = applicationState.session;
points = project.annotations.curvePoints;
fit = project.results.fit;
lengthResult = project.results.length;
imageData = session.cache.image;
hasImage = ~isempty(imageData);
editMode = string(session.workflow.editMode);

summary = curvature.curvePreview.presentationData.summaryViewData( ...
    session.cache.imagePath, points(:, 1), fit, lengthResult, ...
    editMode == "curve", editMode == "reference");
view = curvature.sourceFiles.present( ...
        session.cache.imagePath, hasImage, size(points, 1)) ...
    .include(curvature.curveEdit.present( ...
        hasImage, points, editMode)) ...
    .include(curvature.scaleCalibration.present( ...
        hasImage, project.annotations.calibration, ...
        project.parameters, editMode)) ...
    .include(curvature.analysisRun.present( ...
        hasImage, points, fit, lengthResult, editMode)) ...
    .include(curvature.curvePreview.present( ...
        imageData, points, fit, project.parameters.showDensePoints, ...
        session.view.scaleBar, editMode, ...
        project.annotations.calibration)) ...
    .tableData("resultTable", summary.tableData, ...
        Columns=["Metric", "Value"]) ...
    .text("detailsText", join(string(summary.details), newline));
end
