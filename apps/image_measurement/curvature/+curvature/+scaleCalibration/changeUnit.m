% App-owned implementation for curvature.scaleCalibration.changeUnit within the curvature product workflow.
function applicationState = changeUnit( ...
        applicationState, unitName, callbackContext)
%CHANGEUNIT Update the physical calibration unit.
calibration = applicationState.project.annotations.calibration;
applicationState.project.annotations.calibration = ...
    labkit.app.interaction.scaleCalibration( ...
        calibration.referencePixels, calibration.referenceLength, ...
        string(unitName), ...
        struct("referenceLine", calibration.referenceLine));
applicationState.session.view.scaleBar = [];
applicationState = curvature.curveEdit.clearMeasurements(applicationState);
callbackContext.log("info", ...
    "curvature.scalecalibration.changeunit.status", ...
    "Scale unit set to " + ...
    string(applicationState.project.annotations.calibration.unit) + ".");
end
