% App-owned implementation for curvature.resultFiles.exportOverlay within the curvature product workflow.
function applicationState = exportOverlay( ...
        applicationState, callbackContext)
%EXPORTOVERLAY Write the shared preview model and a standard manifest.
if isempty(applicationState.session.cache.image)
    callbackContext.alert( ...
        "Open an image before exporting an overlay.", "No image loaded");
    return
end
choice = callbackContext.chooseOutputFile( ...
    ["*.png", "PNG image (*.png)"], ...
    defaultOutputPath(applicationState, "curvature_overlay.png"));
if choice.Cancelled
    callbackContext.appendStatus("Overlay PNG export cancelled.");
    return
end
filepath = string(choice.Value);
project = applicationState.project;
try
    model = curvature.curvePreview.model( ...
        applicationState.session.cache.image, ...
        project.annotations.curvePoints, project.results.fit, ...
        project.parameters.showDensePoints, ...
        applicationState.session.view.scaleBar);
    curvature.resultFiles.writeOverlayPng(model, filepath);
    written = writeManifest(applicationState, callbackContext, ...
        filepath, "curvatureOverlay", "image/png", ...
        "curvature_overlay.labkit.json");
catch ME
    callbackContext.reportError("Export Curvature overlay PNG", ME);
    callbackContext.alert(ME.message, "Could not export overlay PNG");
    return
end
applicationState.project.results.lastOverlayExport = struct( ...
    "pngPath", filepath, "manifestPath", string(written.Value));
callbackContext.appendStatus("Exported overlay PNG: " + filepath);
end

function written = writeManifest( ...
        applicationState, callbackContext, filepath, ...
        id, mediaType, manifestName)
[folder, name, extension] = fileparts(filepath);
output = labkit.app.result.File( ...
    id, "primary", string(name) + string(extension), ...
    MediaType=mediaType);
package = labkit.app.result.Package( ...
    Outputs={output}, ...
    Inputs=struct("sources", applicationState.project.inputs.sources), ...
    Parameters=applicationState.project.parameters, ...
    Summary=struct( ...
        "fitOk", logical(applicationState.project.results.fit.ok), ...
        "lengthOk", logical(applicationState.project.results.length.ok), ...
        "pointCount", ...
            size(applicationState.project.annotations.curvePoints, 1)), ...
    ManifestName=manifestName);
written = callbackContext.writeResultPackage(folder, package);
end

function filepath = defaultOutputPath(applicationState, filename)
folder = string(fileparts(applicationState.session.cache.imagePath));
if strlength(folder) == 0 || ~isfolder(folder)
    folder = string(pwd);
end
filepath = string(fullfile(folder, filename));
end
