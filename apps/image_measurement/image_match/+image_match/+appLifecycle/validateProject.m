% Expected caller: the LabKit V2 runtime. Input is a candidate durable Image
% Match project. Output is true or this function throws for invalid buckets.
function accepted = validateProject(project)
    buckets = ["inputs", "parameters", "annotations", "results", "extensions"];
    assert(isstruct(project) && isscalar(project) && ...
        all(isfield(project, cellstr(buckets))), ...
        'image_match:InvalidProject', ...
        'Image Match project is missing required durable buckets.');
    assert(isfield(project.inputs, 'sources') && isstruct(project.inputs.sources), ...
        'image_match:InvalidProject', 'Project sources are invalid.');
    sources = project.inputs.sources;
    assert(isempty(sources) || all(isfield(sources, ...
        {'id', 'required', 'role', 'reference'})), ...
        'image_match:InvalidProject', ...
        'Sources must use the canonical source-record contract.');
    fields = {'matchMethod', 'matchStrength', 'toneStrength', ...
        'colorStrength', 'exportFormat', 'outputFolder'};
    assert(all(isfield(project.parameters, fields)), ...
        'image_match:InvalidProject', 'Project parameters are incomplete.');
    assert(isfield(project.annotations, 'steps') && ...
        isstruct(project.annotations.steps), ...
        'image_match:InvalidProject', 'Match history is invalid.');
    accepted = true;
end
