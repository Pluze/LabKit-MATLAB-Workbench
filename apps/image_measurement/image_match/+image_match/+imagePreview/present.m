function view = present(steps, currentItem, previewResult, previewMode)
%PRESENT Build the image-preview snapshot from explicit display inputs.
view = labkit.app.view.Snapshot();
view = view.tableData("historyTable", ...
    image_match.imagePreview.presentationData.historyTableData(steps), ...
    Columns=["#" "Step" "Settings"]);
view = view.tableData("metricsTable", ...
    image_match.imagePreview.presentationData.resultTableData( ...
        currentItem, previewResult, numel(steps)), ...
    Columns=["Metric" "Value"]);
view = view.renderPlot("preview", struct( ...
    "source", currentItem, ...
    "result", previewResult, ...
    "mode", previewMode));
end
