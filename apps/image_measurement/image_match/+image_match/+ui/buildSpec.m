% Expected caller: labkit_ImageMatch_app. Inputs are match-method labels,
% initial export folder text, and callback handles. Output is a data-only UI
% 2.0 workbench spec for the Image Match app.
function spec = buildSpec(methods, outputFolder, callbacks)

    spec = labkit.ui.spec.app('imageMatchApp', 'Paper Image Match', ...
        'position', [80 60 1460 860], ...
        'leftWidth', 500, ...
        'controlTabs', { ...
            labkit.ui.spec.tab('libraryExport', 'Library + Export', { ...
                labkit.ui.spec.section('librarySection', 'Library', { ...
                    labkit.ui.spec.pathPanel('sourceImages', 'Source images', ...
                        'mode', 'multiFile', ...
                        'selectionMode', 'single', ...
                        'filters', image_match.io.imageDialogFilter(), ...
                        'status', 'No images loaded', ...
                        'emptyText', 'No images loaded', ...
                        'height', 'flex', ...
                        'onChoose', callbackValue(callbacks, 'sourceImagesChosen'), ...
                        'onSelectionChange', callbackValue(callbacks, 'imageSelectionChanged'), ...
                        'onClear', callbackValue(callbacks, 'clearImages')), ...
                    labkit.ui.spec.field('imageStatus', 'Status', ...
                        'kind', 'readonly', ...
                        'value', 'Images: 0')}, ...
                    'height', 250), ...
                labkit.ui.spec.section('exportSection', 'Batch Export', { ...
                    labkit.ui.spec.field('outputFolder', 'Output folder', ...
                        'kind', 'readonly', ...
                        'value', outputFolder), ...
                    labkit.ui.spec.field('exportFormat', 'Format', ...
                        'kind', 'dropdown', ...
                        'items', {'PNG', 'TIFF', 'JPEG'}, ...
                        'value', 'PNG'), ...
                    labkit.ui.spec.actionGroup('exportActions', { ...
                        labkit.ui.spec.action('chooseOutputFolder', 'Choose folder', ...
                            callbackValue(callbacks, 'chooseOutputFolder')), ...
                        labkit.ui.spec.action('exportImages', 'Export matched images', ...
                            callbackValue(callbacks, 'exportImages'), ...
                            'enabled', false)})}, ...
                    'height', 185), ...
                labkit.ui.spec.section('exportDetailsSection', 'Export Details', { ...
                    labkit.ui.spec.statusPanel('exportDetails', 'Export Details', ...
                        'value', image_match.view.detailLines( ...
                        repmat(image_match.state.emptyItem(), 0, 1), 1, ...
                        repmat(image_match.state.emptyStep(), 0, 1), []), ...
                        'height', 'flex')}, ...
                    'height', 150)}), ...
            labkit.ui.spec.tab('matchHistory', 'Match + History', { ...
                labkit.ui.spec.section('matchSection', 'Reference Match', { ...
                    labkit.ui.spec.field('referenceImage', 'Reference', ...
                        'kind', 'dropdown', ...
                        'items', {'No reference'}, ...
                        'value', 'No reference', ...
                        'enabled', false, ...
                        'onChange', callbackValue(callbacks, 'matchSettingChanged')), ...
                    labkit.ui.spec.field('matchMethod', 'Method', ...
                        'kind', 'dropdown', ...
                        'items', methods, ...
                        'value', methods{1}, ...
                        'onChange', callbackValue(callbacks, 'matchSettingChanged')), ...
                    labkit.ui.spec.field('matchStrength', 'Strength (%)', ...
                        'kind', 'spinner', ...
                        'value', 100, ...
                        'limits', [0 100], ...
                        'step', 1, ...
                        'onChange', callbackValue(callbacks, 'matchSettingChanged')), ...
                    labkit.ui.spec.field('toneStrength', 'Tone (%)', ...
                        'kind', 'spinner', ...
                        'value', 100, ...
                        'limits', [0 100], ...
                        'step', 1, ...
                        'onChange', callbackValue(callbacks, 'matchSettingChanged')), ...
                    labkit.ui.spec.field('colorStrength', 'Color (%)', ...
                        'kind', 'spinner', ...
                        'value', 100, ...
                        'limits', [0 100], ...
                        'step', 1, ...
                        'onChange', callbackValue(callbacks, 'matchSettingChanged')), ...
                    labkit.ui.spec.action('applyMatch', 'Apply match', ...
                        callbackValue(callbacks, 'applyMatch'), ...
                        'enabled', false)}, ...
                    'height', 265), ...
                labkit.ui.spec.section('matchFlowSection', 'Match Flow', { ...
                    labkit.ui.spec.statusPanel('matchFlow', 'Match Flow', ...
                        'value', image_match.view.matchFlowLines(methods{1}), ...
                        'height', 'flex')}, ...
                    'height', 160), ...
                labkit.ui.spec.section('historySection', 'Match History', { ...
                    labkit.ui.spec.actionGroup('historyActions', { ...
                        labkit.ui.spec.action('undoHistory', 'Undo history', ...
                            callbackValue(callbacks, 'undoHistory'), ...
                            'enabled', false), ...
                        labkit.ui.spec.action('resetHistory', 'Reset history', ...
                            callbackValue(callbacks, 'resetHistory'), ...
                            'enabled', false)}), ...
                    labkit.ui.spec.resultTable('historyTable', 'Match History', ...
                        'columns', {'#', 'Step', 'Settings', 'Ref'}, ...
                        'data', image_match.view.historyTableData( ...
                        repmat(image_match.state.emptyStep(), 0, 1))), ...
                    labkit.ui.spec.field('historyStatus', 'Status', ...
                        'kind', 'readonly', ...
                        'value', 'History steps: 0')}, ...
                    'height', 245), ...
                labkit.ui.spec.section('currentImageSection', 'Current Image', { ...
                    labkit.ui.spec.resultTable('metricsTable', 'Current Image', ...
                        'columns', {'Metric', 'Value'}, ...
                        'data', image_match.view.resultTableData([], [], 0))}, ...
                    'height', 125)}), ...
            labkit.ui.spec.tab('log', 'Log', { ...
                labkit.ui.spec.section('logSection', 'Log', { ...
                    labkit.ui.spec.logPanel('logPanel', 'Log')}, ...
                    'height', 'flex')})}, ...
        'workspace', labkit.ui.spec.workspace('workspace', 'Preview', { ...
            labkit.ui.spec.previewArea('preview', 'Preview', ...
                'layout', 'single', ...
                'axisTitles', {'Matched Preview'}, ...
                'viewModes', {'Matched', 'Original', 'Before | After'}, ...
                'onModeChange', callbackValue(callbacks, 'previewModeChanged'))}));
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
