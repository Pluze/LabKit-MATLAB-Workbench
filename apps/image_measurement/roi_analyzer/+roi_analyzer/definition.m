function app = definition()
%DEFINITION Declare the ROI Analyzer product and runtime capabilities.
app = labkit.app.Definition(Entrypoint="labkit_ROIAnalyzer_app", ...
    AppId="roi_analyzer", Title="ROI Pixel Analyzer", ...
    DisplayName="ROI Analyzer", Family="Image Measurement", ...
    AppVersion="1.1.0", Updated="2026-09-05", ...
    Requirements=labkit.contract.requirements("image", ">=2.0 <3"), ...
    CreateState=@createInitialState, RefreshState=@refreshState, ...
    Workbench=roi_analyzer.workbench.buildLayout(), ...
    PresentWorkbench=@roi_analyzer.workbench.present);
end

function state = createInitialState(context, initialInput)
if isempty(initialInput)
    project = roi_analyzer.initialData();
else
    project = initialInput;
end
state = struct("project", project, ...
    "session", roi_analyzer.createSession(project, context));
end

function state = refreshState(state, context)
state.session = roi_analyzer.createSession(state.project, context);
end
