function rois = resolve(definitions, templates, imageSize)
%RESOLVE Combine ROI definitions, template geometry, and center placements.
template = struct("id", "", "name", "", ...
    "templateId", "", "centerXY", [NaN NaN], "shape", "", ...
    "size", [NaN NaN], "position", [NaN NaN NaN NaN]);
rois = repmat(template, numel(definitions), 1);
for k = 1:numel(definitions)
    match = find(string({templates.id}) == string(definitions(k).templateId), 1);
    if isempty(match)
        error("roi_analyzer:roiTemplates:UnknownTemplate", ...
            "ROI definition refers to an unknown geometry template.");
    end
    geometry = templates(match);
    center = double(definitions(k).centerXY);
    position = [center - (double(geometry.size) - 1) ./ 2, ...
        double(geometry.size)];
    position = roi_analyzer.roiLibrary.normalizePosition( ...
        position, geometry.shape, imageSize);
    center = position(1:2) + (position(3:4) - 1) ./ 2;
    rois(k) = struct("id", definitions(k).id, ...
        "name", definitions(k).name, ...
        "templateId", definitions(k).templateId, "centerXY", center, ...
        "shape", geometry.shape, "size", geometry.size, ...
        "position", position);
end
end
