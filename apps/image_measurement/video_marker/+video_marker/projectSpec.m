% App-owned durable Video Marker contract. The App SDK calls the one migration
% entry for old payload versions, legacy importer for the former MAT variable,
% and resume hooks for the current-frame convenience.
function spec = projectSpec()
    spec = labkit.app.project.Schema( ...
        Version=2, Create=@createProject, Validate=@validateProject, Migrate=@migrateProject, ...
        LegacyImports=struct( ...
            "videoMarkerProject", @importLegacyProject), ...
        CreateResume=@createResume, ...
        ApplyResume=@applyResume);
end

function project = createProject()
    project = struct();
    project.inputs = struct( ...
        "sources", struct([]), ...
        "videoMetadata", video_marker.videoSource.emptyMetadata());
    project.parameters = struct( ...
        "coordinateUnitMode", "pixels", ...
        "coordinateOriginMode", "top_left_pixel_center", ...
        "coordinateYAxisMode", "up", ...
        "coordinateStartFrame", 1, ...
        "coordinateEndFrame", 1, ...
        "scaleBarLength", 100, ...
        "scaleBarPosition", "Bottom right", ...
        "scaleBarColor", "Black");
    project.annotations = struct( ...
        "skeleton", video_marker.skeletonDefinition.defaultSkeleton(), ...
        "frames", video_marker.frameAnnotations.emptyAnnotations(0, 0), ...
        "calibration", ...
        labkit.app.interaction.scaleCalibration([], [], "px"));
    project.results = struct( ...
        "markerManifestPath", "", ...
        "coordinateManifestPath", "");
    project.extensions = struct();
end

function project = migrateProject(project, fromVersion)
    switch double(fromVersion)
        case 1
            project = migrateVersionOne(project);
        otherwise
            error('video_marker:UnsupportedProjectMigration', ...
                'Video Marker cannot migrate project version %d.', ...
                fromVersion);
    end
end

function project = migrateVersionOne(project)
    if ~isfield(project, "inputs") || ~isstruct(project.inputs)
        project.inputs = struct();
    end
    if ~isfield(project.inputs, "videoMetadata")
        project.inputs.videoMetadata = ...
            video_marker.videoSource.emptyMetadata();
    end
    if isfield(project, "annotations") && ...
            isfield(project.annotations, "frames") && ...
            isfield(project.annotations.frames, "coords") && ...
            ~isempty(project.annotations.frames.coords)
        project.inputs.videoMetadata.frameCount = ...
            size(project.annotations.frames.coords, 1);
    end
end

function [project, resume] = importLegacyProject(legacy)
    if ~isstruct(legacy) || ~isscalar(legacy) || ...
            ~isfield(legacy, 'schemaVersion') || legacy.schemaVersion ~= 1
        error('video_marker:InvalidLegacyProject', ...
            'Unsupported Video Marker legacy project schema.');
    end
    project = createProject();
    project.inputs.sources = legacySources(legacy);
    project.annotations.skeleton = legacy.skeleton;
    project.annotations.frames = ...
        video_marker.frameAnnotations.upgradeAnnotationSchema( ...
        legacy.annotations);
    project.annotations.calibration = normalizeCalibration(legacy.calibration);
    if isfield(legacy, 'exportPreferences')
        preferences = legacy.exportPreferences;
        project.parameters.coordinateUnitMode = string(preferences.unitMode);
        project.parameters.coordinateOriginMode = string(preferences.originMode);
        project.parameters.coordinateYAxisMode = string(preferences.yAxisMode);
        project.parameters.coordinateStartFrame = double(preferences.startFrame);
        project.parameters.coordinateEndFrame = double(preferences.endFrame);
    end
    currentFrame = 1;
    if isfield(legacy, 'currentFrame')
        currentFrame = double(legacy.currentFrame);
    end
    resume = struct("currentFrame", currentFrame);
end

function sources = legacySources(legacy)
    sources = struct([]);
    if isfield(legacy, 'videoReference') && ...
            isstruct(legacy.videoReference)
        sources = labkit.app.project.sourceRecord( ...
            "video", "video", legacy.videoReference, true);
    elseif isfield(legacy, 'videoPath') && ...
            strlength(string(legacy.videoPath)) > 0
        sources = labkit.app.project.sourceRecord( ...
            "video", "video", string(legacy.videoPath), true);
    end
end

function resume = createResume(session, ~)
    resume = struct("currentFrame", ...
        double(session.selection.currentFrame));
end

function session = applyResume(session, resume, ~)
    if session.cache.videoInfo.frameCount <= 0 || ...
            ~isstruct(resume) || ~isfield(resume, 'currentFrame')
        return;
    end
    target = min(max(1, round(double(resume.currentFrame))), ...
        session.cache.videoInfo.frameCount);
    videoPath = session.cache.videoPath;
    if strlength(videoPath) == 0 || ~isfile(videoPath)
        return;
    end
    [reader, ~] = video_marker.videoSource.openVideo(videoPath);
    session.selection.currentFrame = target;
    session.cache.currentImage = ...
        video_marker.videoSource.readFrame(reader, target);
    session.cache.frameIndex = target;
end

function accepted = validateProject(project)
    assert(isfield(project.inputs, 'sources') && ...
        isfield(project.inputs, 'videoMetadata') && ...
        all(isfield(project.annotations, ...
        {'skeleton', 'frames', 'calibration'})), ...
        'video_marker:InvalidProject', ...
        'Video Marker project inputs or annotations are incomplete.');
    metadata = project.inputs.videoMetadata;
    metadataFields = ["frameCount", "frameRate", "duration", ...
        "height", "width"];
    assert(isstruct(metadata) && isscalar(metadata) && ...
        all(isfield(metadata, cellstr(metadataFields))), ...
        'video_marker:InvalidProject', ...
        'Video Marker video metadata are incomplete.');
    for name = metadataFields
        value = double(metadata.(name));
        assert(isscalar(value) && isfinite(value) && value >= 0, ...
            'video_marker:InvalidProject', ...
            'Video Marker video metadata must be finite nonnegative scalars.');
    end
    parameterFields = ["coordinateUnitMode", "coordinateOriginMode", ...
        "coordinateYAxisMode", "coordinateStartFrame", ...
        "coordinateEndFrame", "scaleBarLength", ...
        "scaleBarPosition", "scaleBarColor"];
    assert(all(isfield(project.parameters, cellstr(parameterFields))), ...
        'video_marker:InvalidProject', ...
        'Video Marker project parameters are incomplete.');
    skeleton = project.annotations.skeleton;
    frames = project.annotations.frames;
    assert(isstruct(skeleton) && isscalar(skeleton) && ...
        all(isfield(skeleton, {'pointIds', 'pointNames', 'edges'})) && ...
        isstruct(frames) && isscalar(frames) && isfield(frames, 'coords'), ...
        'video_marker:InvalidProject', ...
        'Video Marker skeleton or frame annotations are malformed.');
    assert(isempty(frames.coords) || ...
        size(frames.coords, 2) == numel(skeleton.pointIds), ...
        'video_marker:InvalidProject', ...
        'Frame annotations must match the durable skeleton point count.');
    assert(isempty(frames.coords) || metadata.frameCount == 0 || ...
        size(frames.coords, 1) == metadata.frameCount, ...
        'video_marker:InvalidProject', ...
        'Frame annotations must match the durable video frame count.');
    accepted = true;
end

function calibration = normalizeCalibration(value)
    line = zeros(0, 2);
    if isstruct(value) && isfield(value, 'referenceLine')
        line = value.referenceLine;
    end
    calibration = labkit.app.interaction.scaleCalibration( ...
        fieldValue(value, 'referencePixels', NaN), ...
        fieldValue(value, 'referenceLength', 0), ...
        fieldValue(value, 'unit', "px"), ...
        struct("referenceLine", line));
end

function value = fieldValue(source, name, fallback)
    value = fallback;
    if isstruct(source) && isfield(source, name)
        value = source.(name);
    end
end
