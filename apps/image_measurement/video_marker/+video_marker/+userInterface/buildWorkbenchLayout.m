% Expected caller: video_marker.definition. Inputs are app-owned callbacks.
% Output is a data-only UI 5 workbench layout for Video Marker.
function layout = buildWorkbenchLayout(callbacks, ~)
    layout = labkit.ui.layout.workbench("videoMarkerApp", "Video Marker", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", videoWorkspace(), ...
        "usageTitle", "Workflow Notes", ...
        "usage", workflowNotesLines());
end

function tabs = controlTabs(callbacks)
    tabs = {videoTab(callbacks), skeletonTab(callbacks), exportTab(callbacks), logTab()};
end

function tab = videoTab(callbacks)
    tab = labkit.ui.layout.tab("video", "Video", { ...
        videoSection(callbacks), ...
        frameSection(callbacks), ...
        markingSection(callbacks), ...
        projectSection(callbacks)});
end

function section = videoSection(callbacks)
    filters = {'*.mp4;*.avi;*.mov;*.m4v;*.mj2', 'Video files'; '*.*', 'All files'};
    section = labkit.ui.layout.section("videoSection", "Video", { ...
        labkit.ui.layout.filePanel("videoFile", "Video file", ...
            "mode", "single", ...
            "filters", filters, ...
            "chooseLabel", "Open video", ...
            "status", "No video loaded", ...
            "emptyText", "No video loaded", ...
            "onChoose", callbackValue(callbacks, "openVideo")), ...
        labkit.ui.layout.field("videoSummary", "Video summary", ...
            "kind", "readonly", ...
            "value", "No video loaded")});
end

function section = frameSection(callbacks)
    section = labkit.ui.layout.section("frameSection", "Frame", { ...
        labkit.ui.layout.panner("currentFrame", "Current frame", ...
            "value", 1, ...
            "limits", [1 2], ...
            "step", 1, ...
            "onChange", callbackValue(callbacks, "frameChanged")), ...
        labkit.ui.layout.group("frameActions", "", { ...
            labkit.ui.layout.action("previousFrame", "Previous frame", ...
                callbackValue(callbacks, "previousFrame"), "enabled", false), ...
            labkit.ui.layout.action("nextFrame", "Next frame", ...
                callbackValue(callbacks, "nextFrame"), "enabled", false)})});
end

function section = markingSection(callbacks)
    section = labkit.ui.layout.section("markingSection", "Marking", { ...
        labkit.ui.layout.action("startPointEdit", "Start point edit", ...
            callbackValue(callbacks, "startPointEdit"), "enabled", false), ...
        labkit.ui.layout.group("pointActions", "", { ...
            labkit.ui.layout.action("undoPoint", "Undo last point", ...
                callbackValue(callbacks, "undoPoint"), "enabled", false), ...
            labkit.ui.layout.action("clearFramePoints", "Clear frame points", ...
                callbackValue(callbacks, "clearFramePoints"), "enabled", false)}), ...
        labkit.ui.layout.action("confirmFrame", "Confirm frame", ...
            callbackValue(callbacks, "confirmFrame"), "enabled", false), ...
        labkit.ui.layout.field("frameStatus", "Frame status", ...
            "kind", "readonly", ...
            "value", "Frame: empty")});
end

function tab = skeletonTab(callbacks)
    tab = labkit.ui.layout.tab("skeleton", "Skeleton + Scale", { ...
        labkit.ui.layout.section("skeletonSection", "Skeleton", { ...
            labkit.ui.layout.field("keypointNames", "Keypoints", ...
                "kind", "text", ...
                "value", "point_1, point_2, point_3, point_4, point_5"), ...
            labkit.ui.layout.field("skeletonEdges", "Connections", ...
                "kind", "text", ...
                "value", "point_1-point_2, point_2-point_3, point_3-point_4, point_4-point_5"), ...
            labkit.ui.layout.action("applySkeleton", "Apply skeleton", ...
                callbackValue(callbacks, "applySkeleton"))}), ...
        labkit.ui.layout.section("scaleSection", "Scale", { ...
            labkit.ui.layout.toolPanel("scaleBarHost", "Scale controls")})});
end

function tab = exportTab(callbacks)
    tab = labkit.ui.layout.tab("export", "Import + Export", { ...
        labkit.ui.layout.section("markerCsvSection", "Marker CSV", { ...
            labkit.ui.layout.group("markerCsvActions", "", { ...
                labkit.ui.layout.action("importMarkerCsv", "Import marker CSV", ...
                    callbackValue(callbacks, "importMarkerCsv")), ...
                labkit.ui.layout.action("exportMarkerCsv", "Export marker CSV", ...
                    callbackValue(callbacks, "exportMarkerCsv"), "enabled", false)})}), ...
        labkit.ui.layout.section("coordinateCsvSection", "Coordinate CSV", { ...
            labkit.ui.layout.field("coordinateUnitMode", "Unit", ...
                "kind", "dropdown", "items", {'pixels', 'calibrated_physical'}, ...
                "value", "pixels"), ...
            labkit.ui.layout.field("coordinateOriginMode", "Origin", ...
                "kind", "dropdown", "items", {'top_left_pixel_center', 'first_point'}, ...
                "value", "top_left_pixel_center"), ...
            labkit.ui.layout.field("coordinateYAxisMode", "Y axis", ...
                "kind", "dropdown", "items", {'up', 'down'}, ...
                "value", "up"), ...
            labkit.ui.layout.group("coordinateRange", "", { ...
                labkit.ui.layout.field("coordinateStartFrame", "Start frame", ...
                    "kind", "number", "value", 1), ...
                labkit.ui.layout.field("coordinateEndFrame", "End frame", ...
                    "kind", "number", "value", 1)}), ...
            labkit.ui.layout.action("exportCoordinateCsv", "Export coordinate CSV", ...
                callbackValue(callbacks, "exportCoordinateCsv"), "enabled", false)}), ...
        labkit.ui.layout.section("summarySection", "Summary", { ...
            labkit.ui.layout.resultTable("summaryTable", "Annotation Summary", ...
                "columns", {'Metric', 'Value'}, ...
                "data", {'Video', 'none'; 'Frames', '0'; 'Confirmed', '0'})})});
end

function section = projectSection(callbacks)
    section = labkit.ui.layout.section("projectSection", "Project", { ...
        labkit.ui.layout.group("projectActions", "", { ...
            labkit.ui.layout.action("openProject", "Open project", ...
                callbackValue(callbacks, "openProject")), ...
            labkit.ui.layout.action("saveProject", "Save project", ...
                callbackValue(callbacks, "saveProject"), "enabled", false)})});
end

function tab = logTab()
    tab = labkit.ui.layout.tab("log", "Log", { ...
        labkit.ui.layout.section("logSection", "Log", { ...
            labkit.ui.layout.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function workspace = videoWorkspace()
    workspace = labkit.ui.layout.workspace("videoPreview", "Video Preview", { ...
        labkit.ui.layout.previewArea("videoAxes", "Video Preview", ...
            "layout", "single", ...
            "axisIds", {'video'}, ...
            "axisTitles", {'Frame + Skeleton'})});
end

function lines = workflowNotesLines()
    lines = { ...
        '1. Open a video and define the ordered keypoints plus connections.', ...
        '2. Start point edit, click keypoints in order, drag to refine, then confirm the frame.', ...
        '3. Moving to a new frame inherits the previous confirmed frame as a draft.', ...
        '4. Export marker CSV for round-trip editing or coordinate CSV for plotting.'};
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end
