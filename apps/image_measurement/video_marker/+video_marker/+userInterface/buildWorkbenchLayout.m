function lines = workflowNotesLines()
    lines = { ...
        '1. Use an editable preset or add and name ordered keypoints, then add connections.', ...
        '2. Open a video, click points in table order, and drag existing points to refine.', ...
        '3. Moving forward predicts points automatically; dragging any point creates a new manual anchor.', ...
        '4. Export marker CSV for round-trip editing or coordinate CSV for plotting.'};
end

function value = callbackValue(callbacks, fieldName)
    value = [];
    fieldName = char(fieldName);
    if isstruct(callbacks) && isfield(callbacks, fieldName)
        value = callbacks.(fieldName);
    end
end

function control = panner(id, label, value, limits, step, enabled, eventId, callbacks)
    control = labkit.ui.layout.panner(id, label, ...
        "value", value, "limits", limits, "step", step, ...
        "enabled", enabled, "onChange", callbackValue(callbacks, eventId));
end

function control = boundPanner(id, label, value, limits, step, enabled, bind, eventId)
    control = labkit.ui.layout.panner(id, label, ...
        "value", value, "limits", limits, "step", step, ...
        "enabled", enabled, "Bind", bind, "Event", eventId);
end

function control = boundDropdown(id, label, items, value, bind, eventId, enabled)
    control = labkit.ui.layout.field(id, label, ...
        "kind", "dropdown", "items", items, "value", value, ...
        "enabled", enabled, "Bind", bind, "Event", eventId);
end
