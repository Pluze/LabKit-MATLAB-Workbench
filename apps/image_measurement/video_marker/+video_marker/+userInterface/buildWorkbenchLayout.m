% Expected caller: video_marker.definition. Inputs are app-owned callbacks.
% Output is a data-only UI 5 workbench layout for Video Marker.
function layout = buildWorkbenchLayout(callbacks, ~)
    layout = labkit.ui.layout.workbench("videoMarkerApp", "Video Marker", ...
        "controlTabs", controlTabs(callbacks), ...
        "workspace", videoWorkspace(), ...
        "usageTitle", "Workflow Notes", ...
        "usage", workflowNotesLines());
end

function tabs = controlTabs(callbacks)
    tabs = {setupTab(callbacks), videoTab(callbacks), exportTab(callbacks), logTab()};
end

function tab = setupTab(callbacks)
    tab = labkit.ui.layout.tab("setup", "Setup + Scale", { ...
        skeletonSection(callbacks), ...
        scaleSection(callbacks)});
end

