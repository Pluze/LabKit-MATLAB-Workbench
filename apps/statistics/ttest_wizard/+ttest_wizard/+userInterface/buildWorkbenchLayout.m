% App layout factory; builds a compact data-test-plot workbench.
function layout = buildWorkbenchLayout(callbacks, ~)
%BUILDWORKBENCHLAYOUT Build the semantic multi-group T-Test Wizard workbench.
%
% Expected caller: ttest_wizard.definition. Inputs are framework-generated
% callbacks and optional initial state. The output keeps file/group commands
% and test/plot controls on the left, with native Data and Plot workspace pages
% on the right. It performs no IO, calculation, or handle creation.

    layout = labkit.ui.layout.workbench( ...
        "ttestWizardApp", "T-Test Wizard", ...
        "controlTabs", { ...
        dataTab(callbacks), ...
        analysisTab(callbacks), ...
        exportTab(callbacks), ...
        logTab()}, ...
        "workspace", mainWorkspace(callbacks), ...
        "usageTitle", "Fast workflow", ...
        "usage", { ...
        "1. Open/paste data and assign values to groups.", ...
        "2. Keep the reference group first and run comparisons.", ...
        "3. Switch the workspace to Plot and adjust presentation.", ...
        "4. Rerun after any data or test change to refresh the plot."});
end

function tab = dataTab(callbacks)
    tab = labkit.ui.layout.tab("data", "1 Data", { ...
        labkit.ui.layout.section("sourceSection", "Source Table", { ...
            labkit.ui.layout.filePanel("sourceFile", "CSV or workbook", ...
                "mode", "single", ...
                "filters", {'*.csv;*.tsv;*.xlsx;*.xls', ...
                'Tables (*.csv, *.tsv, *.xlsx, *.xls)'}, ...
                "chooseLabel", "Open table", ...
                "emptyText", "No table open", ...
                "onChoose", callbacks.openSource, ...
                "onClear", callbacks.clearSource), ...
            labkit.ui.layout.field("sourceSheet", "Worksheet", ...
                "kind", "dropdown", "items", {'(no source)'}, ...
                "value", "(no source)", ...
                "Bind", "project.inputs.sourceSheet", ...
                "Event", "sheetChanged"), ...
            labkit.ui.layout.field("sourceSummary", "Table", ...
                "kind", "readonly", "value", "Open a CSV or workbook"), ...
            labkit.ui.layout.field( ...
                "selectionSummary", "Selected cells", ...
                "kind", "readonly", ...
                "value", "Select numeric cells in the upper data table.")}), ...
        labkit.ui.layout.section("assignSection", "Add Selected Values", { ...
            labkit.ui.layout.field("captureTarget", "Source selection to", ...
                "kind", "dropdown", "items", {'(new group)'}, ...
                "value", "(new group)", ...
                "Bind", "project.parameters.captureTarget"), ...
            labkit.ui.layout.action( ...
                "captureGroup", "Add selected source cells", ...
                callbacks.captureGroup, "enabled", false, ...
                "priority", "primary"), ...
            labkit.ui.layout.field( ...
                "batchGroupTarget", "Selected data rows to", ...
                "kind", "dropdown", "items", {'(select group)'}, ...
                "value", "(select group)", ...
                "Bind", "session.selection.batchGroupTarget"), ...
            labkit.ui.layout.action( ...
                "assignRowsToGroup", "Change selected rows", ...
                callbacks.assignRowsToGroup, "enabled", false), ...
            labkit.ui.layout.action( ...
                "deleteSelectedRows", "Delete selected rows", ...
                callbacks.deleteSelectedRows, "enabled", false), ...
            labkit.ui.layout.action( ...
                "clearGroups", "Clear all data", ...
                callbacks.clearGroups, "enabled", false)})});
end

function tab = analysisTab(callbacks)
    choices = ttest_wizard.testRun.choices();
    plotChoices = ttest_wizard.userInterface.plotChoices();
    tab = labkit.ui.layout.tab("analysis", "2 Test & Plot", { ...
        labkit.ui.layout.section("testSection", "Run T-Tests", { ...
            labkit.ui.layout.field("testMethod", "Test", ...
                "kind", "dropdown", ...
                "items", cellstr(choices.methodLabels), ...
                "value", choices.methodLabels(1), ...
                "Bind", "project.parameters.testMethod", ...
                "Event", "testSettingsChanged"), ...
            labkit.ui.layout.field("alternative", ...
                "Question (reference minus comparison)", ...
                "kind", "dropdown", ...
                "items", cellstr(choices.alternativeLabels), ...
                "value", choices.alternativeLabels(1), ...
                "Bind", "project.parameters.alternative", ...
                "Event", "testSettingsChanged"), ...
            labkit.ui.layout.field("alpha", "Alpha", ...
                "kind", "number", "value", 0.05, ...
                "Bind", "project.parameters.alpha", ...
                "Event", "testSettingsChanged"), ...
            labkit.ui.layout.statusPanel( ...
                "pendingTest", "What will run", ...
                "value", "Add at least two groups first."), ...
            labkit.ui.layout.action( ...
                "runComparisons", "Run / refresh comparisons", ...
                callbacks.runComparisons, "enabled", false, ...
                "priority", "primary")}), ...
        labkit.ui.layout.section("resultSection", "Latest Results", { ...
            labkit.ui.layout.statusPanel( ...
                "resultStatus", "Result family", ...
                "value", "No comparisons have been run."), ...
            labkit.ui.layout.resultTable( ...
                "resultTable", "Each group versus reference", ...
                "columns", {'Comparison', 'Difference', 'p', ...
                'Significance', 'Status'}, ...
                "data", {'Not run', '', '', '', ''})}), ...
        labkit.ui.layout.section("plotSection", "Plot Style", { ...
            labkit.ui.layout.field("plotFreshness", "Plot status", ...
                "kind", "readonly", ...
                "value", "Run comparisons to create the plot."), ...
            labkit.ui.layout.field("plotType", "Plot", ...
                "kind", "dropdown", "items", cellstr(plotChoices.types), ...
                "value", plotChoices.types(1), ...
                "Bind", "project.parameters.plot.type", ...
                "Event", "plotChanged"), ...
            labkit.ui.layout.field("showPoints", ...
                "Overlay individual values", ...
                "kind", "checkbox", "value", false, ...
                "Bind", "project.parameters.plot.showPoints", ...
                "Event", "plotChanged"), ...
            labkit.ui.layout.field("showSummary", "Show SD bars (bar plot)", ...
                "kind", "checkbox", "value", true, ...
                "Bind", "project.parameters.plot.showSummary", ...
                "Event", "plotChanged"), ...
            labkit.ui.layout.field("showPValue", ...
                "Show significance brackets", ...
                "kind", "checkbox", "value", true, ...
                "Bind", "project.parameters.plot.showPValue", ...
                "Event", "plotChanged"), ...
            labkit.ui.layout.field("plotTitle", "Title", ...
                "kind", "text", "value", "", ...
                "Bind", "project.parameters.plot.title", ...
                "Event", "plotChanged"), ...
            labkit.ui.layout.field("yLabel", "Y-axis label", ...
                "kind", "text", "value", "Value", ...
                "Bind", "project.parameters.plot.yLabel", ...
                "Event", "plotChanged")})});
end

