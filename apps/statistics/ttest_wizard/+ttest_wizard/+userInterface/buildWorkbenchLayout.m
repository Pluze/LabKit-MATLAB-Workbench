function tab = logTab()
    tab = labkit.ui.layout.tab("log", "Log", { ...
        labkit.ui.layout.section("logSection", "Log", { ...
            labkit.ui.layout.logPanel("appLog", "Log", ...
                "value", {'Ready.'})})});
end

function workspace = mainWorkspace(callbacks)
    dataPage = labkit.ui.layout.tab("dataPage", "Data", { ...
        labkit.ui.layout.resultTable( ...
            "sourceGrid", ...
            "Opened table — select numeric cells here", ...
            "columns", {'A'}, "rowName", {'1'}, ...
            "data", {'Open a CSV or workbook'}, ...
            "onSelectionChange", callbacks.sourceSelectionChanged), ...
        labkit.ui.layout.resultTable( ...
            "dataTable", ...
            "Analysis data — type or paste Group and Value", ...
            "columns", {'Group', 'Value'}, ...
            "data", {'', ''}, ...
            "columnEditable", [true true], ...
            "onCellEdit", callbacks.groupsEdited, ...
            "onSelectionChange", callbacks.analysisSelectionChanged)});
    plotPage = labkit.ui.layout.tab("plotPage", "Plot", { ...
        labkit.ui.layout.previewArea( ...
            "resultPlot", "Statistical comparison plot", ...
            "layout", "single", "axisIds", {'main'}, ...
            "axisTitles", {'All groups vs reference'})});
    workspace = labkit.ui.layout.workspace( ...
        "workspace", "Data and Plot", {dataPage, plotPage});
end
