% App result writer; writes one row per first-group comparison.
function writeResultCsv(filepath, results)
%WRITERESULTCSV Write completed or attempted t-tests as comparison rows.
%
% Expected caller: T-Test Wizard result export. filepath is scalar output text
% and results is a nonempty vector of canonical runTTest structs. The file has
% one readable header and preserves comparison order. The only side effect is
% writing filepath.

    filepath = string(filepath);
    assert(isscalar(filepath) && strlength(filepath) > 0, ...
        'ttest_wizard:InvalidOutputPath', ...
        'Result CSV output path must be nonempty scalar text.');
    required = fieldnames(ttest_wizard.testRun.emptyResult());
    assert(isstruct(results) && ~isempty(results) && ...
        all(arrayfun(@(result) all(isfield(result, required)), results(:))), ...
        'ttest_wizard:InvalidResult', ...
        'Result export requires canonical t-test results.');
    headers = { ...
        'Test', 'Alternative', 'Alpha', 'Reference Group', ...
        'Comparison Group', 'N Reference', 'N Comparison', 'N Pairs', ...
        'Mean Reference', 'SD Reference', 'Mean Comparison', ...
        'SD Comparison', 'Difference Reference-Comparison', ...
        'SE', 'T', 'DF', 'P', 'CI Lower', 'CI Upper', ...
        'Significance', 'Status', 'Message'};
    rows = cell(numel(results), numel(headers));
    for k = 1:numel(results)
        result = results(k);
        rows(k, :) = { ...
            char(result.method), char(result.alternative), result.alpha, ...
            char(result.labelA), char(result.labelB), ...
            result.nA, result.nB, result.nPairs, ...
            result.meanA, result.sdA, result.meanB, result.sdB, ...
            result.meanDifference, result.standardError, ...
            result.tStatistic, result.degreesOfFreedom, result.pValue, ...
            result.ciLower, result.ciUpper, significanceText(result), ...
            char(result.status), char(result.message)};
    end
    writecell([headers; rows], filepath);
end

function value = significanceText(result)
    if ~result.ok
        value = '';
    elseif result.pValue < 1e-4
        value = '****';
    elseif result.pValue < 1e-3
        value = '***';
    elseif result.pValue < 1e-2
        value = '**';
    elseif result.pValue < result.alpha
        value = '*';
    else
        value = 'NS';
    end
end
