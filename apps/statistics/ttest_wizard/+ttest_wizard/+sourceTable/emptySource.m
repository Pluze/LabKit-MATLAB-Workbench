function source = emptySource()
%EMPTYSOURCE Create the transient no-table-loaded source record.
%
% Expected callers: session creation and source-clear actions. The output has
% the same display fields as readSourceTable with ok=false and empty cells.
% Side effects are none.

    source = struct( ...
        "ok", false, ...
        "filepath", "", ...
        "displayName", "", ...
        "sheet", "(no source)", ...
        "sheetNames", "(no source)", ...
        "cells", {cell(0, 0)}, ...
        "columnNames", {{'A'}}, ...
        "rowNames", {{'1'}}, ...
        "rowCount", 0, ...
        "columnCount", 0, ...
        "message", "Open a CSV or workbook to select data.");
end
