function installFilePanelCallbacks(obj, node, list)
% Class-folder implementation of MatlabPlatformAdapter.installFilePanelCallbacks.
    handles = list.UserData;
    list.ValueChangedFcn = @(src, ~) obj.runUtility(@() ...
        obj.Runtime.applyFilePanelSelection(node.Id, ...
        labkit.app.internal.NativeAdapterValues.selectedIndices(src)), ...
        "Could not select file");
    handles.Choose.ButtonPushedFcn = @(~, ~) obj.runUtility( ...
        @() obj.chooseFiles(node.Id), "Could not add files");
    if ~isempty(handles.Folder)
        handles.Folder.ButtonPushedFcn = @(~, ~) obj.runUtility( ...
            @() obj.chooseFolderFiles(node.Id, false), ...
            "Could not add folder");
    end
    if ~isempty(handles.RecursiveFolder)
        handles.RecursiveFolder.ButtonPushedFcn = @(~, ~) obj.runUtility( ...
            @() obj.chooseFolderFiles(node.Id, true), ...
            "Could not add folder tree");
    end
    if ~isempty(handles.Remove)
        handles.Remove.ButtonPushedFcn = @(~, ~) ...
            obj.removeSelectedFiles(node.Id, list);
    end
    if ~isempty(handles.Clear)
        handles.Clear.ButtonPushedFcn = @(~, ~) obj.runUtility(@() ...
            obj.Runtime.applyFileSelection( ...
            node.Id, strings(1, 0), zeros(1, 0)), ...
            "Could not clear files");
    end
end
