function list = createFilePanel(~, node, parent)
% Class-folder implementation of MatlabPlatformAdapter.createFilePanel.
    config = node.Configuration;
    policy = labkit.app.internal.native.NativeAdapterValues.layoutPolicy();
    panel = uipanel(parent, BorderType="line", ...
        Title=char(config.Label));
    if config.SelectionMode == "single" && config.MaxFiles == 1
        panel.Title = "";
        panel.BorderType = "none";
        grid = uigridlayout(panel, [3 1], Padding=[0 2 0 2], ...
            RowHeight={22, policy.ButtonHeight, '1x'}, RowSpacing=4);
        grid.Tag = char(node.Id + ".layout");
        uilabel(grid, Text=config.Label, FontSize=14, FontWeight="bold");
        choose = uibutton(grid, Text=config.ChooseLabel, ...
            Tag=char(node.Id + ".choose"), Tooltip=char(config.ChooseTooltip));
        status = uitextarea(grid, Editable="off", ...
            Value=cellstr(string(config.EmptyText)), WordWrap="on", ...
            Tag=char(node.Id + ".status"));
        list = uilistbox(panel, Items=strings(1, 0), ...
            Visible="off", Position=[0 0 1 1]);
        list.UserData = struct("Panel", panel, ...
            "Choose", choose, "Folder", [], ...
            "RecursiveFolder", [], "Remove", [], "Clear", [], ...
            "Status", status, "EmptyText", config.EmptyText, ...
            "Target", node.Id, "Compact", true, ...
            "Paths", strings(1, 0), ...
            "ItemStatuses", strings(1, 0));
        return
    end
    % This component has a source action row, a collection viewport and
    % selection actions. Only a presenter-supplied message needs a status box.
    panel.Title = "";
    panel.BorderType = "none";
    grid = uigridlayout(panel, [5 1], Padding=[0 4 0 4], ...
        RowHeight={24, 2 * policy.ButtonHeight + policy.ButtonGap, '1x', 0, 0}, RowSpacing=5);
    grid.Tag = char(node.Id + ".layout");
    uilabel(grid, Text=config.Label, FontSize=16, FontWeight="bold");
    addButtons = uigridlayout(grid, [2 2], Padding=[0 0 0 0], ...
        RowSpacing=policy.ButtonGap, ColumnSpacing=policy.ButtonGap);
    addButtons.Layout.Row = 2;
    choose = uibutton(addButtons, Text=config.ChooseLabel, Tag= ...
        char(node.Id + ".choose"), Tooltip=char(config.ChooseTooltip));
    choose.Layout.Row = 1;
    choose.Layout.Column = [1 2];
    folder = uibutton(addButtons, Text=config.FolderLabel, Tag= ...
        char(node.Id + ".folder"), Tooltip=char(config.FolderLabel));
    recursive = uibutton(addButtons, ...
        Text=config.RecursiveFolderLabel, Tag= ...
        char(node.Id + ".recursiveFolder"), ...
        Tooltip=char(config.RecursiveFolderLabel));
    list = uilistbox(grid, Items=strings(1, 0), Visible="off", ...
        Multiselect=config.SelectionMode == "multiple");
    list.Layout.Row = 3;
    empty = uilabel(grid, Text=config.EmptyText, HorizontalAlignment="center", ...
        WordWrap="on", Tag=node.Id + ".empty");
    empty.Layout.Row = 3;
    empty.Layout.Column = 1;
    selectionButtons = uigridlayout(grid, [1 3], Visible="off", ...
        Padding=[0 0 0 0], ColumnWidth={'1x', '1.4x', '1x'}, ColumnSpacing=5);
    selectionButtons.Layout.Row = 4;
    count = [];
    selectAll = [];
    if config.SelectionMode == "multiple"
        selectAll = uibutton(selectionButtons, Text="Select all", Tag=node.Id + ".selectAll");
    else
        count = uilabel(selectionButtons, Text="", FontWeight="bold", ...
            Visible=labkit.app.internal.native.NativeAdapterValues.onOff(config.ShowStatus));
    end
    remove = uibutton(selectionButtons, ...
        Text=config.RemoveLabel, Tag= ...
        char(node.Id + ".remove"), Tooltip=char(config.RemoveLabel));
    clear = uibutton(selectionButtons, ...
        Text=config.ClearLabel, Tag= ...
        char(node.Id + ".clear"), Tooltip=char(config.ClearLabel));
    buttons = [choose, folder, recursive, remove, clear];
    for k = 1:numel(buttons)
        labkit.app.internal.native.NativeAdapterValues.fitText(buttons(k), ...
            CharsPerStep=18, MaxShrinkSteps=3);
    end
    status = [];
    if config.ShowStatus
        status = uitextarea(grid, Editable="off", ...
            Value="", Visible="off", WordWrap="on", ...
            Tag=char(node.Id + ".status"));
        status.Layout.Row = 5;
    end
    list.UserData = struct("Panel", panel, "Choose", choose, ...
        "Folder", folder, "RecursiveFolder", recursive, ...
        "Remove", remove, "Clear", clear, "Status", status, ...
        "EmptyText", config.EmptyText, "Target", node.Id, ...
        "Compact", false, "EmptyLabel", empty, "CountLabel", count, "SelectAll", selectAll, ...
        "Paths", strings(1, 0), ...
        "ItemStatuses", strings(1, 0));
end
