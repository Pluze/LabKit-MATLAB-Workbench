function installUtilityMenus(obj)
% Install the two everyday image-copy actions and session diagnostics.
    toolsMenu = uimenu(obj.Figure, Text="Tools", ...
        Tag="labkitAppUtilityToolsMenu");
    uimenu(toolsMenu, Text="Copy Main Plots", ...
        Tag="labkitAppUtilityCopyPlot", ...
        MenuSelectedFcn=@(~, ~) obj.runUtility(@() obj.Runtime.performPlotOperation( ...
            "plots.copy_main", @() obj.copyMainPlots())));
    uimenu(toolsMenu, Text="Copy Current Interface", ...
        Tag="labkitAppUtilityCopyScreenshot", ...
        MenuSelectedFcn=@(~, ~) obj.runUtility(@() obj.Runtime.performPlotOperation( ...
            "plots.copy_interface", @() obj.copyScreenshot())));
    diagnosticsMenu = uimenu(toolsMenu, Text="Diagnostics", ...
        Separator="on", Tag="labkitAppUtilityDiagnosticsMenu");
    uimenu(diagnosticsMenu, Text="Open Session Log...", ...
        Tag="labkitAppUtilitySessionLog", ...
        MenuSelectedFcn=@(~, ~) obj.runUtility(@() obj.openSessionLog()));
end
