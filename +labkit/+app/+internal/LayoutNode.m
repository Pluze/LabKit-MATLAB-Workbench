        function obj = workspace(varargin)
            content = {};
            if ~isempty(varargin) && isa(varargin{1}, "labkit.app.internal.LayoutNode")
                content = {varargin{1}};
                varargin = varargin(2:end);
            end
            options = labkit.app.internal.OptionParser.parse( ...
                "labkit.app.layout.workspace", ...
                ["Title", "OnPageChanged"], varargin{:});
            signal = labkit.app.internal.LayoutNodeValues.optionalSignal("workspace", "pageChanged", ...
                labkit.app.internal.LayoutNodeValues.optionValue(options, "OnPageChanged", []));
            if ~isempty(content)
                labkit.app.internal.LayoutNodeValues.validateChildKinds(content, labkit.app.internal.LayoutNodeValues.workspaceContentKinds(), ...
                    "workspace");
            end
            obj = labkit.app.internal.LayoutNode("workspace", "workspace", content, ...
                strings(1, 0), labkit.app.internal.LayoutNodeValues.signalCell(signal), [], ...
                strings(1, 0), struct("Title", labkit.app.internal.LayoutNodeValues.nonemptyText( ...
                labkit.app.internal.LayoutNodeValues.optionValue(options, "Title", "Workspace"), ...
                "workspace title")));
        end

