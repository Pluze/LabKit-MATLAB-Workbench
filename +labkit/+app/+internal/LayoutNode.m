            options = labkit.app.internal.OptionParser.parse( ...
                "labkit.app.layout.workbench", ...
                ["Workspace", "Usage", "UsageTitle"], varargin{:});
            children = labkit.app.internal.LayoutNodeValues.normalizeChildren(children);
            labkit.app.internal.LayoutNodeValues.validateChildKinds(children, ...
                [labkit.app.internal.LayoutNodeValues.leafAndGroupKinds(), "section", "tab"], "workbench");
            usage = labkit.app.internal.LayoutNodeValues.textRow(labkit.app.internal.LayoutNodeValues.optionValue( ...
                options, "Usage", strings(1, 0)), "Usage");
            if ~isempty(usage)
                usageTitle = labkit.app.internal.LayoutNodeValues.nonemptyText(labkit.app.internal.LayoutNodeValues.optionValue( ...
                    options, "UsageTitle", "Usage"), "UsageTitle");
                usagePanel = labkit.app.internal.LayoutNode.statusPanel( ...
                    "applicationUsage", Title=usageTitle, Text=usage);
                usageSection = labkit.app.internal.LayoutNode.section( ...
                    "applicationUsageSection", usageTitle, {usagePanel});
                if ~isempty(children) && children{1}.Kind == "tab"
                    first = children{1};
                    children{1} = labkit.app.internal.LayoutNode( ...
                        "tab", first.Id, ...
                        [first.Children, {usageSection}], ...
                        first.Capabilities, first.Signals, ...
                        first.Renderer, first.AxisIds, ...
                        first.Configuration);
                else
                    children{end + 1} = usageSection;
                end
            end
            workspace = labkit.app.internal.LayoutNodeValues.optionValue(options, "Workspace", []);
            if ~isempty(workspace)
                if ~isa(workspace, "labkit.app.internal.LayoutNode") || ...
                        workspace.Kind ~= "workspace"
                    error("labkit:app:contract:InvalidValue", ...
                        "Layout workbench Workspace must be a workspace value.");
                end
                children{end + 1} = workspace;
            end
            obj = labkit.app.internal.LayoutNode("workbench", "application", children, ...
                strings(1, 0), {}, [], strings(1, 0), struct());
        end
    end

    methods
        function obj = page(obj, id, title, content)
            if obj.Kind ~= "workspace"
                error("labkit:app:contract:UnsupportedOperation", ...
                    "Layout page is available only on a workspace.");
            end
            if ~isempty(obj.Children) && isempty(obj.PageIds)
                error("labkit:app:contract:UnsupportedOperation", ...
                    "A single-content workspace cannot also declare " + ...
                    "named pages.");
            end
            id = labkit.app.internal.LayoutNodeValues.normalizeId(id);
            if any(obj.PageIds == id)
                error("labkit:app:contract:DuplicateId", ...
                    "Workspace page ID repeats: %s.", id);
            end
            if isa(content, "labkit.app.internal.LayoutNode")
                content = {content};
            else
                content = labkit.app.internal.LayoutNodeValues.normalizeChildren(content);
            end
            if isempty(content)
                error("labkit:app:contract:InvalidValue", ...
                    "Workspace page content must not be empty.");
            end
            labkit.app.internal.LayoutNodeValues.validateChildKinds(content, labkit.app.internal.LayoutNodeValues.workspaceContentKinds(), ...
                "workspace page");
            pageNode = labkit.app.internal.LayoutNode("workspacePage", id, content, ...
                ["workspacePage"], {}, [], strings(1, 0), ...
                struct("Title", labkit.app.internal.LayoutNodeValues.nonemptyText(title, "workspace page title")));
            obj.Children{end + 1} = pageNode;
            obj.PageIds(end + 1) = id;
            if strlength(obj.InitialPage) == 0
                obj.InitialPage = id;
            end
        end

        function obj = initialPage(obj, id)
            if obj.Kind ~= "workspace"
                error("labkit:app:contract:UnsupportedOperation", ...
                    "Layout initialPage is available only on a workspace.");
            end
            id = labkit.app.internal.LayoutNodeValues.normalizeId(id);
            if ~any(obj.PageIds == id)
                error("labkit:app:contract:UnknownReference", ...
                    "Workspace initial page is undeclared: %s.", id);
            end
            obj.InitialPage = id;
        end
    end

    methods (Access = ?labkit.app.internal.CompiledDefinition)
        function nodes = flattenForCompiler(obj)
            chunks = cell(1, 1 + numel(obj.Children));
            chunks{1} = {obj};
            for k = 1:numel(obj.Children)
                chunks{k + 1} = obj.Children{k}.flattenForCompiler();
            end
            nodes = [chunks{:}];
        end

        function value = configurationForCompiler(obj)
            value = obj.Configuration;
        end
    end
end

function obj = makeLeaf(kind, id, capabilities, signals, configuration)
    obj = labkit.app.internal.LayoutNode(kind, labkit.app.internal.LayoutNodeValues.normalizeId(id), {}, capabilities, ...
        signals, [], strings(1, 0), configuration);
end

function obj = makeContainer(kind, id, children, configuration)
    obj = labkit.app.internal.LayoutNode(kind, labkit.app.internal.LayoutNodeValues.normalizeId(id), children, ...
        strings(1, 0), {}, [], strings(1, 0), configuration);
end

