function [index, status] = indexFile(filepath)
%INDEXFILE Build an Intan RHS sample/block index for lazy reads.
%
% Inputs:
%   filepath - char/string path to one .rhs file.
%
% Outputs:
%   index - struct containing the parsed header plus byte/sample layout used
%           by labkit.rhs.readWindow.
%   status - struct with ok, message, and filepath. Header-only files and
%            files with trailing partial bytes are represented without
%            loading waveform arrays.

    filepath = normalizeFilepath(filepath);
    [info, status] = labkit.rhs.inspectFile(filepath);
    index = emptyIndex(filepath, info);

    if ~status.ok
        return;
    end

    index = struct( ...
        "type", "rhsIndex", ...
        "version", 1, ...
        "filepath", filepath, ...
        "info", info, ...
        "sampleRateHz", info.sampleRateHz, ...
        "samplesPerBlock", info.samplesPerBlock, ...
        "dataOffsetBytes", info.dataOffsetBytes, ...
        "bytesPerBlock", info.bytesPerBlock, ...
        "dataBytes", info.dataBytes, ...
        "blockCount", info.blockCount, ...
        "sampleCount", info.sampleCount, ...
        "durationSec", info.durationSec, ...
        "exactBlocks", info.exactBlocks, ...
        "hasData", info.sampleCount > 0);

    if ~info.exactBlocks
        status.message = "Data section has trailing partial bytes; full blocks are still indexed.";
    end
end

function index = emptyIndex(filepath, info)
    index = struct( ...
        "type", "rhsIndex", ...
        "version", 1, ...
        "filepath", filepath, ...
        "info", info, ...
        "sampleRateHz", NaN, ...
        "samplesPerBlock", 128, ...
        "dataOffsetBytes", NaN, ...
        "bytesPerBlock", NaN, ...
        "dataBytes", NaN, ...
        "blockCount", 0, ...
        "sampleCount", 0, ...
        "durationSec", NaN, ...
        "exactBlocks", false, ...
        "hasData", false);
end
