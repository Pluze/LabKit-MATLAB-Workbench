function layout = filePanel(id, labelText, varargin)
%FILEPANEL Create a file input panel layout node.
%
% Usage:
%   layout = labkit.ui.layout.filePanel(id, labelText)
%   layout = labkit.ui.layout.filePanel(id, labelText, Name=Value)
%
% Inputs:
%   id - Text scalar used to identify the panel. It must be a valid MATLAB
%       variable name and unique within the workbench.
%   labelText - Text displayed in the panel title.
%
% Name-Value Arguments:
%   mode - "multi" accumulates files and provides file, folder, recursive
%       folder, remove, and clear actions. "single" shows one chooser and
%       replaces the previous file. Default: "multi".
%   filters - uigetfile-style filter cell array used by file selection and
%       folder scans. Default: {'*.*','All files'}.
%   selectionMode - List selection mode in a multi panel: "single" or
%       "multiple". Default: "single".
%   maxFiles - Positive maximum number of retained entries. Inf has no limit.
%       Single mode always retains one file. Default: Inf.
%   folderWarningThreshold - Nonnegative match count above which a folder scan
%       asks for confirmation. Default: 500.
%   showStatus - Logical value controlling the count/status box in multi mode.
%       Default: true.
%   startPath - Preferred initial file-dialog folder. A missing or unsafe path
%       falls back to the last LabKit input folder or the user's home folder.
%   chooseLabel - File button text. Default: "Add..." in multi mode and
%       "Choose..." in single mode.
%   folderLabel - Direct-folder button text. Default: "Add folder".
%   recursiveFolderLabel - Recursive-folder button text. Default:
%       "Add folder tree".
%   removeLabel - Remove button text. Default: "Remove selected".
%   clearLabel - Clear button text. Default: "Clear".
%   emptyText - Text shown when no files are loaded. Default:
%       "No files loaded".
%   onChoose - Callback called as onChoose(control,event) after files are added.
%   onRemove - Callback called after the selected entries are removed.
%   onClear - Callback called after every entry is removed.
%   onSelectionChange - Callback called when list selection changes.
%
% Callback Event Fields:
%   action - "choose", "remove", "clear", or "select".
%   files - Complete file-entry array after the action.
%   selectedFiles - Currently selected entries after the action.
%   value - Same value as selectedFiles.
%   addedFiles - Entries added by a choose action.
%   removedFiles - Entries removed by a remove or clear action.
%
% File Entry Fields:
%   id - Stable entry ID generated by the panel unless supplied by the app.
%   index - One-based position in the current file list.
%   path - Full selected file path.
%   name - File name and extension.
%   displayName - User-facing label; defaults to name.
%   status - Optional app-authored status text shown with the file label.
%
% Outputs:
%   layout - Scalar filePanel node with kind, id, props, children, and slots
%       fields.
%
% Description:
%   Multi-file selection uses one native file dialog and therefore returns
%   files from one folder. Folder actions cover the other common cases: direct
%   children only or all matching files recursively. Cancelling any chooser
%   leaves the current list unchanged. Files beyond maxFiles are discarded in
%   selection order.
%
% Errors:
%   labkit:ui:layout:InvalidFilePanelMode or
%   InvalidFilePanelSelectionMode - A mode label is unsupported.
%   labkit:ui:layout:InvalidFilePanelMaxFiles or
%   InvalidFilePanelWarningThreshold - A numeric limit is invalid.
%   labkit:ui:layout:InvalidId, InvalidOptions, or InvalidOptionName - id or
%   Name-value syntax is malformed.
%
% Typical Call:
%   files = labkit.ui.layout.filePanel("images", "Images", ...
%       "filters", {'*.png;*.tif','Images'}, "selectionMode", "multiple");
%
% See also labkit.ui.layout.section

    props = optionStruct(varargin);
    props.label = char(string(labelText));
    props.mode = char(string(optionValue(props, 'mode', 'multi')));
    validateMode(props.mode);
    props.selectionMode = char(string(optionValue(props, ...
        'selectionMode', 'single')));
    validateSelectionMode(props.selectionMode);
    props.maxFiles = optionValue(props, 'maxFiles', Inf);
    validateMaxFiles(props.maxFiles);
    props.folderWarningThreshold = optionValue(props, ...
        'folderWarningThreshold', 500);
    validateWarningThreshold(props.folderWarningThreshold);
    props.showStatus = logical(optionValue(props, 'showStatus', true));
    layout = makeLayoutNode('filePanel', id, props, {}, struct());
end

function validateMode(mode)
    allowed = {'multi', 'single'};
    if ~any(strcmp(mode, allowed))
        error('labkit:ui:layout:InvalidFilePanelMode', ...
            'Unsupported filePanel mode "%s".', mode);
    end
end

function validateSelectionMode(mode)
    allowed = {'single', 'multiple'};
    if ~any(strcmp(mode, allowed))
        error('labkit:ui:layout:InvalidFilePanelSelectionMode', ...
            'Unsupported filePanel selectionMode "%s".', mode);
    end
end

function validateMaxFiles(value)
    if ~(isnumeric(value) && isscalar(value) && value >= 1)
        error('labkit:ui:layout:InvalidFilePanelMaxFiles', ...
            'filePanel maxFiles must be a positive scalar.');
    end
end

function validateWarningThreshold(value)
    if ~(isnumeric(value) && isscalar(value) && isfinite(value) && value >= 0)
        error('labkit:ui:layout:InvalidFilePanelWarningThreshold', ...
            'filePanel folderWarningThreshold must be a nonnegative scalar.');
    end
end

function value = optionValue(opts, name, defaultValue)
    value = defaultValue;
    if isfield(opts, name)
        value = opts.(name);
    end
end
