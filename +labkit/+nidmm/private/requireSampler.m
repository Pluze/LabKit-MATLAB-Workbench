function state = requireSampler(sampler)
% Validate the opaque token returned by labkit.nidmm.startSampling.
if ~(isstruct(sampler) && isscalar(sampler) && ...
        isfield(sampler, "Type") && ...
        string(sampler.Type) == "labkit.nidmm.sampler" && ...
        isfield(sampler, "State") && isa(sampler.State, "containers.Map"))
    error("labkit:nidmm:InvalidSampler", ...
        "Expected a sampler returned by labkit.nidmm.startSampling.");
end
state = sampler.State;
end
